# tK-countassert.py -- TRAIN K fixup helper: the silent-duplication / silent-subtraction asserts on files every seat
# merged CLEANLY (merge-hazards: a clean merge is exactly when duplication hides). READ-ONLY: git objects only.
#
#   python tK-countassert.py regs  <repo> <base> <head>   # PRERES-K1 (go2cs-src.projitems) + PRERES-K3 (go2cs.slnx and
#                                                         # the 4 BehavioralTests *Tests.cs registration files)
#   python tK-countassert.py nuget <repo> <base> <head>   # PRERES-K2 (src/push-nuget.ps1: both seats' lines present)
#
# THE PREDICTION is taken from the assembled union's own history, not from the merged file: walk the FIRST-PARENT
# chain base..head; every commit on it is a seat merge M with parents (U, seat). A seat's OWN change to a file is the
# sum of the per-commit diffs of the NON-MERGE commits in U..seat (each against its one parent) -- exactly the commits
# the seat brings that the union did not already hold. That is independent of any merge-base pick: `git diff
# merge-base(U, seat) seat` is NOT, because a criss-cross has more than one best base and plain merge-base picks one
# arbitrarily (at c2-gen-guard's merge 0aef70f524, `merge-base --all` returns f819887fa3 AND 272afeef93; from the
# latter the seat reads +7/+8/+21x4 on these files -- TRAIN J's own inserts -- from the former projitems +1, which is
# right only because S1 touches none of them). A MERGE commit inside U..seat (c2-gen-guard stacking S1; r-hop-
# population-gen's S4 landing merge) contributes nothing of its own only if it is clean on the file, so its combined
# diff (`diff-tree --cc`) for the file must be EMPTY; an evil merge on a counted file is unmodeled and fails.
# Keep-every-side then predicts: lines(head) = lines(base) + sum(added - deleted), and the same for the registration
# keys. A SECOND derivation, made by hand at authoring time (each seat's diff from merge-base(seat, f819887fa3),
# 2026-09-30 -- for c2-gen-guard that base is f819887fa3, whose diff also carries S1's delta, harmless here because S1
# touches none of these files), is carried as AUTHORED below and must agree; a disagreement aborts.
# Exit: 0 pass, 3 fail.
