def git(repo, *a):
    r = subprocess.run(["git", "-C", repo] + list(a), capture_output=True)
    if r.returncode != 0:
        raise SystemExit(f"git {' '.join(a)} failed: {r.stderr.decode('utf-8', 'replace').strip()}")
    return r.stdout.decode("utf-8", "surrogateescape")


def blob(repo, rev, path):
    r = subprocess.run(["git", "-C", repo, "show", f"{rev}:{path}"], capture_output=True)
    return r.stdout.decode("utf-8", "surrogateescape").replace("\r\n", "\n") if r.returncode == 0 else ""


def chain(repo, base, head):
    """The seat merges on the first-parent chain, oldest first: (merge, U, seat, [(commit, [parents])] of U..seat)."""
    out = []
    for line in git(repo, "rev-list", "--first-parent", "--reverse", "--parents", f"{base}..{head}").split("\n"):
        parts = line.split()
        if not parts:
            continue
        if len(parts) != 3:
            raise SystemExit(f"first-parent commit {parts[0][:10]} is not a two-parent seat merge ({len(parts) - 1} parents)")
        m, u, s = parts
        own = [(x[0], x[1:]) for x in (ln.split() for ln in git(repo, "rev-list", "--reverse", "--parents", f"{u}..{s}").split("\n")) if x]
        if not own:
            raise SystemExit(f"seat merge {m[:10]}: {u[:10]}..{s[:10]} is empty (the seat was already in the union)")
        out.append((m, u, s, own))
    return out


def seat_delta(repo, s, own, path, rxc=None, lines=False):
    """The seat's OWN change to path: (added, deleted, key delta, Counter of line deltas) summed over its non-merge
    commits; None when none of them touches path. A merge in U..seat must be clean on path (empty --cc)."""
    a = d = kd = 0
    ld, hit = Counter(), False
    for c, ps in own:
        if len(ps) != 1:
            cc = git(repo, "diff-tree", "--cc", "--no-commit-id", "-r", c, "--", path).strip()
            if cc:
                raise SystemExit(f"seat {s[:10]}: merge {c[:10]} changes {path} beyond its parents (an evil merge); "
                                 f"the per-commit sum cannot model it -- subtract it by hand")
            continue
        ns = git(repo, "diff-tree", "--no-commit-id", "--numstat", "-r", c, "--", path).strip()
        if not ns:
            continue
        f = ns.split("\t")
        if f[0] == "-":
            raise SystemExit(f"seat {s[:10]}: commit {c[:10]} reads {path} as binary")
        hit = True
        a, d = a + int(f[0]), d + int(f[1])
        if rxc is not None or lines:
            now, was = blob(repo, c, path), blob(repo, ps[0], path)
            if rxc is not None:
                kd += len(rxc.findall(now)) - len(rxc.findall(was))
            if lines:
                ld.update(Counter(now.split("\n")))
                ld.subtract(Counter(was.split("\n")))
    return (a, d, kd, ld) if hit else None


def nlines(t):
    return t.count("\n")


def regs(repo, base, head):
    ch = chain(repo, base, head)
    bad = []
    print(f"REGS chain: {len(ch)} seat merges on the first-parent chain {base[:10]}..{head[:10]}")
    for path, (rx, auth_base, auth_union) in REGS.items():
        rxc = re.compile(rx)
        b = blob(repo, base, path)
        lines, keys = nlines(b), len(rxc.findall(b))
        touched = []
        for m, u, s, own in ch:
            sd = seat_delta(repo, s, own, path, rxc=rxc)
            if sd is None:
                continue
            a, d, kd, _ = sd
            lines += a - d
            keys += kd
            touched.append(f"{s[:10]}(+{a}/-{d},keys{kd:+d})")
        h = blob(repo, head, path)
        got_lines, got_keys = nlines(h), len(rxc.findall(h))
        dups = sorted(k for k, n in Counter(rxc.findall(h)).items() if n > 1)
        ok = (got_lines, got_keys) == (lines, keys) == auth_union and (nlines(b), len(rxc.findall(b))) == auth_base and not dups
        print(f"  {'OK  ' if ok else 'FAIL'} {path}: base {nlines(b)}/{len(rxc.findall(b))} + {len(touched)} seat(s) "
              f"-> predicted {lines}/{keys}, authored {auth_union[0]}/{auth_union[1]}, union {got_lines}/{got_keys} "
              f"(lines/keys), duplicate keys {len(dups)}")
        print(f"       seats: {' '.join(touched) if touched else '(none)'}")
        for k in dups[:10]:
            print(f"       DUPLICATE KEY: {k}")
        if not ok:
            bad.append(path)
    print("REGS PASS" if not bad else f"REGS FAIL: {len(bad)} file(s): {' '.join(bad)}")
    return 0 if not bad else 3


def nuget(repo, base, head):
    ch = chain(repo, base, head)
    b, h = blob(repo, base, NUGET), blob(repo, head, NUGET)
    bad = []
    # (1) the line count, predicted from the chain exactly as regs() does
    lines, touched, expect = nlines(b), [], Counter()
    for m, u, s, own in ch:
        sd = seat_delta(repo, s, own, NUGET, lines=True)
        if sd is None:
            continue
        a, d, _, ld = sd
        lines += a - d
        touched.append(f"{s[:10]}(+{a}/-{d})")
        # (2) every non-blank line the seat's own commits changed must occur in the union exactly as often as base +
        # every seat's own delta of that line predicts (catches a lost hunk AND a doubled one)
        for ln, dl in ld.items():
            if ln.strip() and dl:
                expect[ln] += dl
    hc, bc = Counter(h.split("\n")), Counter(b.split("\n"))
    wrong = [ln for ln, dlt in expect.items() if hc[ln] != bc[ln] + dlt]
    print(f"NUGET seats touching {NUGET}: {' '.join(touched) if touched else '(none)'}")
    print(f"  lines: base {nlines(b)} predicted {lines} authored {NUGET_AUTHORED[1]} union {nlines(h)}")
    if not (nlines(h) == lines == NUGET_AUTHORED[1] and nlines(b) == NUGET_AUTHORED[0]):
        bad.append("line count")
    print(f"  changed-line multiset: {len(expect)} distinct lines checked, {len(wrong)} off")
    for ln in wrong[:15]:
        print(f"    OFF: union has {hc[ln]}, predicted {bc[ln] + expect[ln]}: {ln.strip()[:140]}")
    if wrong:
        bad.append("changed-line multiset")
    # (3) the named tokens, per seat
    for seat, toks in NUGET_TOKENS.items():
        for tok, want in toks:
            n = h.count(tok)
            print(f"  {'OK  ' if n == want else 'FAIL'} [{seat}] x{n} (want {want}): {tok.strip()[:110]}")
            if n != want:
                bad.append(f"token {tok.strip()[:40]}")
    # (4) the param block reads VerifyOnly then VersionSuffix, closed once
    pb = re.search(r"\nparam\(\n(.*?)\n\)\n", h, re.S)
    tail = [x.strip() for x in pb.group(1).split("\n")][-2:] if pb else []
    okpb = tail == ["[switch]$VerifyOnly,", "[string]$VersionSuffix"]
    print(f"  {'OK  ' if okpb else 'FAIL'} param block tail: {tail}")
    if not okpb:
        bad.append("param block")
    print("NUGET PASS" if not bad else f"NUGET FAIL: {'; '.join(bad)}")
    return 0 if not bad else 3


