#!/usr/bin/env python3
# Emits the go.arrays family for a set of lengths: one public generic wrapper per length, holding a private nested
# [InlineArray(N)] storage, with an element indexer, the constant length and Go equality. No Span, slice or address
# member (7.6.1). Usage: genfamily.py <out.cs> <spec>, spec = "201" | "1-4096" | "1-256,480,488,..."
import sys
out, spec = sys.argv[1], sys.argv[2]
constraint = ' where T : unmanaged' if len(sys.argv) > 3 and sys.argv[3] == 'unmanaged' else ''
lengths = set()
for part in spec.split(','):
    if '-' in part:
        a, b = part.split('-'); lengths.update(range(int(a), int(b) + 1))
    else:
        lengths.add(int(part))
w = open(out, 'w')
w.write('''// <auto-generated/> go.arrays family, lengths: %s (%d types)
#nullable enable
using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Diagnostics.CodeAnalysis;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;

namespace go.arrays;

[EditorBrowsable(EditorBrowsableState.Never)]
public static class GoArrays
{
    [DoesNotReturn, MethodImpl(MethodImplOptions.NoInlining)]
    public static void ThrowIndex(int index, int length) => throw new IndexOutOfRangeException($"index out of range [{index}] with length {length}");

    public static bool Equal<T>(ref T a, ref T b, int length)
    {
        EqualityComparer<T> comparer = EqualityComparer<T>.Default;
        for (int i = 0; i < length; i++)
            if (!comparer.Equals(Unsafe.Add(ref a, i), Unsafe.Add(ref b, i)))
                return false;
        return true;
    }

    public static int Hash<T>(ref T a, int length)
    {
        HashCode hash = new();
        for (int i = 0; i < length; i++)
            hash.Add(Unsafe.Add(ref a, i));
        return hash.ToHashCode();
    }
}
''' % (spec, len(lengths)))
for n in sorted(lengths):
    w.write('''
[EditorBrowsable(EditorBrowsableState.Never)]
public struct array{n}<T> : IEquatable<array{n}<T>>{c}
{{
    [InlineArray({n})] private struct Storage {{ private T m_element; }}

    private Storage m_storage;

    public const int Length = {n};

    [UnscopedRef]
    public ref T this[int index]
    {{
        get
        {{
            if ((uint)index >= {n})
                GoArrays.ThrowIndex(index, {n});
            return ref Unsafe.Add(ref Unsafe.As<Storage, T>(ref m_storage), index);
        }}
    }}

    public bool Equals(array{n}<T> other) => GoArrays.Equal(ref Unsafe.As<Storage, T>(ref m_storage), ref Unsafe.As<Storage, T>(ref other.m_storage), {n});
    public override bool Equals(object? obj) => obj is array{n}<T> other && Equals(other);
    public override int GetHashCode() => GoArrays.Hash(ref Unsafe.As<Storage, T>(ref m_storage), {n});
    public static bool operator ==(array{n}<T> left, array{n}<T> right) => left.Equals(right);
    public static bool operator !=(array{n}<T> left, array{n}<T> right) => !left.Equals(right);
}}
'''.format(n=n, c=constraint))
w.close()
print(len(lengths))
