using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace go2cs;

/// <summary>
/// Generates go.arrays.dll's inline-array family: <c>array1&lt;T&gt;</c> ... <c>array4096&lt;T&gt;</c>, one per Go array
/// length the 4 KiB cap admits (docs/phase4/DESIGN-array-value-storage.md, 7.7).
/// </summary>
/// <remarks>
/// <para>
/// Each member wraps a private <c>[InlineArray(N)]</c> storage. It exposes only an element indexer (by <c>int</c>,
/// <c>nint</c> and <c>ulong</c>, golib's <c>array&lt;T&gt;</c> overloads, so an unsigned Go index binds) and the constant
/// length: C# converts any <c>[InlineArray]</c> type to <c>Span&lt;T&gt;</c>, so the wrapper is what makes an
/// unanalysed face (a slice, an address, a Span) a compile error rather than a silent copy (7.6.1). It implements Go
/// equality itself: the default equality of an inline array throws, and that of a holder is order-dependent and wrong
/// (7.6.5).
/// </para>
/// <para>
/// <c>where T : unmanaged</c> keeps a rooted Native AOT publish of the family small (7.7.2) and matches I0, which admits
/// only unmanaged elements. Every member carries <c>[go.golib.GoInlineArray(N)]</c>, the attribute golib reads, so golib never
/// names a family type and a program that does not opt in never loads go.arrays.dll.
/// </para>
/// <para>
/// The generator acts only in the compilation named go.arrays, and its output depends on nothing but
/// <see cref="MaxLength"/> and <see cref="ChunkSize"/>, so it is byte-stable from run to run.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class ArrayFamilyGenerator : IIncrementalGenerator
{
    /// <summary>The family's assembly; the generator emits into no other compilation.</summary>
    internal const string FamilyAssemblyName = "go.arrays";

    /// <summary>The longest member: every length the 4 KiB per-array cap admits for a one-byte element.</summary>
    internal const int MaxLength = 4096;

    /// <summary>Members per generated file.</summary>
    internal const int ChunkSize = 64;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<bool> isFamily = context.CompilationProvider.Select(static (compilation, _) => compilation.AssemblyName == FamilyAssemblyName);

        context.RegisterSourceOutput(isFamily, static (output, generate) =>
        {
            if (!generate)
                return;

            for (int first = 1; first <= MaxLength; first += ChunkSize)
            {
                int last = first + ChunkSize - 1;

                if (last > MaxLength)
                    last = MaxLength;

                output.AddSource(ChunkHintName(first, last), SourceText.From(Chunk(first, last), Encoding.UTF8));
            }
        });
    }

    /// <summary>The hint name of the file holding lengths <paramref name="first"/> to <paramref name="last"/>.</summary>
    internal static string ChunkHintName(int first, int last) =>
        string.Format(CultureInfo.InvariantCulture, "array{0:D4}-{1:D4}.g.cs", first, last);

    /// <summary>The source of the members of lengths <paramref name="first"/> to <paramref name="last"/>.</summary>
    internal static string Chunk(int first, int last)
    {
        StringBuilder source = new();

        source.Append("// <auto-generated/>\n");
        source.Append("// go.arrays inline-array family, lengths ").Append(first.ToString(CultureInfo.InvariantCulture))
            .Append('-').Append(last.ToString(CultureInfo.InvariantCulture)).Append(" (go2cs-arrays-gen).\n");
        source.Append("#nullable enable\n\n");
        source.Append("namespace go.arrays;\n");

        for (int length = first; length <= last; length++)
            AppendMember(source, length);

        return source.ToString();
    }

    private static void AppendMember(StringBuilder source, int length)
    {
        string n = length.ToString(CultureInfo.InvariantCulture);
        string name = "array" + n;

        source.Append('\n');
        source.Append("/// <summary>A Go array value <c>[").Append(n).Append("]T</c>, held inline in its owner.</summary>\n");
        source.Append("[global::go.golib.GoInlineArray(").Append(n).Append(")]\n");
        source.Append("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\n");
        source.Append("public struct ").Append(name).Append("<T> : global::go.IGoEquatable, global::System.IEquatable<")
            .Append(name).Append("<T>> where T : unmanaged\n");
        source.Append("{\n");
        source.Append("    [global::System.Runtime.CompilerServices.InlineArray(").Append(n).Append(")]\n");
        source.Append("    private struct Storage { private T m_element; }\n\n");
        source.Append("    private Storage m_storage;\n\n");
        source.Append("    /// <summary>The Go array's length.</summary>\n");
        source.Append("    public const int Length = ").Append(n).Append(";\n\n");
        source.Append("    /// <summary>The element at <paramref name=\"index\"/>; Go's index panic when it is out of range.</summary>\n");
        source.Append("    [global::System.Diagnostics.CodeAnalysis.UnscopedRef]\n");
        source.Append("    public ref T this[int index]\n");
        source.Append("    {\n");
        source.Append("        get\n");
        source.Append("        {\n");
        source.Append("            if ((uint)index >= ").Append(n).Append("u)\n");
        source.Append("                throw global::go.golib.RuntimeErrorPanic.IndexOutOfRange(index, ").Append(n).Append(");\n\n");
        source.Append("            return ref global::System.Runtime.CompilerServices.Unsafe.Add(ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref m_storage), index);\n");
        source.Append("        }\n");
        source.Append("    }\n\n");
        source.Append("    /// <summary>The element at <paramref name=\"index\"/>; Go's index panic when it is out of range.</summary>\n");
        source.Append("    [global::System.Diagnostics.CodeAnalysis.UnscopedRef]\n");
        source.Append("    public ref T this[nint index]\n");
        source.Append("    {\n");
        source.Append("        get\n");
        source.Append("        {\n");
        source.Append("            if ((nuint)index >= ").Append(n).Append("u)\n");
        source.Append("                throw global::go.golib.RuntimeErrorPanic.IndexOutOfRange(index, ").Append(n).Append(");\n\n");
        source.Append("            return ref global::System.Runtime.CompilerServices.Unsafe.Add(ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref m_storage), index);\n");
        source.Append("        }\n");
        source.Append("    }\n\n");
        source.Append("    /// <summary>The element at an unsigned <paramref name=\"index\"/>, checked before any narrowing.</summary>\n");
        source.Append("    [global::System.Diagnostics.CodeAnalysis.UnscopedRef]\n");
        source.Append("    public ref T this[ulong index]\n");
        source.Append("    {\n");
        source.Append("        get\n");
        source.Append("        {\n");
        source.Append("            if (index >= ").Append(n).Append("ul)\n");
        source.Append("                throw global::go.golib.RuntimeErrorPanic.IndexOutOfRange(index, ").Append(n).Append(");\n\n");
        source.Append("            return ref global::System.Runtime.CompilerServices.Unsafe.Add(ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref m_storage), (nint)index);\n");
        source.Append("        }\n");
        source.Append("    }\n\n");
        source.Append("    public bool Equals(").Append(name).Append("<T> other) => global::go.arrays.InlineArrays.Equal(ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref m_storage), ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref other.m_storage), ").Append(n).Append(");\n\n");
        source.Append("    public override bool Equals(object? obj) => obj is ").Append(name).Append("<T> other && Equals(other);\n\n");
        source.Append("    bool global::go.IGoEquatable.GoEquals(object? other) => other is ").Append(name).Append("<T> value && Equals(value);\n\n");
        source.Append("    public override int GetHashCode() => global::go.arrays.InlineArrays.Hash(ref global::System.Runtime.CompilerServices.Unsafe.As<Storage, T>(ref m_storage), ").Append(n).Append(");\n\n");
        source.Append("    public static bool operator ==(").Append(name).Append("<T> left, ").Append(name).Append("<T> right) => left.Equals(right);\n\n");
        source.Append("    public static bool operator !=(").Append(name).Append("<T> left, ").Append(name).Append("<T> right) => !left.Equals(right);\n");
        source.Append("}\n");
    }
}
