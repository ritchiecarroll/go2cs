using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace go2cs;

/// <summary>
/// Writes the accessor of a Go package var built on its FIRST READ (docs/DESIGN-lazy-static-data.md). The converter
/// writes the var's declaration as it would an eager one, inside a holder class named for the var:
/// <c>[GoLazy] partial class lazyᴛ_Lu { internal static ж&lt;RangeTable&gt; _Lu = Ꮡ(new RangeTable(…)); }</c>. The
/// holder's field initializer runs when the CLR first initializes the holder, which is the var's first read; this
/// generator gives the package class the var's <c>ref</c> accessor under its Go name, with the field's accessibility, so
/// every use site reads as it did:
/// <c>internal static ref ж&lt;RangeTable&gt; _Lu => ref lazyᴛ_Lu._Lu;</c>.
/// </summary>
/// <remarks>
/// <para>
/// <c>[GoLazy(Initial = true)]</c> marks an EXPORTED var a lazy initializer of its package reads. An importer may assign
/// it before that initializer runs, where Go's init-time build saw its initial value, so the generator keeps the initial
/// value apart: <c>internal static readonly T initial;</c>, set in the holder's explicit static constructor, which C# runs
/// after every field initializer of the holder in all its parts. The converter has lazy initializers read
/// <c>lazyᴛX.initial</c>.
/// </para>
/// <para>
/// A var whose address is taken keeps its heap box: the holder holds the box,
/// <c>[GoLazy] partial class lazyᴛX { internal static readonly ж&lt;T&gt; ᏑX = new StaticBox&lt;T&gt;(…); }</c>, the converter
/// keeps the var's <c>ref T X => ref ((StaticBox&lt;T&gt;)ᏑX).ValueSlot</c> property beside it, and the generator writes
/// the box accessor, <c>ж&lt;T&gt; ᏑX => lazyᴛX.ᏑX</c>: the box is readonly, so the accessor returns it rather than a
/// writable ref to it. <c>&amp;X</c> and <c>X</c> then read one box, built by the first of either.
/// </para>
/// <para>
/// A holder that does not hold exactly one static field named for it (or for its box) is refused by name (GO2CS0009), and
/// nothing is generated for it.
/// </para>
/// </remarks>
[Generator]
public class LazyHolderGenerator : ISourceGenerator
{
    internal const string HolderPrefix = "lazyᴛ";

    // The box of a var whose address is taken, as the converter names it (AddressPrefix): `&X` reads ᏑX.
    internal const string BoxPrefix = "Ꮡ";

    public void Initialize(GeneratorInitializationContext context)
    {
        context.RegisterForSyntaxNotifications(() => new LazyHolderFinder());
    }

    public void Execute(GeneratorExecutionContext context)
    {
        if (context.SyntaxReceiver is not LazyHolderFinder { Holders.Count: > 0 } finder)
            return;

        HashSet<string> hintNames = new(System.StringComparer.OrdinalIgnoreCase);

        foreach (IGrouping<SyntaxTree, ClassDeclarationSyntax> file in finder.Holders.GroupBy(holder => holder.SyntaxTree))
        {
            List<(ClassDeclarationSyntax holder, FieldDeclarationSyntax field, string name, bool initial)> holders = [];

            foreach (ClassDeclarationSyntax holder in file)
            {
                if (Refusal(holder, out FieldDeclarationSyntax? field, out string name) is { } refusal)
                {
                    context.ReportDiagnostic(Diagnostic.Create(GeneratorDiagnostics.MalformedLazyHolder, holder.Identifier.GetLocation(), holder.Identifier.ValueText, name, refusal));
                    continue;
                }

                holders.Add((holder, field!, name, IsInitial(holder)));
            }

            if (holders.Count == 0)
                continue;

            CompilationUnitSyntax unit = (CompilationUnitSyntax)file.Key.GetRoot();
            StringBuilder source = new();
            source.Append("// <auto-generated/>\r\n#nullable enable\r\n");

            foreach (ExternAliasDirectiveSyntax alias in unit.Externs)
                source.Append(alias.WithoutTrivia().ToFullString()).Append("\r\n");

            // A `global using` is already in scope everywhere in the compilation; only the file's own directives are copied,
            // so the field's type text resolves here as it does in the source.
            foreach (UsingDirectiveSyntax usingDirective in unit.Usings.Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None)))
                source.Append(usingDirective.WithoutTrivia().ToFullString()).Append("\r\n");

            // The holders of one containing type share its namespace and type chain, written outermost first as the source
            // declares it (a converted file's holders all sit in its package class).
            foreach (IGrouping<SyntaxNode?, (ClassDeclarationSyntax holder, FieldDeclarationSyntax field, string name, bool initial)> group in holders.GroupBy(entry => entry.holder.Parent))
            {
                List<SyntaxNode> chain = group.First().holder.Ancestors().Where(node => node is BaseNamespaceDeclarationSyntax or TypeDeclarationSyntax).Reverse().ToList();
                int depth = 0;

                foreach (SyntaxNode node in chain)
                {
                    string indent = new(' ', depth * 4);

                    if (node is BaseNamespaceDeclarationSyntax ns)
                    {
                        source.Append($"{indent}namespace {ns.Name}\r\n{indent}{{\r\n");

                        foreach (UsingDirectiveSyntax usingDirective in ns.Usings)
                            source.Append(indent).Append("    ").Append(usingDirective.WithoutTrivia().ToFullString()).Append("\r\n");
                    }
                    else if (node is TypeDeclarationSyntax type)
                    {
                        source.Append($"{indent}partial {type.Keyword.ValueText} {type.Identifier.ValueText}{type.TypeParameterList?.WithoutTrivia().ToFullString()}\r\n{indent}{{\r\n");
                    }

                    depth++;
                }

                string memberIndent = new(' ', depth * 4);

                foreach ((ClassDeclarationSyntax holder, FieldDeclarationSyntax field, string name, bool initial) in group)
                {
                    string type = field.Declaration.Type.WithoutTrivia().ToFullString();
                    string holderName = holder.Identifier.ValueText;
                    string fieldName = field.Declaration.Variables[0].Identifier.ValueText;

                    // The var's field, or its box (ᏑX) for a var whose address is taken: the accessor takes the field's name. A
                    // box is readonly, which a writable ref cannot return (CS8161), so its accessor returns the box itself.
                    if (field.Modifiers.Any(SyntaxKind.ReadOnlyKeyword))
                        source.Append($"{memberIndent}{Accessibility(field)} static {type} {fieldName} => {holderName}.{fieldName};\r\n");
                    else
                        source.Append($"{memberIndent}{Accessibility(field)} static ref {type} {fieldName} => ref {holderName}.{fieldName};\r\n");

                    if (initial)
                        source.Append($"{memberIndent}partial class {holderName} {{ internal static readonly {type} initial; static {holderName}() {{ initial = {name}; }} }}\r\n");
                }

                for (int level = depth - 1; level >= 0; level--)
                    source.Append(new string(' ', level * 4)).Append("}\r\n");
            }

            string hintName = $"{System.IO.Path.GetFileNameWithoutExtension(file.Key.FilePath)}.lazy-holders.g.cs";

            for (int suffix = 2; !hintNames.Add(hintName); suffix++)
                hintName = $"{System.IO.Path.GetFileNameWithoutExtension(file.Key.FilePath)}.lazy-holders{suffix}.g.cs";

            context.AddSource(hintName, source.ToString());
        }
    }

    // Why the holder cannot be completed, or null when it can: a nested partial class named lazyᴛX holding exactly one
    // static field, X, or X's box ᏑX for a var whose address is taken. `name` is X, as far as the holder's name says.
    private static string? Refusal(ClassDeclarationSyntax holder, out FieldDeclarationSyntax? field, out string name)
    {
        field = null;
        string holderName = holder.Identifier.ValueText;
        name = holderName.StartsWith(HolderPrefix, System.StringComparison.Ordinal) ? holderName.Substring(HolderPrefix.Length) : "";

        if (name.Length == 0)
            return $"its name does not start with '{HolderPrefix}' followed by the var's name";

        if (holder.Parent is not TypeDeclarationSyntax)
            return "it is not nested in the package class whose var it holds";

        if (!holder.Modifiers.Any(SyntaxKind.PartialKeyword))
            return "it is not partial";

        if (holder.TypeParameterList is not null)
            return "it is generic";

        if (holder.Members.Count != 1 || holder.Members[0] is not FieldDeclarationSyntax only)
            return $"it holds {holder.Members.Count} member(s), not one field";

        if (!only.Modifiers.Any(SyntaxKind.StaticKeyword))
            return "its field is not static";

        if (only.Declaration.Variables.Count != 1)
            return "its field declares more than one variable";

        string fieldName = only.Declaration.Variables[0].Identifier.ValueText;
        bool box = fieldName == BoxPrefix + name;

        if (fieldName != name && !box)
            return $"its field is named '{fieldName}'";

        // A var whose address is taken is never read by a lazy initializer, so nothing reads a snapshot of it.
        if (box && IsInitial(holder))
            return "it holds the var's box, which keeps no initial snapshot";

        field = only;
        return null;
    }

    // The accessor takes the field's declared accessibility, so an exported var is public and an unexported one internal.
    private static string Accessibility(FieldDeclarationSyntax field)
    {
        string accessibility = string.Join(" ", field.Modifiers
            .Where(modifier => modifier.IsKind(SyntaxKind.PublicKeyword) || modifier.IsKind(SyntaxKind.InternalKeyword) ||
                               modifier.IsKind(SyntaxKind.PrivateKeyword) || modifier.IsKind(SyntaxKind.ProtectedKeyword))
            .Select(modifier => modifier.ValueText));

        return accessibility.Length > 0 ? accessibility : "private";
    }

    // [GoLazy(Initial = true)]
    private static bool IsInitial(ClassDeclarationSyntax holder) =>
        holder.AttributeLists.SelectMany(list => list.Attributes).Where(LazyHolderFinder.IsGoLazy)
            .SelectMany(attribute => attribute.ArgumentList?.Arguments ?? default)
            .Any(argument => argument.NameEquals?.Name.Identifier.ValueText == "Initial" && argument.Expression.IsKind(SyntaxKind.TrueLiteralExpression));
}

/// <summary>Collects every class declaration carrying a <c>[GoLazy]</c> attribute, matched by name as go2cs-gen matches its other markers.</summary>
internal sealed class LazyHolderFinder : ISyntaxReceiver
{
    public List<ClassDeclarationSyntax> Holders { get; } = [];

    public void OnVisitSyntaxNode(SyntaxNode syntaxNode)
    {
        if (syntaxNode is ClassDeclarationSyntax holder && holder.AttributeLists.SelectMany(list => list.Attributes).Any(IsGoLazy))
            Holders.Add(holder);
    }

    internal static bool IsGoLazy(AttributeSyntax attribute)
    {
        string name = attribute.Name switch
        {
            QualifiedNameSyntax qualified => qualified.Right.Identifier.ValueText,
            AliasQualifiedNameSyntax aliased => aliased.Name.Identifier.ValueText,
            SimpleNameSyntax simple => simple.Identifier.ValueText,
            _ => ""
        };

        return name is "GoLazy" or "GoLazyAttribute";
    }
}
