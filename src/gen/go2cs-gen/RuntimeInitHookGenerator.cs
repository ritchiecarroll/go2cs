using Microsoft.CodeAnalysis;

namespace go2cs;

/// <summary>
/// Gives every converted EXECUTABLE that references the converted <c>runtime</c> package a lazy way to initialize it:
/// a module initializer that installs golib's <c>CrashReport.RuntimeInitializer</c>.
/// </summary>
/// <remarks>
/// <para>
/// runtime installs the crash and fatal-error traceback renderers from its own module initializer, and a module
/// initializer runs only when its module is first touched. A program with no imports never touches runtime, so an
/// unrecovered panic printed <c>panic: &lt;value&gt;</c> and no <c>goroutine 1 [running]:</c> block at all, where Go
/// always prints one (C2, 2026-10-24).
/// </para>
/// <para>
/// The hook is installed eagerly and, under the JIT, RUN lazily: golib invokes it only from a report that finds no
/// renderer, so a program that never crashes never loads runtime for it. The <c>typeof</c> in its body keeps runtime's
/// type rooted for trimming and Native AOT; under Native AOT that keeps runtime in the image and ILC runs its module
/// initializer at startup, so runtime is kept and initialized for programs that did not otherwise load it (C1's
/// review, measured). Go's runtime is always present, so this costs size, never behavior.
/// </para>
/// </remarks>
[Generator]
public class RuntimeInitHookGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context) { }

    public void Execute(GeneratorExecutionContext context)
    {
        Compilation compilation = context.Compilation;

        // An executable only: a library's crash is reported by the executable that references it.
        if (compilation.Options.OutputKind is not (OutputKind.ConsoleApplication or OutputKind.WindowsApplication))
            return;

        // runtime as a REFERENCED, public package -- never runtime itself, and nothing when it is absent or ambiguous.
        if (compilation.GetTypeByMetadataName("go.runtime_package") is not { DeclaredAccessibility: Accessibility.Public } runtime ||
            SymbolEqualityComparer.Default.Equals(runtime.ContainingAssembly, compilation.Assembly))
            return;

        // A golib old enough to have no hook gets none.
        if (compilation.GetTypeByMetadataName("go.golib.CrashReport") is not { } crashReport || crashReport.GetMembers("RuntimeInitializer").IsEmpty)
            return;

        context.AddSource("go2cs.runtime-init-hook.g.cs", Source);
    }

    private const string Source =
        "// <auto-generated/>\r\n" +
        "namespace go;\r\n\r\n" +
        "file static class ᴛRuntimeInitHook\r\n" +
        "{\r\n" +
        "    [global::System.Runtime.CompilerServices.ModuleInitializer]\r\n" +
        "    internal static void ᴛInstall() =>\r\n" +
        "        global::go.golib.CrashReport.RuntimeInitializer ??= static () =>\r\n" +
        "            global::System.Runtime.CompilerServices.RuntimeHelpers.RunModuleConstructor(typeof(global::go.runtime_package).Module.ModuleHandle);\r\n" +
        "}\r\n";
}
