using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using static go2cs.Common;

namespace go2cs;

public sealed partial class TwinGenerator
{
    internal sealed partial class Run
    {
        private int m_awaitSites, m_goTwinned, m_goLiterals, m_unrederivable, m_spills, m_refBlocked;

        // One file of twins per source file: each twin sits in its function's own namespace and class, under a
        // #line directive that puts it on the function's own lines, so a trace or a breakpoint reads the source.
        private void Emit()
        {
            HashSet<string> hints = new(StringComparer.OrdinalIgnoreCase);

            foreach (IGrouping<SyntaxTree, Candidate> file in m_ordered.Where(candidate => candidate.Twinned).GroupBy(candidate => candidate.Syntax.SyntaxTree))
            {
                CompilationUnitSyntax unit = (CompilationUnitSyntax)file.Key.GetRoot(Context.CancellationToken);
                StringBuilder source = new();

                source.Append("// <auto-generated/>\r\n#nullable enable annotations\r\n#pragma warning disable\r\n");

                foreach (ExternAliasDirectiveSyntax alias in unit.Externs)
                    source.Append(alias.WithoutTrivia().ToFullString()).Append("\r\n");

                foreach (UsingDirectiveSyntax directive in unit.Usings.Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None)))
                    source.Append(directive.WithoutTrivia().ToFullString()).Append("\r\n");

                foreach (IGrouping<SyntaxNode?, Candidate> group in file.GroupBy(candidate => candidate.Syntax.Parent))
                {
                    List<SyntaxNode> chain = group.First().Syntax.Ancestors().Where(node => node is BaseNamespaceDeclarationSyntax or TypeDeclarationSyntax).Reverse().ToList();
                    string indent = "";

                    foreach (SyntaxNode node in chain)
                    {
                        if (node is BaseNamespaceDeclarationSyntax space)
                        {
                            source.Append(indent).Append("namespace ").Append(space.Name.ToString()).Append("\r\n").Append(indent).Append("{\r\n");

                            foreach (UsingDirectiveSyntax directive in space.Usings)
                                source.Append(indent).Append("    ").Append(directive.WithoutTrivia().ToFullString()).Append("\r\n");
                        }
                        else if (node is TypeDeclarationSyntax type)
                        {
                            string keyword = type is RecordDeclarationSyntax record && !record.ClassOrStructKeyword.IsKind(SyntaxKind.None)
                                ? "record " + record.ClassOrStructKeyword.ValueText
                                : type.Keyword.ValueText;

                            source.Append(indent).Append("partial ").Append(keyword).Append(' ').Append(type.Identifier.Text)
                                .Append(type.TypeParameterList?.WithoutTrivia().ToFullString()).Append("\r\n").Append(indent).Append("{\r\n");
                        }

                        indent += "    ";
                    }

                    foreach (Candidate candidate in group)
                        source.Append(TwinText(candidate, indent));

                    for (int i = chain.Count - 1; i >= 0; i--)
                    {
                        indent = indent.Substring(4);
                        source.Append(indent).Append("}\r\n");
                    }
                }

                string hint = Path.GetFileNameWithoutExtension(file.Key.FilePath) + ".twins.g.cs";
                string unique = hint;

                for (int index = 1; !hints.Add(unique); index++)
                    unique = index + "." + hint;

                Context.AddLineExactSource(GetValidFileName(unique), source.ToString());
            }

            EmitIface();
            EmitEntry();
            EmitReport();
        }

        private string TwinText(Candidate candidate, string indent)
        {
            MethodDeclarationSyntax method = candidate.Syntax;
            SyntaxTree tree = method.SyntaxTree;
            Rewriter rewriter = new(this, Model(tree), method);
            BlockSyntax? body = (BlockSyntax?)rewriter.Visit(method.Body);
            ArrowExpressionClauseSyntax? arrow = (ArrowExpressionClauseSyntax?)rewriter.Visit(method.ExpressionBody);

            candidate.Awaits = rewriter.Awaits;
            m_awaitSites += rewriter.Awaits;
            m_ifaceAwaits += rewriter.IfaceAwaits;
            m_goTwinned += rewriter.GoTwinned;
            m_goLiterals += rewriter.Literals;
            m_unrederivable += rewriter.Unrederivable;
            m_spills += rewriter.Spills;
            m_refBlocked += rewriter.RefBlocked;

            SyntaxToken first = method.Modifiers.Count > 0 ? method.Modifiers[0] : method.ReturnType.GetFirstToken();
            LinePosition start = tree.GetLineSpan(first.Span).StartLinePosition;

            string result = method.ReturnType is PredefinedTypeSyntax predefined && predefined.Keyword.IsKind(SyntaxKind.VoidKeyword)
                ? "global::go.golib.GoTask"
                : "global::go.golib.GoTask<" + method.ReturnType.WithoutTrivia().ToFullString() + ">";

            SyntaxTokenList modifiers = SyntaxFactory.TokenList(method.Modifiers.Where(modifier => !modifier.IsKind(SyntaxKind.PartialKeyword)))
                .Add(SyntaxFactory.Token(SyntaxKind.AsyncKeyword).WithTrailingTrivia(SyntaxFactory.Space));

            MethodDeclarationSyntax twin = method
                .WithAttributeLists(default)
                .WithModifiers(modifiers)
                .WithReturnType(SyntaxFactory.ParseTypeName(result).WithTriviaFrom(method.ReturnType))
                .WithIdentifier(SyntaxFactory.ParseToken(method.Identifier.Text + Suffix).WithLeadingTrivia(method.Identifier.LeadingTrivia).WithTrailingTrivia(method.Identifier.TrailingTrivia))
                .WithBody(body)
                .WithExpressionBody(arrow)
                .WithLeadingTrivia();

            return indent + "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\r\n" +
                   "#line " + (start.Line + 1) + " \"" + tree.FilePath + "\"\r\n" +
                   new string(' ', start.Character) + twin.ToFullString().TrimEnd() + "\r\n#line default\r\n";
        }

        // A program built with twins starts here: main's twin runs multiplexed when the scheduler is on, and
        // main itself runs when it is off. The entry is a sealed class, not a static one: it can hold no
        // extension method, so the extension-host list has nothing to say about it.
        private void EmitEntry()
        {
            if (Context.Compilation.Options.OutputKind is not (OutputKind.ConsoleApplication or OutputKind.WindowsApplication))
                return;

            // Go's main, as the converter writes it: `main` in the program's main_package, which sits in namespace go
            // or in the one a dotted module path gives it (the entry generator's own search). The entry generator's
            // `Main` beside it is not the program's.
            IMethodSymbol? main = m_augmented.GetSymbolsWithName("main_package", SymbolFilter.Type).OfType<INamedTypeSymbol>()
                .Where(type => type.ContainingType is null)
                .SelectMany(type => type.GetMembers("main").OfType<IMethodSymbol>())
                .FirstOrDefault(method => method is { IsStatic: true, ReturnsVoid: true, Parameters.Length: 0, IsGenericMethod: false });

            if (main is null)
                return;

            bool twinned = m_candidates.TryGetValue(Normalize(main), out Candidate? candidate) && candidate.Twinned;
            string name = main.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".main";

            string call = twinned
                ? "global::go.builtin.RunMainꞏtwin(" + name + ", " + name + Suffix + ")"
                : "global::go.golib.MainThread.Run(" + name + ")";

            Context.AddGeneratedSource("go2cs.twins.entry.g.cs",
                "// <auto-generated/>\r\nnamespace go\r\n{\r\n    internal sealed class GoTwinEntry\r\n    {\r\n        private static void Main() => " + call + ";\r\n    }\r\n}\r\n");
        }

        // The census a spike reading is taken from, as comments: totals first, then one line per function.
        private void EmitReport()
        {
            List<Candidate> twinned = m_ordered.Where(candidate => candidate.Twinned).ToList();
            List<Site> sites = twinned.SelectMany(candidate => candidate.Sites).ToList();
            List<Site> elsewhere = m_ordered.Where(candidate => !candidate.Twinned).SelectMany(candidate => candidate.Sites).ToList();
            StringBuilder report = new();

            report.Append("// <auto-generated/>\r\n// go2cs twins report\r\n");
            report.Append("// go-propagation=").Append(goSites ? "on" : "off").Append("\r\n");
            report.Append("// candidates=").Append(m_ordered.Count).Append(" twinned=").Append(twinned.Count)
                .Append(" go-only=").Append(twinned.Count(candidate => candidate.GoOnly)).Append("\r\n");
            report.Append("// await-sites=").Append(m_awaitSites).Append(" go-twinned=").Append(m_goTwinned).Append(" go-literals=").Append(m_goLiterals)
                .Append(" ref-unrederivable=").Append(m_unrederivable).Append(" ref-spills=").Append(m_spills)
                .Append(" ref-blocked=").Append(m_refBlocked).Append("\r\n");
            report.Append("// in-twins: go-group-left=").Append(sites.Count(site => site.Go == GoKind.Group && !GoTwinnable(site)))
                .Append(" go-other=").Append(sites.Count(site => site.Go == GoKind.Other))
                .Append(" go-passive=").Append(sites.Count(site => site.Go != GoKind.None && !site.Active))
                .Append(" unbound=").Append(sites.Count(site => site.Unbound))
                .Append(" delegate-calls=").Append(sites.Count(site => site.Delegate))
                .Append(" interface-calls=").Append(sites.Count(site => site.Interface))
                .Append(" closure-parks=").Append(sites.Count(site => site is { Active: false, Go: GoKind.None, Renameable: true } && CanPark(site.Target)))
                .Append(" not-renameable=").Append(sites.Count(site => site is { Active: true, Go: GoKind.None, Renameable: false } && CanPark(site.Target))).Append("\r\n");
            report.Append("// outside-twins: go-sites=").Append(elsewhere.Count(site => site.Go != GoKind.None))
                .Append(" unbound=").Append(elsewhere.Count(site => site.Unbound))
                .Append(" calls=").Append(elsewhere.Count).Append("\r\n");
            ReportIface(report);
            ReportSiblings(report);

            foreach (IGrouping<string, Candidate> reason in m_ordered.Where(candidate => candidate.Refusal is not null).GroupBy(candidate => candidate.Refusal!).OrderBy(group => group.Key, StringComparer.Ordinal))
                report.Append("// refused ").Append(reason.Key).Append('=').Append(reason.Count()).Append(" blocked=").Append(reason.Count(candidate => candidate.Parks)).Append("\r\n");

            foreach (Candidate candidate in m_ordered)
            {
                if (!candidate.Parks)
                    continue;

                FileLinePositionSpan span = candidate.Syntax.SyntaxTree.GetLineSpan(candidate.Syntax.Identifier.Span);

                report.Append(candidate.Refusal is null ? "// T " : "// R ").Append(Path.GetFileName(span.Path)).Append('|').Append(span.StartLinePosition.Line + 1)
                    .Append('|').Append(candidate.Syntax.Identifier.Text).Append('|')
                    .Append(candidate.Refusal ?? "sites=" + candidate.Awaits).Append("\r\n");
            }

            Context.AddGeneratedSource("go2cs.twins.report.g.cs", report.ToString());
        }
    }
}
