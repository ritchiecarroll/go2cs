        private int m_awaitSites, m_goTwinned, m_goLiterals, m_unrederivable, m_spills, m_refBlocked;

        // One file of twins per source file: each twin sits in its function's own namespace and class, under a
        // #line directive that puts it on the function's own lines, so a trace or a breakpoint reads the source.
        private void Emit()
        {
            HashSet<string> hints = new(StringComparer.OrdinalIgnoreCase);

            foreach (IGrouping<SyntaxTree, Candidate> file in m_ordered.Where(candidate => candidate.Twinned || candidate.Forwarded).GroupBy(candidate => candidate.Syntax.SyntaxTree))
            {
                CompilationUnitSyntax unit = (CompilationUnitSyntax)file.Key.GetRoot(Context.CancellationToken);
                StringBuilder source = new();

                source.Append("// <auto-generated/>\r\n#nullable enable annotations\r\n#pragma warning disable\r\n");

                foreach (ExternAliasDirectiveSyntax alias in unit.Externs)
                    source.Append(alias.WithoutTrivia().ToFullString()).Append("\r\n");

                foreach (UsingDirectiveSyntax directive in unit.Usings.Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None)))
                    source.Append(directive.WithoutTrivia().ToFullString()).Append("\r\n");

                foreach (IGrouping<SyntaxNode?, Candidate> group in file.GroupBy(candidate => candidate.Syntax.Parent))
                {
                    List<SyntaxNode> chain = group.First().Syntax.Ancestors().Where(node => node is BaseNamespaceDeclarationSyntax or TypeDeclarationSyntax).Reverse().ToList();
                    string indent = "";

                    foreach (SyntaxNode node in chain)
                    {
                        if (node is BaseNamespaceDeclarationSyntax space)
                        {
                            source.Append(indent).Append("namespace ").Append(space.Name.ToString()).Append("\r\n").Append(indent).Append("{\r\n");

                            foreach (UsingDirectiveSyntax directive in space.Usings)
                                source.Append(indent).Append("    ").Append(directive.WithoutTrivia().ToFullString()).Append("\r\n");
                        }
                        else if (node is TypeDeclarationSyntax type)
                        {
                            string keyword = type is RecordDeclarationSyntax record && !record.ClassOrStructKeyword.IsKind(SyntaxKind.None)
                                ? "record " + record.ClassOrStructKeyword.ValueText
                                : type.Keyword.ValueText;

                            source.Append(indent).Append("partial ").Append(keyword).Append(' ').Append(type.Identifier.Text)
                                .Append(type.TypeParameterList?.WithoutTrivia().ToFullString()).Append("\r\n").Append(indent).Append("{\r\n");
                        }

                        indent += "    ";
                    }

                    foreach (Candidate candidate in group)
                        source.Append(candidate.Twinned ? TwinText(candidate, indent) : ForwarderText(candidate, indent));

                    for (int i = chain.Count - 1; i >= 0; i--)
                    {
                        indent = indent.Substring(4);
                        source.Append(indent).Append("}\r\n");
                    }
                }

                string hint = Path.GetFileNameWithoutExtension(file.Key.FilePath) + ".twins.g.cs";
                string unique = hint;

                for (int index = 1; !hints.Add(unique); index++)
                    unique = index + "." + hint;

                Context.AddLineExactSource(GetValidFileName(unique), source.ToString());
            }

            EmitPairs();
            EmitIface();
            EmitEntry();
            EmitReport();
        }

        // PB-5 (12.5): the stack locals this twin declares as heap locals: those whose box an awaited box call hands
        // (an argument box of a byref-param twin, or a receiver box), by name with their type.
        private Dictionary<string, ITypeSymbol>? PromotedLocals(Candidate candidate)
        {
            if (candidate.Promotable.Count == 0)
                return null;

            Dictionary<string, ITypeSymbol> promoted = new(System.StringComparer.Ordinal);

            foreach (Site site in candidate.Sites)
            {
                if (!site.Active || !site.Direct || !ShouldAwait(site))
                    continue;

                List<string> boxes = [];

                if (site.ArgBoxes is { } argBoxes && IsParamBoxTwin(site.Target))
                    boxes.AddRange(argBoxes.Where(box => box is not null)!);

                if (site.BoxOf is { } receiverBox && !site.ViaBoxOverload && IsBoxTwinTarget(site.Target))
                    boxes.Add(receiverBox);

                foreach (KeyValuePair<string, ITypeSymbol> local in candidate.Promotable)
                {
                    string own = "Ꮡ" + local.Key;

                    if (boxes.Any(box => box == own || box.StartsWith(own + ".", System.StringComparison.Ordinal)))
                        promoted[local.Key] = local.Value;
                }
            }

            return promoted.Count == 0 ? null : promoted;
        }

        private string TwinText(Candidate candidate, string indent)
        {
            MethodDeclarationSyntax method = candidate.Syntax;
            SyntaxTree tree = method.SyntaxTree;
            Rewriter rewriter = new(this, Model(tree), method) { BoxReceiver = candidate.BoxReceiver, BoxParams = candidate.BoxParams, Promoted = PromotedLocals(candidate) };
            BlockSyntax? body = (BlockSyntax?)rewriter.Visit(method.Body);
            ArrowExpressionClauseSyntax? arrow = (ArrowExpressionClauseSyntax?)rewriter.Visit(method.ExpressionBody);

            // N2: the box twin's prologue derives its receiver's ref from the box, on the opening brace's own line so the
            // body keeps its #line mapping. Under GoTwinsBoxCopy (the aliasing probe's negative control) it copies instead.
            // byref-param (12.1): each boxed parameter takes the same prologue, in parameter order.
            List<string> boxedNames = [.. candidate.BoxReceiver is { } boxedReceiver ? [boxedReceiver] : Array.Empty<string>(), .. candidate.BoxParams ?? []];

            if (body is not null && boxedNames.Count > 0)
            {
                List<StatementSyntax> entry = [];

                foreach (string receiver in boxedNames)
                {
                    if (BoxCopy)
                    {
                        entry.Add(SyntaxFactory.ParseStatement(" var ᴛcopy" + receiver + " = Ꮡ" + receiver + ".DerefOrNull();"));
                        entry.Add(SyntaxFactory.ParseStatement(" ref var " + Local(receiver) + " = ref ᴛcopy" + receiver + ";"));
                    }
                    else
                    {
                        entry.Add(SyntaxFactory.ParseStatement(" ref var " + Local(receiver) + " = ref Ꮡ" + receiver + ".DerefOrNull();"));
                    }
                }

                entry[^1] = entry[^1].WithTrailingTrivia(body.OpenBraceToken.TrailingTrivia);
                body = body.WithOpenBraceToken(body.OpenBraceToken.WithTrailingTrivia()).WithStatements(body.Statements.InsertRange(0, entry));
            }

            // N3's D3 core: a func-value parameter never reassigned is tested for a pair ONCE, at the twin's entry. The
            // declarations sit on the opening brace's own line, so every line of the body keeps its #line mapping.
            if (body is not null && rewriter.HoistedPairs.Count > 0)
            {
                SyntaxTriviaList braceTrailing = body.OpenBraceToken.TrailingTrivia;
                List<StatementSyntax> declarations = [.. rewriter.HoistedPairs.Select(name =>
                    SyntaxFactory.ParseStatement(" global::go.golib.GoFuncPair? " + name + "ꞏpair = " + name + "?.Target as global::go.golib.GoFuncPair;"))];

                declarations[^1] = declarations[^1].WithTrailingTrivia(braceTrailing);
                body = body.WithOpenBraceToken(body.OpenBraceToken.WithTrailingTrivia()).WithStatements(body.Statements.InsertRange(0, declarations));
            }

            candidate.Awaits = rewriter.Awaits;
            m_awaitSites += rewriter.Awaits;
            m_ifaceAwaits += rewriter.IfaceAwaits;
            m_goTwinned += rewriter.GoTwinned;
            m_goLiterals += rewriter.Literals;
            m_unrederivable += rewriter.Unrederivable;
            m_spills += rewriter.Spills;
            m_refBlocked += rewriter.RefBlocked;

            SyntaxToken first = method.Modifiers.Count > 0 ? method.Modifiers[0] : method.ReturnType.GetFirstToken();
            LinePosition start = tree.GetLineSpan(first.Span).StartLinePosition;

            string result = method.ReturnType is PredefinedTypeSyntax predefined && predefined.Keyword.IsKind(SyntaxKind.VoidKeyword)
                ? "global::go.golib.GoTask"
                : "global::go.golib.GoTask<" + method.ReturnType.WithoutTrivia().ToFullString() + ">";

            SyntaxTokenList modifiers = SyntaxFactory.TokenList(method.Modifiers.Where(modifier => !modifier.IsKind(SyntaxKind.PartialKeyword)))
                .Add(SyntaxFactory.Token(SyntaxKind.AsyncKeyword).WithTrailingTrivia(SyntaxFactory.Space));

            ParameterListSyntax parameters = method.ParameterList;

            // N2: `this ref T t` becomes `this ж<T> Ꮡt`, the receiver's box.
            if (candidate.BoxReceiver is not null && parameters.Parameters.Count > 0 && parameters.Parameters[0] is { Type: { } receiverType } receiverParameter)
            {
                ParameterSyntax boxed = receiverParameter
                    .WithModifiers(SyntaxFactory.TokenList(SyntaxFactory.Token(SyntaxKind.ThisKeyword).WithTrailingTrivia(SyntaxFactory.Space)))
                    .WithType(SyntaxFactory.ParseTypeName("global::go.ж<" + receiverType.WithoutTrivia().ToFullString() + ">").WithTrailingTrivia(SyntaxFactory.Space))
                    .WithIdentifier(SyntaxFactory.Identifier("Ꮡ" + receiverParameter.Identifier.ValueText).WithTriviaFrom(receiverParameter.Identifier));

                parameters = parameters.WithParameters(parameters.Parameters.Replace(receiverParameter, boxed));
            }

            // byref-param: each boxed `ref T p` becomes `ж<T> Ꮡp`, its box.
            foreach (string name in candidate.BoxParams ?? [])
            {
                if (parameters.Parameters.FirstOrDefault(parameter => parameter.Identifier.ValueText == name) is not { Type: { } type } parameter)
                    continue;

                ParameterSyntax boxed = parameter
                    .WithModifiers(default)
                    .WithType(SyntaxFactory.ParseTypeName("global::go.ж<" + type.WithoutTrivia().ToFullString() + ">")
                        .WithLeadingTrivia(parameter.GetLeadingTrivia()).WithTrailingTrivia(SyntaxFactory.Space))
                    .WithIdentifier(SyntaxFactory.Identifier("Ꮡ" + parameter.Identifier.ValueText).WithTriviaFrom(parameter.Identifier));

                parameters = parameters.WithParameters(parameters.Parameters.Replace(parameter, boxed));
            }

            MethodDeclarationSyntax twin = method
                .WithParameterList(parameters)
                .WithAttributeLists(default)
                .WithModifiers(modifiers)
                .WithReturnType(SyntaxFactory.ParseTypeName(result).WithTriviaFrom(method.ReturnType))
                .WithIdentifier(SyntaxFactory.ParseToken(method.Identifier.Text + Suffix).WithLeadingTrivia(method.Identifier.LeadingTrivia).WithTrailingTrivia(method.Identifier.TrailingTrivia))
                .WithBody(body)
                .WithExpressionBody(arrow)
                .WithLeadingTrivia();

            return indent + "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\r\n" +
                   indent + rewriter.Stamp() + "\r\n" +
                   indent + rewriter.KeepOrigin() + "\r\n" +
                   "#line " + (start.Line + 1) + " \"" + tree.FilePath + "\"\r\n" +
                   new string(' ', start.Character) + twin.ToFullString().TrimEnd() + "\r\n#line default\r\n" +
                   string.Concat(rewriter.CacheFields.Select(field => indent + field + "\r\n"));
        }

        // 7a (12.1, R3): a forwarder keeps the plain member's modifiers (`partial` dropped) and parameters, calls it, and
        // returns a completed task. No #line: it holds no line of the source.
        private static string ForwarderText(Candidate candidate, string indent)
        {
            MethodDeclarationSyntax method = candidate.Syntax;
            bool isVoid = method.ReturnType is PredefinedTypeSyntax predefined && predefined.Keyword.IsKind(SyntaxKind.VoidKeyword);
            string returnType = method.ReturnType.WithoutTrivia().ToFullString();
            // `extern` and `partial` belong to the plain member: a forwarder has a body (CS0179 with `extern`).
            string modifiers = string.Join(" ", method.Modifiers.Where(modifier => !modifier.IsKind(SyntaxKind.PartialKeyword) && !modifier.IsKind(SyntaxKind.ExternKeyword))
                .Select(modifier => modifier.Text));
            List<string> declared = [], arguments = [];

            for (int i = 0; i < method.ParameterList.Parameters.Count; i++)
            {
                ParameterSyntax parameter = method.ParameterList.Parameters[i];
                ITypeSymbol type = candidate.Symbol.Parameters[i].Type;

                if (IsBoxedReceiver(candidate.Symbol, i) && parameter.Type is { } receiverType)
                {
                    string box = "Ꮡ" + parameter.Identifier.ValueText;
                    declared.Add("this global::go.ж<" + receiverType.WithoutTrivia().ToFullString() + "> " + box);
                    arguments.Add("ref " + box + ".DerefOrNull()");
                }
                else if (VariadicElement(candidate.Symbol.Parameters[i]) is { } element)
                {
                    declared.Add("global::go.slice<" + element.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "> " + parameter.Identifier.Text);
                    arguments.Add(parameter.Identifier.Text + ".ꓸꓸꓸ");
                }
                else if (IsSString(type) && parameter.Type is not null)
                {
                    declared.Add(parameter.WithType(SyntaxFactory.ParseTypeName("global::go.@string").WithTrailingTrivia(SyntaxFactory.Space)).WithoutTrivia().ToFullString());
                    arguments.Add(parameter.Identifier.Text);
                }
                else
                {
                    declared.Add(parameter.WithoutTrivia().ToFullString());
                    arguments.Add(parameter.Identifier.Text);
                }
            }

            string parameters = "(" + string.Join(", ", declared) + ")";
            string call = method.Identifier.Text + "(" + string.Join(", ", arguments) + ")";

            string declaration = modifiers + " " + (isVoid ? "global::go.golib.GoTask" : "global::go.golib.GoTask<" + returnType + ">") + " " +
                                 method.Identifier.Text + Suffix + parameters;

            string body = isVoid ? " { " + call + "; return default; }" : " => new global::go.golib.GoTask<" + returnType + ">(" + call + ");";

            // COORD's ruling on P8 (iii): the mark says the member CANNOT park, by the park analysis, a property of the Go
            // code. A refused member that parks gets an unmarked forwarder, which a caller in another assembly awaits, so
            // lifting the refusal later changes nothing a caller bound.
            return indent + "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]\r\n" +
                   (candidate.Parks ? "" : indent + "[global::go.golib.GoParkForwarder]\r\n") +
                   indent + declaration + body + "\r\n";
        }

        // A program built with twins starts here: main's twin runs multiplexed when the scheduler is on, and
        // main itself runs when it is off. The entry is a sealed class, not a static one: it can hold no
        // extension method, so the extension-host list has nothing to say about it.
        private void EmitEntry()
        {
            if (Context.Compilation.Options.OutputKind is not (OutputKind.ConsoleApplication or OutputKind.WindowsApplication))
                return;

            // Go's main, as the converter writes it: `main` in the program's main_package, which sits in namespace go
            // or in the one a dotted module path gives it (the entry generator's own search). The entry generator's
            // `Main` beside it is not the program's.
            IMethodSymbol? main = m_augmented.GetSymbolsWithName("main_package", SymbolFilter.Type).OfType<INamedTypeSymbol>()
                .Where(type => type.ContainingType is null)
                .SelectMany(type => type.GetMembers("main").OfType<IMethodSymbol>())
                .FirstOrDefault(method => method is { IsStatic: true, ReturnsVoid: true, Parameters.Length: 0, IsGenericMethod: false });

            if (main is null)
                return;

            bool twinned = m_candidates.TryGetValue(Normalize(main), out Candidate? candidate) && candidate.Twinned;
            string name = main.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ".main";

            string call = twinned
                ? "global::go.builtin.RunMainꞏtwin(" + name + ", " + name + Suffix + ")"
                : "global::go.golib.MainThread.Run(" + name + ")";

            Context.AddGeneratedSource("go2cs.twins.entry.g.cs",
                "// <auto-generated/>\r\nnamespace go\r\n{\r\n    internal sealed class GoTwinEntry\r\n    {\r\n        private static void Main() => " + call + ";\r\n    }\r\n}\r\n");
        }

        // The census a spike reading is taken from, as comments: totals first, then one line per function.
        private void EmitReport()
        {
            List<Candidate> twinned = m_ordered.Where(candidate => candidate.Twinned).ToList();
            List<Site> sites = twinned.SelectMany(candidate => candidate.Sites).ToList();
            List<Site> elsewhere = m_ordered.Where(candidate => !candidate.Twinned).SelectMany(candidate => candidate.Sites).ToList();
            StringBuilder report = new();

            report.Append("// <auto-generated/>\r\n// go2cs twins report\r\n");
            report.Append("// go-propagation=").Append(goSites ? "on" : "off").Append("\r\n");
            report.Append("// candidates=").Append(m_ordered.Count).Append(" twinned=").Append(twinned.Count)
                .Append(" go-only=").Append(twinned.Count(candidate => candidate.GoOnly)).Append("\r\n");
            report.Append("// forwarders=").Append(m_ordered.Count(candidate => candidate.Forwarded))
                .Append(" marked=").Append(m_ordered.Count(candidate => candidate is { Forwarded: true, Parks: false }))
                .Append(" unmarked=").Append(m_ordered.Count(candidate => candidate is { Forwarded: true, Parks: true })).Append("\r\n");

            // Section 9: one row per member of the population, `// S file|line|name|class`.
            if (m_populationAssembly)
            {
                foreach (Candidate candidate in m_ordered.Where(InPopulation))
                {
                    FileLinePositionSpan span = candidate.Syntax.SyntaxTree.GetLineSpan(candidate.Syntax.Identifier.Span);

                    report.Append("// S ").Append(Path.GetFileName(span.Path)).Append('|').Append(span.StartLinePosition.Line + 1).Append('|')
                        .Append(candidate.Syntax.Identifier.Text).Append('|').Append(Classify(candidate)).Append("\r\n");
                }
            }
            report.Append("// await-sites=").Append(m_awaitSites).Append(" go-twinned=").Append(m_goTwinned).Append(" go-literals=").Append(m_goLiterals)
                .Append(" ref-unrederivable=").Append(m_unrederivable).Append(" ref-spills=").Append(m_spills)
                .Append(" ref-blocked=").Append(m_refBlocked).Append(" go-plain=").Append(GoPlain).Append("\r\n");
            report.Append("// box: twins=").Append(twinned.Count(candidate => candidate.BoxReceiver is not null))
                .Append(" calls=").Append(BoxCalls).Append(" plain=").Append(BoxPlain)
                .Append(" param-twins=").Append(twinned.Count(candidate => candidate.BoxParams is not null)).Append(" param=").Append(BoxParam ? "on" : "off")
                .Append(BoxArgCopy ? " ARGCOPY(control)" : "")
                .Append(" recv=").Append(BoxRecv ? "on" : "off").Append(" forwarders=").Append(BoxForwarders ? "on" : "off").Append(BoxCopy ? " COPY(control)" : "").Append("\r\n");

            foreach (string row in BoxPlainRows)
                report.Append(row).Append("\r\n");

            foreach (string row in ViaOverloadRows)
                report.Append(row).Append("\r\n");
            report.Append("// in-twins: go-group-left=").Append(sites.Count(site => site.Go == GoKind.Group && !GoTwinnable(site)))
                .Append(" go-other=").Append(sites.Count(site => site.Go == GoKind.Other || site.Go == GoKind.Literal && !LiteralLaunches(site)))
                .Append(" go-passive=").Append(sites.Count(site => site.Go != GoKind.None && !site.Active))
                .Append(" unbound=").Append(sites.Count(site => site.Unbound))
                .Append(" delegate-calls=").Append(sites.Count(site => site.Delegate)).Append(" delegate-uncovered=").Append(UncoveredFuncValueCalls)
                .Append(" interface-calls=").Append(sites.Count(site => site.Interface))
                .Append(" closure-parks=").Append(sites.Count(site => site is { Active: false, Go: GoKind.None, Renameable: true } && CanPark(site.Target)))
                .Append(" not-renameable=").Append(sites.Count(site => site is { Active: true, Go: GoKind.None, Renameable: false } && CanPark(site.Target))).Append("\r\n");
            report.Append("// outside-twins: go-sites=").Append(elsewhere.Count(site => site.Go != GoKind.None))
                .Append(" unbound=").Append(elsewhere.Count(site => site.Unbound))
                .Append(" calls=").Append(elsewhere.Count).Append("\r\n");
            ReportIface(report);
            ReportSiblings(report);

            foreach (IGrouping<string, Candidate> reason in m_ordered.Where(candidate => candidate.Refusal is not null).GroupBy(candidate => candidate.Refusal!).OrderBy(group => group.Key, StringComparer.Ordinal))
                report.Append("// refused ").Append(reason.Key).Append('=').Append(reason.Count()).Append(" blocked=").Append(reason.Count(candidate => candidate.Parks)).Append("\r\n");

            foreach (Candidate candidate in m_ordered)
            {
                if (!candidate.Parks)
                    continue;

                FileLinePositionSpan span = candidate.Syntax.SyntaxTree.GetLineSpan(candidate.Syntax.Identifier.Span);

                report.Append(candidate.Refusal is null ? "// T " : "// R ").Append(Path.GetFileName(span.Path)).Append('|').Append(span.StartLinePosition.Line + 1)
                    .Append('|').Append(candidate.Syntax.Identifier.Text).Append('|')
                    .Append(candidate.Refusal ?? "sites=" + candidate.Awaits).Append("\r\n");
            }

            Context.AddGeneratedSource("go2cs.twins.report.g.cs", report.ToString());
        }
    }
