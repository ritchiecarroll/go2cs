using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using static go2cs.Common;

namespace go2cs;

/// <summary>
/// Writes a generated partial of a declared type carrying type-level attributes: the route by which a
/// generator states a fact converted code leaves to a comment, since a generated file can add an
/// attribute to a type but not to its members (ChanDirSigGenerator, MemberRecordGenerator).
/// </summary>
public static class GeneratedPartials
{
    /// <summary>
    /// Whether <paramref name="type"/> and every type enclosing it is partial in every declaration, which a
    /// generated part needs (CS0260).
    /// </summary>
    public static bool CanReopen(INamedTypeSymbol type) => EnclosingChain(type).All(IsPartialEverywhere);

    /// <summary>
    /// The source of one generated file: <paramref name="attributes"/> on a partial of <paramref name="type"/>,
    /// nested inside a partial of each enclosing type, outermost first.
    /// </summary>
    public static string Source(string ns, INamedTypeSymbol type, IEnumerable<string> attributes)
    {
        List<INamedTypeSymbol> chain = EnclosingChain(type).Reverse().ToList();

        StringBuilder source = new();
        source.Append("// <auto-generated/>\r\n#nullable enable\r\n\r\n");
        source.Append($"namespace {ns};\r\n\r\n");

        for (int depth = 0; depth < chain.Count; depth++)
        {
            string indent = new(' ', depth * 4);

            if (depth == chain.Count - 1)
            {
                foreach (string attribute in attributes.Distinct())
                    source.Append(indent).Append(attribute).Append("\r\n");
            }

            source.Append($"{indent}partial {Keyword(chain[depth])} {EscapeIdentifier(chain[depth].Name)}{TypeParameters(chain[depth])}\r\n{indent}{{\r\n");
        }

        for (int depth = chain.Count - 1; depth >= 0; depth--)
            source.Append(new string(' ', depth * 4)).Append("}\r\n");

        return source.ToString();
    }

    /// <summary>A hint name for <paramref name="type"/>'s generated part, unique within <paramref name="used"/>.</summary>
    public static string HintName(HashSet<string> used, string ns, INamedTypeSymbol type, string suffix)
    {
        string hint = $"{ns}.{string.Join(".", EnclosingChain(type).Reverse().Select(item => item.MetadataName))}.{suffix}.g.cs";
        string unique = hint;

        for (int index = 1; !used.Add(unique); index++)
            unique = $"{index}.{hint}";

        return GetValidFileName(unique);
    }

    /// <summary>
    /// The one spelling of a parameter type in a generated record's method key: <c>typeof(...)</c>, which the
    /// compiler resolves, so golib matches the key by Type identity and never by a name
    /// (<c>GoReflect.SignatureMatches</c>; ChanDirSigGenerator, MemberRecordGenerator).
    /// </summary>
    public static string TypeOf(ITypeSymbol type) => $"typeof({type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})";

    /// <summary>
    /// Whether an attribute argument can name <paramref name="type"/>, and so whether a method whose parameters
    /// all pass can be keyed: no type parameter anywhere in it, and no unmanaged pointer.
    /// </summary>
    public static bool IsNameable(ITypeSymbol type) => type switch
    {
        ITypeParameterSymbol => false,
        IPointerTypeSymbol or IFunctionPointerTypeSymbol => false,
        IArrayTypeSymbol array => IsNameable(array.ElementType),
        INamedTypeSymbol named => named.TypeArguments.All(IsNameable) && (named.ContainingType is null || IsNameable(named.ContainingType)),
        _ => true
    };

    // The declaring type and every type enclosing it, innermost first.
    private static IEnumerable<INamedTypeSymbol> EnclosingChain(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? current = type; current is not null; current = current.ContainingType)
            yield return current;
    }

    private static string Keyword(INamedTypeSymbol type) => type.TypeKind switch
    {
        TypeKind.Interface => "interface",
        TypeKind.Struct => "struct",
        _ => "class"
    };

    private static string TypeParameters(INamedTypeSymbol type) =>
        type.TypeParameters.Length == 0 ? "" : $"<{string.Join(", ", type.TypeParameters.Select(parameter => parameter.Name))}>";

    private static bool IsPartialEverywhere(INamedTypeSymbol type) =>
        type.DeclaringSyntaxReferences.Length > 0 &&
        type.DeclaringSyntaxReferences.All(reference =>
            reference.GetSyntax() is TypeDeclarationSyntax declaration &&
            declaration.Modifiers.Any(modifier => modifier.IsKind(SyntaxKind.PartialKeyword)));

    private static string EscapeIdentifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
}
