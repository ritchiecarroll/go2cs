    static Common()
    {
        const string FallBackAssemblyName = nameof(go2cs);
        const string FallBackVersion = "0.0.1";

        try
        {
            EntryAssembly = Assembly.GetAssembly(typeof(Common));
            AssemblyName = EntryAssembly?.GetName().Name ?? FallBackAssemblyName;
            Version = getVersion();
        }
        catch
        {
            EntryAssembly = null;
            AssemblyName = FallBackAssemblyName;
            Version = FallBackVersion;
        }

        // global::-rooted so a Go type in the SAME package class can never shadow the attribute
        // name (the generated partials sit inside `<pkg>_package`, where every Go type name is a
        // sibling member — the same collision class as the System.Range/System.Type audit).
        GeneratedCodeAttribute = $"""global::System.CodeDom.Compiler.GeneratedCode("{AssemblyName}", "{Version}")""";

        PointerExpr = new Regex($"^(?:[^<]*)?{PointerPrefix}<.*$", RegexOptions.Compiled);

        return;

        string getVersion()
        {
            Version? version = EntryAssembly?.GetName().Version;
            return version is null ? FallBackVersion : $"{version.Major}.{version.Minor}.{version.Build}";
        }
    }

    public static bool IsGenericType(string typeName)
    {
        return typeName.Contains('<') && typeName.Contains('>');
    }

    /// <summary>
    /// Reduces a type reference to its bare name by truncating at the first type-argument list:
    /// <c>node&lt;K, V&gt;</c> becomes <c>node</c>, <c>go.sync.Map</c> stays <c>go.sync.Map</c>.
    /// </summary>
    /// <remarks>
    /// Two generators need this and for opposite reasons, which is why it lives here rather than
    /// beside either of them:
    /// <list type="bullet">
    /// <item><c>ImplementGenerator</c> re-opens the list to substitute a proxy type, so it wants
    /// everything BEFORE the <c>&lt;</c> and then writes its own arguments.</item>
    /// <item><c>StructTypeTemplate</c> wants the member-access spelling of an embed, and a declared
    /// member never carries type arguments.</item>
    /// </list>
    /// Truncation at the FIRST <c>&lt;</c> is deliberate: a nested argument list
    /// (<c>Map&lt;K, List&lt;V&gt;&gt;</c>) has nothing to contribute to a bare name, so there is no
    /// bracket matching to do. A name with no <c>&lt;</c> is returned unchanged (not copied).
    /// </remarks>
    internal static string StripGenericTypeArguments(string typeName)
    {
        int index = typeName.IndexOf('<');
        return index < 0 ? typeName : typeName[..index];
    }

    public static string GetSimpleName(string typeName, bool dropGeneric = false, bool dropCollisionPrefix = false)
    {
        // Check if type name is a pointer, i.e., ж<T>. Match the prefix as `ж<` specifically — a bare
        // `ж` scan mis-fires on the marker glyph EMBEDDED in an identifier (crypto/elliptic's
        // `P256PointжnistPoint` proxy), mangling a VALUE embed's simple name (`nistCurve<…ж…>` →
        // `istPoint.Value`) so its promoted member access binds a nonexistent hop (CS0103/CS1061).
        int startIndex = typeName.IndexOf($"{PointerPrefix}<", StringComparison.Ordinal);
        bool isPointer = false;

        // For pointer types, get dereferenced underlying type
        if (startIndex > -1 && typeName.EndsWith(">"))
        {
            typeName = $"{typeName[(startIndex + 2)..^1]}";
            isPointer = true;
        }

        string[] parts = typeName.Split('.');

        string simpleName = $"{parts[^1]}{(isPointer ? ".Value" : "")}";

        if (dropGeneric)
        {
            // Index into simpleName, and admit index 1. This read `typeName.IndexOf('<') > 1`
            // until 2026-08-14, and both halves of that were wrong:
            //   * `> 1` silently exempted every ONE-CHARACTER generic name. `G<T>` carries its
            //     '<' at index 1, so the argument list SURVIVED a "drop the generics" request and
            //     StructTypeTemplate spelled its constructor `public G<T>(NilType _)`. That is not
            //     a constructor to C#, so the `partial struct G<T>` scope never opens and every
            //     member the template writes lands in the containing STATIC package class —
            //     CS0715 (operators) and CS0708 (instance members), the shared root under
            //     `internal/reflectlite`'s `B[T any]` and `runtime/debug`'s `G[T any]`. Every
            //     multi-character generic in the corpus (`meta<T>`, `nistCurve<Point>`) cleared
            //     the guard, which is why this held until the first single-letter one.
            //   * the index came from typeName but sliced simpleName, which is SHORTER whenever
            //     the name is dotted — `a.Map<K, V>` indexes at 5 into an 8-char `Map<K, V>` and
            //     yields the garbage `Map<K`. Unreached today; corrected rather than left latent.
            // Index 0 stays excluded: it would name an empty type.
            startIndex = simpleName.IndexOf('<');

            if (startIndex > 0 && typeName.EndsWith(">"))
                simpleName = $"{simpleName[..startIndex]}";
        }

        if (dropCollisionPrefix && simpleName.StartsWith(ShadowVarMarker, StringComparison.Ordinal))
            simpleName = simpleName[ShadowVarMarker.Length..];

        return simpleName;
    }

    /// <summary>
    /// Resolves the name a forwarding call must spell on the receiver for an interface member named
    /// <paramref name="interfaceMemberName"/>, against the methods the implementing struct actually
    /// DECLARES.
    /// </summary>
    /// <param name="interfaceMemberName">Interface member's simple, C#-escaped name.</param>
    /// <param name="declaredNames">Every method name the struct declares, in any receiver form.</param>
    /// <returns>The declared name to forward to, or <c>null</c> when it is the interface member's own.</returns>
    /// <remarks>
    /// A member is IMPLEMENTED under the interface's name and FORWARDS under the emitted one, and the
    /// two part company when the converter's collision pass Δ-renames the implementation — which a
    /// `-tests` whitebox compilation does to a test-file declarator whose bare name would hijack a
    /// same-named member the file carries via `using static` (flag_test.go's five `flag.Value` types
    /// each declare `String`/`Set` against the production `flag` package the test variant dot-imports,
    /// emitted `ΔString`/`ΔSet`). The exact name is matched FIRST so a genuinely Δ-named Go method can
    /// never be displaced by a projection, and the marker strip runs only as a second pass — the same
    /// two-pass rule golib's shell binder and method-set probe apply at run time
    /// (<c>TypeExtensions.GoMethodNameMatches</c>), so the compile-time adapter cannot disagree with
    /// them about one name. Null for every member the collision pass left alone, which is the whole
    /// production corpus.
    /// </remarks>
    public static string? ResolveForwardMemberName(string interfaceMemberName, ICollection<string> declaredNames)
    {
        if (declaredNames.Contains(interfaceMemberName))
            return null;

        string projected = $"{ShadowVarMarker}{interfaceMemberName}";

        return declaredNames.Contains(projected) ? projected : null;
    }

    // A generated reference that BEGINS with the root namespace must be global::-qualified:
    // inside a package whose namespace nests a same-named segment (go/build/constraint →
    // namespace go.go.build), C# binds the leading `go` RELATIVELY to go.go, so every
    // `go.…` type reference in the generated adapter failed (CS0234 ×50 + CS0538 ×13).
    // Qualifies each type-reference position (string start, after '<', '(', ',' or space);
    // an interior `.go.` segment (go.go.build itself) is never touched.
    private static readonly Regex s_rootTypeRefRegex = new(@"(^|[<(,\s])go\.", RegexOptions.Compiled);

    public static string GlobalQualify(string typeName)
    {
        return s_rootTypeRefRegex.Replace(typeName, "$1global::go.");
    }

    // RefKindPrefix renders a parameter's ref-kind modifier ("in " / "ref " / "out ") so a
    // generated signature matches an interface member declared with one (the hand-finished
    // io stub's Reader.Read(in slice<byte>) - an explicit impl without it is CS0539).
    public static string RefKindPrefix(RefKind refKind) => refKind switch
    {
        RefKind.In => "in ",
        RefKind.Ref => "ref ",
        RefKind.Out => "out ",
        _ => "",
    };

    public static string GetFullTypeName(this ITypeSymbol? typeSymbol, bool useDisplayString = false)
    {
        switch (typeSymbol)
        {
            case null:
                return string.Empty;
            case IArrayTypeSymbol arrayType:
                return $"{GetFullTypeName(arrayType.ElementType)}[]";
            case INamedTypeSymbol { IsGenericType: true } namedType:
                ImmutableArray<ITypeSymbol> typeArgs = namedType.TypeArguments;
                IEnumerable<string> typeArgNames = typeArgs.Select(typeArg => typeArg.GetFullTypeName(useDisplayString));
                return $"{namedType.Name}<{string.Join(", ", typeArgNames)}>";
            default:
                return useDisplayString ? typeSymbol.ToDisplayString() : typeSymbol.Name;
        }
    }

    public static string[] GetFullyQualifiedUsingStatements(SyntaxTree syntaxTree, SemanticModel semanticModel)
    {
        return syntaxTree
            .GetRoot()
            .DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            // Skip `global using` directives: they are already in scope in every file of the
            // compilation (including generated ones), so re-emitting them as file-local `using`
            // here would collide with the original global alias (CS1537 "appeared previously").
            .Where(directive => directive.GlobalKeyword.IsKind(SyntaxKind.None))
            .Select(directive =>
            {
                if (directive.Name is null)
                    return "";

                // For alias directives, maintain the alias but fully qualify the target
                if (directive.Alias is not null)
                {
                    ISymbol? symbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                    if (symbol is not null)
                    {
                        string fullyQualifiedName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        return $"using {directive.Alias.Name.Identifier.Text} = {fullyQualifiedName};";
                    }
                    
                    return directive.GetText().ToString().Trim();
                }
                
                // Static using directives
                if (directive.StaticKeyword.Kind() is not SyntaxKind.None)
                {
                    ISymbol? symbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                    if (symbol is not null)
                    {
                        string fullyQualifiedName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                        return $"using static {fullyQualifiedName};";
                    }

                    return directive.GetText().ToString().Trim();
                }

                // Standard namespace imports
                ISymbol? namespaceSymbol = semanticModel.GetSymbolInfo(directive.Name).Symbol;

                if (namespaceSymbol is not null)
                {
                    return $"using {namespaceSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)};";
                }
                
                return directive.GetText().ToString().Trim();
            })
            .ToArray();
    }

    /// <summary>
    /// Sanitizes a composed name into a legal Roslyn <c>AddSource</c> hint name.
    /// </summary>
    /// <remarks>
    /// The rule is Roslyn's own, spelled out as an ALLOW-list, and it is deliberately NOT
    /// <see cref="Path.GetInvalidFileNameChars"/> — that call is OS-DEPENDENT, and using it made every
    /// generator in this assembly silently platform-specific. Windows returns 41 characters (including
    /// <c>:</c> <c>&lt;</c> <c>&gt;</c> <c>"</c> <c>|</c> <c>?</c> <c>*</c>), Unix returns TWO (NUL and
    /// <c>/</c>). Roslyn validates a hint name identically on both, so a name like
    /// <c>…Lock.global::go.sync.atomic_package.noCopy.g.cs</c> or <c>…Pointer&lt;T&gt;.g.cs</c> was
    /// scrubbed on Windows and passed through untouched on Linux, where <c>AddSource</c> threw
    /// <see cref="ArgumentException"/>. A generator that throws is reported as CS8785 — a WARNING — and
    /// simply contributes nothing, so the failure surfaced as a flood of downstream errors in code that
    /// had never been generated (CS0051/CS0052 accessibility, CS8983 struct initializers, CS0246 on a
    /// missing adapter type: 106 errors building <c>core/fmt</c>'s closure on Linux, none on Windows).
    ///
    /// The allow-list is letters, digits, and <c>. , - _ (space) ( ) [ ]</c>. Unicode letters pass
    /// (<c>char.IsLetterOrDigit</c> is culture-independent for these), so the emission markers ж, Δ, ᴛ
    /// survive exactly as they did. Measured Windows-neutral: a hint name containing a character that
    /// Windows allows but Roslyn rejects would already be failing this corpus with CS8785 on Windows,
    /// and none does — so the two rules agree on every name the corpus produces, and the generated file
    /// names are now identical on every host.
    /// </remarks>
    public static string GetValidFileName(string fileName)
    {
        return CapHintName(new string(fileName.Replace("@", "").Select(c => IsValidHintNameChar(c) ? c : '_').ToArray()));
    }

    private static bool IsValidHintNameChar(char c)
    {
        return char.IsLetterOrDigit(c) || c is '.' or ',' or '-' or '_' or ' ' or '(' or ')' or '[' or ']';
    }

    /// <summary>
    /// The longest hint name any generator in this assembly will emit.
    /// </summary>
    /// <remarks>
    /// Windows caps a single FILENAME COMPONENT at 255 characters. Unlike MAX_PATH that ceiling is not
    /// liftable — <c>LongPathsEnabled</c>, the <c>\\?\</c> prefix and a long-path-aware manifest all
    /// raise the limit on the total PATH and none of them touches the component (measured: a 265-character
    /// path writes fine on such a machine; a 256-character file name fails on the same one).
    /// <para>
    /// Hint names compose the containing package's namespace with a fully qualified type name, so the
    /// converted import path appears in them TWICE and they grow at twice its length. For the standard
    /// library that is nothing — <c>log/slog</c>'s longest is 81 characters — but a converted third-party
    /// tree has no such bound: issue #35's reporter has import paths of 115 characters, which produces
    /// <c>go.github.com.envoyproxy…v3_package.ProtoReflect.global__go.github.com.envoyproxy…v3_package.ClientSideWeightedRoundRobinConfig.g.cs</c>
    /// at 314 characters, and <c>csc</c> then fails the build outright with CS0016 — at ANY output root,
    /// on any Windows, with every setting turned on.
    /// </para>
    /// <para>
    /// A hint name is only a label: Roslyn requires it to be unique within a generator and nothing more,
    /// and <c>EmitCompilerGeneratedFiles</c> writes it out purely so the generated source is readable on
    /// disk. Capping it is therefore free of any semantic consequence — the compiled output is identical
    /// and the files it names are git-ignored.
    /// </para>
    /// <para>
    /// The value is set from the PATH the emitted file lands at, not from the 255 ceiling. Under a
    /// <c>-recurse</c> conversion that is
    /// <c>&lt;root&gt;\.artifacts\gen\&lt;token&gt;\go2cs-gen\go2cs.ImplicitConvGenerator\&lt;hint&gt;</c>,
    /// whose fixed part measures 66 characters; 128 therefore holds the whole path to 194 characters plus
    /// the user's output root, which keeps a root of up to 59 characters inside MAX_PATH — the same
    /// promise the converter's own project-path budget makes. There is room to spare for the numeric
    /// suffix <see cref="GetUniqueHintName"/> may still add.
    /// </para>
    /// </remarks>
    public const int MaxHintNameLength = 128;

    // Compresses an over-long hint name to `<head>-<hash16>.g.cs`, deterministically: the hash is
    // SHA-256 over the FULL name, so two names sharing a head stay distinct, and it is stable across
    // processes and machines (string.GetHashCode is NOT — it is randomized per process in .NET Core,
    // which would make the emitted file names differ run to run).
    //
    // The elision separator MUST come from the same allow-list IsValidHintNameChar enforces, which is
    // why it is a hyphen and not the tilde a truncation usually reads best with. Roslyn validates the
    // hint name it is handed, and this compression runs AFTER the sanitize pass — so an out-of-list
    // character here reaches AddSource unscrubbed and throws ArgumentException, which surfaces as
    // CS8785, a WARNING, leaving the generator to contribute NOTHING and the build to fail on whatever
    // it should have produced. That is precisely the failure mode GetValidFileName's remarks describe,
    // reachable from the other side; measured on the issue-#35 repro, a tilde here cost all three
    // generators at once (ImplementGenerator, RecvGenerator, TypeGenerator) and the package then failed
    // with CS0246 on the adapter type that was never emitted.
    private static string CapHintName(string hintName)
    {
        if (hintName.Length <= MaxHintNameLength)
            return hintName;

        string extension = hintName.EndsWith(".g.cs") ? ".g.cs" : "";
        string baseName = hintName.Substring(0, hintName.Length - extension.Length);

        using SHA256 sha256 = SHA256.Create();
        byte[] digest = sha256.ComputeHash(Encoding.UTF8.GetBytes(hintName));
        StringBuilder hash = new(16);

        for (int i = 0; i < 8; i++)
            hash.Append(digest[i].ToString("x2"));

        int keep = MaxHintNameLength - extension.Length - hash.Length - 1;

        return string.Concat(baseName.Substring(0, keep), "-", hash.ToString(), extension);
    }

    /// <summary>
    /// Returns every base interface of <paramref name="type"/>, recovering the ones the semantic
    /// model reports as INACCESSIBLE because this generator has not emitted their access modifier yet.
    /// </summary>
    /// <remarks>
    /// The converter emits a Go type as a bare <c>[GoType] partial interface X</c> nested in the
    /// package class and leaves the access modifier to this generator, which derives it from the Go
    /// export convention (<see cref="GetScope"/> — public for an exported name, internal otherwise).
    /// A generator cannot see its own output, so until that partial exists the declaration is a
    /// PRIVATE nested type: accessible from inside its own package class, and inaccessible from any
    /// other class in the assembly. A type in another package class that names it as a base therefore
    /// binds to an <see cref="IErrorTypeSymbol"/> with zero members, and every method the base
    /// contributes silently vanishes from the adapter/shell — while the FINAL compilation, which does
    /// have the generated partial, still demands them (CS0535). io's external test package hit this:
    /// <c>io_test.closer : io.Closer</c> and <c>io_test.testMultiWriter_sink : io.Writer</c> lost
    /// <c>Close()</c>/<c>Write()</c>, while the same <c>io.Closer</c> resolved normally as a base of
    /// <c>io.ReadCloser</c> inside its own class.
    ///
    /// The accessibility seen here is PROVISIONAL, so recovering the candidate is sound rather than a
    /// bypass: this generator is about to declare that same type <c>public</c> or <c>internal</c>, and
    /// both are reachable from anywhere in the assembly. Recovery is therefore limited to a candidate
    /// interface declared in THIS compilation's assembly — a genuinely inaccessible foreign type keeps
    /// its error symbol. A recovered base's own transitive bases are folded in too, since
    /// <see cref="ITypeSymbol.AllInterfaces"/> cannot traverse through an error symbol.
    /// </remarks>
    /// <summary>
    /// Determines if <paramref name="typeDeclaration"/> is the DEFINING part of its type, i.e. the
    /// one carrying the converter's <c>[GoType]</c> attribute.
    /// </summary>
    /// <remarks>
    /// A converted Go type has two converter-written parts: the <c>[GoType]</c> declaration in the
    /// package source, which carries the members and the definition token, and the condensed
    /// accessibility-pinning declaration in package_info.cs's <c>TypeAccessibility</c> section,
    /// which carries only the access modifier. Any lookup that resolves a type by NAME through the
    /// syntax trees can land on either one, so a lookup that goes on to read members or the
    /// definition token must prefer this one — the accessibility part is empty by construction.
    /// Without the attribute, the defining part is the converted Go type declaration (see
    /// <see cref="IsConvertedGoTypeDeclaration"/>), which by rule is never in package_info.cs.
    /// </remarks>
    public static bool IsGoTypeDefinition(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        return typeDeclaration.HasGoTypeAttribute() || typeDeclaration.IsConvertedGoTypeDeclaration();
    }

    /// <summary>
    /// Determines if <paramref name="typeDeclaration"/> carries a <c>[GoType]</c> attribute, with or
    /// without a definition argument: the converter's mark, or a hand-written file's opt-in.
    /// </summary>
    public static bool HasGoTypeAttribute(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        foreach (AttributeListSyntax attributeList in typeDeclaration.AttributeLists)
        {
            foreach (AttributeSyntax attribute in attributeList.Attributes)
            {
                string name = attribute.Name.ToString();

                if (name == GoTypeAttributeName || name == $"{GoTypeAttributeName}Attribute")
                    return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Simple name of the converter-emitted type-definition attribute.
    /// </summary>
    public const string GoTypeAttributeName = "GoType";

    /// <summary>
    /// The converter-reserved suffix of a descriptor carrier, the uninhabited interface the converter
    /// emits for a defined type over an interface (see the converter's visitTypeSpec.go).
    /// </summary>
    public const string DescriptorCarrierSuffix = "ᴅ";

    /// <summary>
    /// Simple name of the assembly-level attribute a hand-owned package carries to opt out of the
    /// converted-Go-type rule (see <see cref="IsConvertedGoTypeDeclaration"/>).
    /// </summary>
    public const string HandOwnedPackageAttributeName = "GoHandOwnedPackageAttribute";

    /// <summary>
    /// Determines if <paramref name="typeDeclaration"/> is a CONVERTED Go type without needing a
    /// <c>[GoType]</c> attribute: the converter stops writing a plain one, so the fact is where the
    /// type is declared.
    /// </summary>
    /// <remarks>
    /// A converted Go type is (1) a struct or interface, never a delegate (a Go func type: no
    /// generator reads one, and no converted delegate ever carried the attribute) and never a class
    /// (a pointer-defined type is a class, and always carries its definition argument);
    /// (2) declared directly inside a <c>*_package</c> class; (3) in a CONVERTED file, i.e. not a
    /// hand-written companion (<c>*_impl.cs</c>, <c>*_impl_test.cs</c>), not a whole-file hand
    /// conversion (<c>[module: GoManualConversion]</c>), not a metadata file (package_info.cs,
    /// package_test_info.cs, go2cs_test_host.cs, whose type parts only pin accessibility) and not
    /// generated output; and (5) not a descriptor carrier, which the converter deliberately leaves
    /// unmarked so no generator emits anything for it. Rule (4), the hand-owned PROJECT, is
    /// assembly-wide and is read by <see cref="IsHandOwnedAssembly"/>. A hand-written file keeps the
    /// attribute as its opt-in (<see cref="HasGoTypeAttribute"/>). A defined type's underlying-type
    /// definition, once the attribute's argument, is the trailing comment after the type's name
    /// (<see cref="GetDefinitionComment"/>), so (1) also admits a CLASS that carries one: a
    /// pointer-defined type, <c>partial class IntPtr /*ж&lt;nint&gt;*/;</c>.
    /// </remarks>
    public static bool IsConvertedGoTypeDeclaration(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        if (typeDeclaration is not (StructDeclarationSyntax or InterfaceDeclarationSyntax) &&
            !(typeDeclaration is ClassDeclarationSyntax && typeDeclaration.GetDefinitionComment() is not null))
        {
            return false;
        }

        if (typeDeclaration.Parent is not ClassDeclarationSyntax packageClass || !packageClass.Identifier.Text.EndsWith(PackageSuffix, StringComparison.Ordinal))
            return false;

        if (typeDeclaration.Identifier.Text.EndsWith(DescriptorCarrierSuffix, StringComparison.Ordinal))
            return false;

        return IsConvertedSourceFile(typeDeclaration.SyntaxTree);
    }

    /// <summary>
    /// Reads the underlying-type definition a converted declaration carries as a comment right after
    /// its name (or its type parameter list): <c>partial struct Duration /*num:int64*/;</c> reads
    /// <c>num:int64</c>, the text the <c>[GoType("…")]</c> argument held. Only a multi-line comment
    /// separated from the name by whitespace alone counts; null when there is none.
    /// </summary>
    public static string? GetDefinitionComment(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        SyntaxToken anchor = typeDeclaration is TypeDeclarationSyntax { TypeParameterList: { } typeParameters } ?
            typeParameters.GreaterThanToken :
            typeDeclaration.Identifier;

        foreach (SyntaxTrivia trivia in anchor.TrailingTrivia)
        {
            if (trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
            {
                string text = trivia.ToString();
                return text.Length > 4 ? text[2..^2].Trim() : null;
            }

            if (!trivia.IsKind(SyntaxKind.WhitespaceTrivia))
                break;
        }

        return null;
    }

    /// <summary>
    /// Reads a Go type declaration's underlying-type definition: the <c>[GoType("…")]</c> argument when
    /// the declaration carries the attribute (a hand-written opt-in, or a converted file from before the
    /// comment), else the definition comment of a CONVERTED declaration. Null for a plain Go type and
    /// for any other declaration.
    /// </summary>
    public static string? GetGoTypeDefinitionText(this BaseTypeDeclarationSyntax typeDeclaration)
    {
        foreach (AttributeSyntax attribute in typeDeclaration.AttributeLists.SelectMany(list => list.Attributes))
        {
            string name = attribute.Name.ToString();

            if (name != GoTypeAttributeName && name != $"{GoTypeAttributeName}Attribute")
                continue;

            string? value = attribute.ArgumentList?.Arguments.FirstOrDefault()?.ToString();

            return value is { Length: > 2 } ? value[1..^1].Trim() : null;
        }

        return typeDeclaration.IsConvertedGoTypeDeclaration() ? typeDeclaration.GetDefinitionComment() : null;
    }

    /// <summary>
    /// Determines if <paramref name="syntaxTree"/> is a file the converter wrote as Go source: not a
    /// hand-written companion, not a whole-file hand conversion, not a metadata file and not generated
    /// output. A tree with no file path (an in-memory test source) counts as converted.
    /// </summary>
    public static bool IsConvertedSourceFile(SyntaxTree syntaxTree)
    {
        string fileName = Path.GetFileName(syntaxTree.FilePath ?? string.Empty);

        if (fileName.EndsWith("_impl.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith("_impl_test.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        if (fileName.Equals("package_info.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.Equals("package_test_info.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.Equals("go2cs_test_host.cs", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        if (syntaxTree.GetRoot() is not CompilationUnitSyntax root)
            return true;

        foreach (AttributeListSyntax attributeList in root.AttributeLists)
        {
            if (attributeList.Target?.Identifier.ValueText != "module")
                continue;

            foreach (AttributeSyntax attribute in attributeList.Attributes)
            {
                string name = attribute.Name.ToString();

                if (name.EndsWith("GoManualConversion", StringComparison.Ordinal) || name.EndsWith("GoManualConversionAttribute", StringComparison.Ordinal))
                    return false;
            }
        }

        return true;
    }

    /// <summary>
    /// Determines if <paramref name="compilation"/> is a hand-owned package, which carries
    /// <c>[assembly: GoHandOwnedPackage]</c> in its own source. Inside one, a type is a Go type only
    /// by its <c>[GoType]</c> attribute.
    /// </summary>
    public static bool IsHandOwnedAssembly(Compilation compilation)
    {
        return IsHandOwnedAssembly(compilation.Assembly);
    }

    private static bool IsHandOwnedAssembly(IAssemblySymbol? assembly)
    {
        return assembly is not null && assembly.GetAttributes().Any(attribute => attribute.AttributeClass?.Name == HandOwnedPackageAttributeName);
    }

    /// <summary>
    /// Determines if <paramref name="type"/>, a type of the CURRENT compilation, is a converted Go type
    /// by rule: one of its declarations satisfies <see cref="IsConvertedGoTypeDeclaration"/> and its
    /// assembly is not a hand-owned package. A type from metadata answers false here; its compiled
    /// <c>[GoType]</c> (re-emitted by the generator) is what a reader of metadata sees.
    /// </summary>
    public static bool IsConvertedGoTypeSymbol(this INamedTypeSymbol type)
    {
        if (type.DeclaringSyntaxReferences.Length == 0 || IsHandOwnedAssembly(type.ContainingAssembly))
            return false;

        return type.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax() is BaseTypeDeclarationSyntax declaration && declaration.IsConvertedGoTypeDeclaration());
    }

    public static IEnumerable<INamedTypeSymbol> GetAllBaseInterfaces(this INamedTypeSymbol type, Compilation compilation)
    {
        HashSet<INamedTypeSymbol> seen = new(SymbolEqualityComparer.Default);
        List<INamedTypeSymbol> resolved = [];

        void Add(INamedTypeSymbol candidate)
        {
            INamedTypeSymbol recovered = RecoverProvisionallyInaccessible(candidate, compilation);

            if (!seen.Add(recovered))
                return;

            resolved.Add(recovered);

            // Only a RECOVERED base needs its own bases folded in: an accessible one already
            // contributed them through the AllInterfaces walk that reached it.
            if (!ReferenceEquals(recovered, candidate))
            {
                foreach (INamedTypeSymbol nested in recovered.AllInterfaces)
                    Add(nested);
            }
        }

        foreach (INamedTypeSymbol baseInterface in type.AllInterfaces)
            Add(baseInterface);

        return resolved;
    }

    private static INamedTypeSymbol RecoverProvisionallyInaccessible(INamedTypeSymbol candidate, Compilation compilation)
    {
        if (candidate is not IErrorTypeSymbol { CandidateReason: CandidateReason.Inaccessible } error)
            return candidate;

        foreach (ISymbol symbol in error.CandidateSymbols)
        {
            if (symbol is INamedTypeSymbol { TypeKind: TypeKind.Interface } named &&
                SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, compilation.Assembly))
                return named;
        }

        return candidate;
    }

    // Roslyn requires every AddSource hintName within a generator to be unique, and it compares them
    // CASE-INSENSITIVELY. Two Go types that differ only in case (e.g. exported `Pinner` and unexported
    // `pinner`, both real, distinct C# types) therefore collide on `…pinner.g.cs` and the generator
    // throws — suppressing ALL of its output. Disambiguate the later collisions with a numeric suffix;
    // the hintName is only an internal file label, so any unique value is correct.
    public static string GetUniqueHintName(HashSet<string> emitted, string hintName)
    {
        if (emitted.Add(hintName))
            return hintName;

        string baseName = hintName.EndsWith(".g.cs") ? hintName[..^5] : hintName;
        string suffix = hintName.EndsWith(".g.cs") ? ".g.cs" : "";

        int index = 1;
        string candidate;

        do
        {
            candidate = $"{baseName}.{index++}{suffix}";
        }
        while (!emitted.Add(candidate));

        return candidate;
    }

    public static string GetUnsanitizedIdentifier(string identifier)
    {
        return identifier.StartsWith("@") ? identifier[1..] : identifier;
    }

    // A Go method/field name that is a C# reserved keyword (encoding/gob's `string()` method)
    // must be `@`-escaped to be a valid C# identifier. Symbol names read from Roslyn
    // (IMethodSymbol.Name) arrive UNescaped, unlike syntax Identifier.Text; escape them before
    // they reach emitted C# (an explicit interface impl `ΔgobType.string()` was a parse error).
    public static string EscapeCsKeyword(string identifier)
    {
        if (identifier.StartsWith("@"))
            return identifier;

        return SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None ? $"@{identifier}" : identifier;
    }

    // A type name written in a DECLARATION position needs the escape for CONTEXTUAL keywords too:
    // `public record ΔClone()` parses as a positional RECORD DECLARATION rather than a method
    // returning the struct named `record` (net/http/fcgi's `type record struct` — CS1514/CS1519 x7 in
    // the generated value-clone). EscapeCsKeyword above covers only reserved words, which is what a
    // member-name position needs. A generic name keeps its type ARGUMENTS unescaped (`@record<T>`).
    public static string EscapeCsTypeName(string typeName)
    {
        if (string.IsNullOrWhiteSpace(typeName) || typeName.StartsWith("@"))
            return typeName;

        int angle = typeName.IndexOf('<');
        string simpleName = angle < 0 ? typeName : typeName.Substring(0, angle);

        if (SyntaxFacts.GetKeywordKind(simpleName) == SyntaxKind.None && SyntaxFacts.GetContextualKeywordKind(simpleName) == SyntaxKind.None)
            return typeName;

        return $"@{typeName}";
    }

    public static string GetScope(string identifier)
    {
        // The collision marker is an EMISSION artifact, not part of the Go identifier, so it comes
        // off before the export rule reads anything. Δ is a Greek CAPITAL, so reading it verbatim
        // answered "exported" for every Δ-renamed UNEXPORTED type — 34 in the corpus (Δsockaddr,
        // Δcommon, ΔgobType, …), each made public while its un-renamed siblings stayed internal.
        // The marker records that a name COLLIDED; it says nothing about whether Go exported it.
        //
        // The converter's generatedTypeScope strips the same prefix in the same place, and the two
        // MUST move together: they decide the modifier of two partial declarations of ONE type, and
        // C# rejects conflicting accessibility (CS0262).
        if (identifier.StartsWith(ShadowVarMarker, StringComparison.Ordinal))
            identifier = identifier.Substring(ShadowVarMarker.Length);

        if (identifier.Length == 0)
            return "internal";

        // An ANONYMOUS-type lift is not a Go identifier and carries no export status to read. The
        // converter names every anonymous struct/interface/composite-literal type with the
        // placeholder "type", which the sanitizer then marks — so the name arriving here is Δtype,
        // or Δtypeᴛ<N> when arity-suffixed. "type" is a Go KEYWORD and can never be a user type
        // name, so the match is unambiguous.
        //
        // These must stay public: a lifted anonymous interface is emitted as a BASE of the named
        // type that embedded it, and C# rejects a public interface whose base is less accessible
        // (CS0061). Measured on the AnonymousInterfaces behavioral test, whose Go declares
        // `type InlineEmbed interface { interface{ Close() error }; Flush() error }`.
        //
        // Same principle as IsEffectivelyPublic's note below: a name is the wrong oracle for
        // anything go2cs SYNTHESIZED. The converter's generatedTypeScope carries the mirror.
        //
        // A NESTED lift (typeᴛ<N>_<field>) still carries one: the Go field whose anonymous type it
        // is. Reading it makes the type's accessibility track its single use site by construction,
        // so it can never under-rank the field it exists to serve — `struct { A struct{…} }` emits
        // `public …_A A`, and an internal type there is CS0052/CS0050/CS0051 (reflect's
        // visiblefields_test, the only site in the corpus).
        if (TryGetAnonymousLiftResidue(identifier, out string residue))
        {
            if (residue.Length == 0)
                return "public";

            identifier = residue;
        }

        char firstChar = identifier[0];

        // A '_'-prefixed Go identifier (other than the bare blank '_') is unexported → internal,
        // matching the converter's getAccess. Treating any '_' lead as public made a generated
        // promoted accessor for an embedded `*_func` public while the converter's `internal partial
        // ref` declaration was internal (CS8799).
        if (firstChar == '_')
            return identifier.Length == 1 ? "public" : "internal";

        return char.IsUpper(firstChar) ? "public" : "internal";
    }

    /// <summary>
    /// Reports whether <paramref name="name"/> — already stripped of its <c>ShadowVarMarker</c> — is
    /// one of the converter's SYNTHESIZED anonymous-type names, returning in
    /// <paramref name="residue"/> the Go identifier the name still carries (empty when it carries
    /// none, which is the caller's signal that no export rule applies).
    /// </summary>
    /// <remarks>
    /// Every anonymous struct/interface/composite-literal type is named from the placeholder
    /// <c>type</c>. The shapes: <c>type</c> and <c>typeᴛ&lt;N&gt;</c> yield an empty residue (the lift
    /// itself, no Go identifier); <c>typeᴛ&lt;N&gt;_&lt;f&gt;</c> and <c>type_&lt;f&gt;</c> yield
    /// <c>&lt;f&gt;</c>, the Go FIELD whose anonymous type it is. <c>type</c> is a Go KEYWORD, so no
    /// user type can collide with the prefix; the match still excludes a user type that merely begins
    /// with it (<c>typeDecl</c>, <c>typeParam</c>) and a sanitized user type carrying the same arity
    /// marker (<c>Δsliceᴛ</c>, from a Go <c>slice</c>). Mirrors the converter's
    /// <c>anonymousLiftResidue</c>.
    /// </remarks>
    private static bool TryGetAnonymousLiftResidue(string name, out string residue)
    {
        const string Placeholder = "type";

        residue = "";

        if (!name.StartsWith(Placeholder, StringComparison.Ordinal))
            return false;

        string rest = name.Substring(Placeholder.Length);

        if (rest.Length == 0)
            return true;

        if (rest[0] == '_')
        {
            if (rest.Length == 1)
                return false;

            residue = rest.Substring(1);
            return true;
        }

        if (!rest.StartsWith(TempVarMarker, StringComparison.Ordinal))
            return false;

        rest = rest.Substring(TempVarMarker.Length);

        if (rest.Length == 0)
            return false;

        int separator = rest.IndexOf('_');

        if (separator >= 0)
        {
            string digits = rest.Substring(0, separator);
            string field = rest.Substring(separator + 1);

            if (field.Length == 0 || !IsAllDigits(digits))
                return false;

            residue = field;
            return true;
        }

        return IsAllDigits(rest);
    }

    /// <summary>Reports whether <paramref name="s"/> is a non-empty run of decimal digits.</summary>
    private static bool IsAllDigits(string s)
    {
        if (s.Length == 0)
            return false;

        foreach (char c in s)
        {
            if (!char.IsDigit(c))
                return false;
        }

        return true;
    }

    /// <summary>
    /// Reports whether <paramref name="type"/> is effectively PUBLIC, for a generated member whose
    /// own scope may not out-rank it.
    /// </summary>
    /// <remarks>
    /// An accessibility WRITTEN in source is authoritative; the Go export rule on the NAME is only
    /// the fallback for a declaration carrying none. That is the same
    /// <c>GetExplicitAccessModifier ?? GetScope</c> precedence <see cref="TypeGenerator"/> uses, and
    /// it matters because a name is the wrong oracle for anything go2cs SYNTHESIZED: a
    /// function-local type hoists to <c>&lt;Func&gt;_&lt;name&gt;</c>, whose leading case belongs to
    /// the ENCLOSING FUNCTION and says nothing about Go exportedness. The converter pins such a type
    /// <c>internal</c> (localTypeAccess), and reading the name here re-widened what it narrowed — a
    /// public adapter, twin or operator over an internal operand (CS0051/CS0052/CS0057). Foreign
    /// metadata is authoritative for the same reason: an internal type in another assembly is
    /// unreachable however its name reads.
    ///
    /// The name fallback is not vestigial. A bare <c>[GoType]</c> partial takes its modifier from the
    /// TypeGenerator's OWN output, which a single-pass sibling generator cannot see, and a nested
    /// type with no modifier reads <c>Private</c> here — that is the case the name rule answers.
    /// golib's lowercase-but-public <c>error</c> is the mirror case, and the symbol arm answers it.
    /// </remarks>
    public static bool EffectiveScopeIsPublic(ITypeSymbol type, string simpleName) => type.DeclaredAccessibility switch
    {
        Accessibility.Public => true,
        Accessibility.Internal or Accessibility.ProtectedOrInternal => false,
        _ => GetScope(simpleName) == "public"
    };

    // Returns the explicit C# access modifier on a member declaration (e.g. the converter-emitted
    // `public partial struct d`, or a method's own `internal static … B(…)`), or null when none is
    // present. This lets an explicit modifier from the converter override the name-based GetScope —
    // e.g. an unexported type the converter publicized because it is used as the type of an exported
    // field (CS0051/CS0052), or a test-declared METHOD the converter downgraded to `internal` because
    // its signature touches an unexported production type (W3a) — a case a method-NAME casing rule
    // (GetScope(identifier) in RecvGenerator) cannot see, exactly as a bare-name rule cannot see a
    // type's own publicization above. Typed over the shared MemberDeclarationSyntax base (not just
    // BaseTypeDeclarationSyntax) so both TypeGenerator's type declarations and RecvGenerator's method
    // declarations read the SAME ground truth instead of each re-deriving their own.
    public static string? GetExplicitAccessModifier(MemberDeclarationSyntax typeDeclaration)
    {
        foreach (SyntaxToken modifier in typeDeclaration.Modifiers)
        {
            switch (modifier.Kind())
            {
                case SyntaxKind.PublicKeyword:
                    return "public";
                case SyntaxKind.InternalKeyword:
                    return "internal";
                case SyntaxKind.PrivateKeyword:
                    return "private";
                case SyntaxKind.ProtectedKeyword:
                    return "protected";
            }
        }

        return null;
    }
