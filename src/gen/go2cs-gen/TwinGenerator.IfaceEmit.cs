using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace go2cs;

public sealed partial class TwinGenerator
{
    internal sealed partial class Run
    {
        // Opens the namespace and the partial types a member sits in; the result is the member's indent.
        private static string Open(StringBuilder source, INamedTypeSymbol? outer, INamespaceSymbol space, out int depth)
        {
            List<INamedTypeSymbol> chain = [];

            for (; outer is not null; outer = outer.ContainingType)
                chain.Insert(0, outer);

            string indent = "";
            depth = 0;

            if (!space.IsGlobalNamespace)
            {
                source.Append("namespace ").Append(space.ToDisplayString()).Append("\r\n{\r\n");
                indent = "    ";
                depth = 1;
            }

            foreach (INamedTypeSymbol type in chain)
            {
                source.Append(indent).Append("partial ").Append(Keyword(type)).Append(' ').Append(Escaped(type.Name)).Append("\r\n").Append(indent).Append("{\r\n");
                indent += "    ";
                depth++;
            }

            return indent;
        }

        private static void Close(StringBuilder source, int depth)
        {
            for (int i = depth - 1; i >= 0; i--)
                source.Append(new string(' ', i * 4)).Append("}\r\n");
        }

        private static string Keyword(INamedTypeSymbol type) => type.TypeKind switch
        {
            TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
            TypeKind.Interface => "interface",
            _ => type.IsRecord ? "record" : "class"
        };

        private static string Access(INamedTypeSymbol type) => type.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Private => "private",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            _ => "internal"
        };

        private void EmitIface()
        {
            if (ifaceShape == IfaceShape.None)
                return;

            StringBuilder source = new();
            source.Append("// <auto-generated/>\r\n#nullable enable annotations\r\n#pragma warning disable\r\n");

            foreach (IGrouping<ISymbol, IfaceMember> group in m_ifaceOrdered.Where(member => member.Parks).GroupBy(member => (ISymbol)member.Symbol.ContainingType, SymbolEqualityComparer.Default))
            {
                INamedTypeSymbol type = (INamedTypeSymbol)group.Key;
                string name = type.ToDisplayString(s_full);
                string indent = Open(source, type.ContainingType, type.ContainingNamespace, out int depth);

                if (IfaceHidden)
                    source.Append(indent).Append(Hidden).Append("\r\n").Append(indent).Append(Access(type)).Append(" interface ").Append(type.Name).Append(Suffix);
                else
                    source.Append(indent).Append("partial interface ").Append(Escaped(type.Name));

                source.Append("\r\n").Append(indent).Append("{\r\n");

                foreach (IfaceMember member in group)
                {
                    IMethodSymbol method = member.Symbol;
                    string result = Result(method), parameters = Parameters(method), arguments = Arguments(method), inner = indent + "    ";
                    string call = Escaped(method.Name) + "(" + arguments + ")", twin = method.Name + Suffix + "(" + arguments + ")";

                    if (IfaceHidden)
                    {
                        source.Append(inner).Append(result).Append(' ').Append(method.Name).Append(Suffix).Append('(').Append(parameters).Append(");\r\n");
                        source.Append(inner).Append("static ").Append(result).Append(' ').Append(method.Name).Append("ꞏcall(").Append(name).Append(" ᴛrecv")
                            .Append(parameters.Length > 0 ? ", " : "").Append(parameters).Append(')');

                        if (method.ReturnsVoid)
                            source.Append(" { if (ᴛrecv is ").Append(name).Append(Suffix).Append(" ᴛtwin) return ᴛtwin.").Append(twin).Append("; ᴛrecv.").Append(call).Append("; return default; }\r\n");
                        else
                            source.Append(" => ᴛrecv is ").Append(name).Append(Suffix).Append(" ᴛtwin ? ᴛtwin.").Append(twin).Append(" : new ").Append(result).Append("(ᴛrecv.").Append(call).Append(");\r\n");
                    }
                    else
                    {
                        source.Append(inner).Append(Hidden).Append("\r\n").Append(inner).Append(result).Append(' ').Append(method.Name).Append(Suffix).Append('(').Append(parameters).Append(')');

                        if (method.ReturnsVoid)
                            source.Append(" { ").Append(call).Append("; return default; }\r\n");
                        else
                            source.Append(" => new ").Append(result).Append('(').Append(call).Append(");\r\n");
                    }
                }

                source.Append(indent).Append("}\r\n");
                Close(source, depth);
            }

            foreach (Forwarder forwarder in m_forwarders)
            {
                if (forwarder.Skip is not null || !IfaceCanPark(forwarder.Member) || !CanPark(forwarder.Target))
                    continue;

                INamedTypeSymbol host = forwarder.Symbol.ContainingType;
                IMethodSymbol target = forwarder.Target!;
                string iface = forwarder.Member.ContainingType.ToDisplayString(s_full) + (IfaceHidden ? Suffix : "");
                string arguments = Arguments(forwarder.Symbol);
                string indent = Open(source, host.ContainingType, host.ContainingNamespace, out int depth);

                source.Append(indent).Append("partial ").Append(Keyword(host)).Append(' ').Append(Escaped(host.Name)).Append(IfaceHidden ? " : " + iface : "")
                    .Append("\r\n").Append(indent).Append("{\r\n");
                source.Append(indent).Append("    ").Append(Result(forwarder.Symbol)).Append(' ').Append(iface).Append('.').Append(forwarder.Member.Name).Append(Suffix)
                    .Append('(').Append(Parameters(forwarder.Symbol)).Append(") => ").Append(target.ContainingType.ToDisplayString(s_full)).Append('.')
                    .Append(target.Name).Append(Suffix).Append('(').Append(forwarder.Receiver).Append(arguments.Length > 0 ? ", " : "").Append(arguments).Append(");\r\n");
                source.Append(indent).Append("}\r\n");
                Close(source, depth);
                m_ifaceForwarded++;
            }

            Context.AddGeneratedSource("go2cs.twins.iface.g.cs", source.ToString());
        }

        private void ReportIface(StringBuilder report)
        {
            if (ifaceShape == IfaceShape.None)
                return;

            report.Append("// iface: shape=").Append(IfaceHidden ? "hidden" : "default").Append(" policy=").Append(ifaceAll ? "all" : "auto")
                .Append(" iface-members=").Append(m_ifaceOrdered.Count)
                .Append(" iface-refused=").Append(m_ifaceOrdered.Count(member => member.Refusal is not null))
                .Append(" iface-twinned=").Append(m_ifaceOrdered.Count(member => member.Parks))
                .Append(" iface-await-sites=").Append(m_ifaceAwaits)
                .Append(" forwarders=").Append(m_forwarders.Count)
                .Append(" forwarders-twinned=").Append(m_ifaceForwarded).Append("\r\n");

            foreach (IGrouping<string, IfaceMember> reason in m_ifaceOrdered.Where(member => member.Refusal is not null).GroupBy(member => member.Refusal!).OrderBy(group => group.Key, StringComparer.Ordinal))
                report.Append("// iface-refused-by ").Append(reason.Key).Append('=').Append(reason.Count()).Append("\r\n");

            foreach (IGrouping<string, Forwarder> reason in m_forwarders.Where(forwarder => forwarder.Skip is not null).GroupBy(forwarder => forwarder.Skip!).OrderBy(group => group.Key, StringComparer.Ordinal))
                report.Append("// forwarder-skipped ").Append(reason.Key).Append('=').Append(reason.Count()).Append("\r\n");

            report.Append("// forwarders-sync=").Append(m_forwarders.Count(forwarder => forwarder.Skip is null && IfaceCanPark(forwarder.Member) && !CanPark(forwarder.Target))).Append("\r\n");
        }
    }
}
