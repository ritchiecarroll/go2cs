using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace go2cs;

/// <summary>
/// The extension-host list, writer 1 (docs/phase4/DESIGN-extension-host-list.md): marks the assembly's list complete
/// (<c>[assembly: GoExtensionHostList]</c>) and lists every top-level, non-generic static class the compilation's OWN
/// sources declare (<c>[assembly: GoExtensionHost(typeof(X))]</c>). golib's extension-method scan reads the list in
/// place of <c>Assembly.GetTypes()</c> where an assembly has no raw metadata to walk, which is Native AOT.
/// </summary>
/// <remarks>
/// <para>
/// A generator never sees what a sibling generator adds, so the classes the generators ADD are listed by the
/// templates that add them (writer 2: TemplateBase.DeclareExtensionHost, and LiteralInterceptorGenerator's file).
/// This writer lists the converter's and the hand-owned sources' classes, which include every package class: the
/// templates add extension methods to it, so it is listed whether or not its own sources declare one.
/// </para>
/// <para>
/// Every static class is listed, not only those that declare an extension method in these sources: a listed class
/// with none yields nothing from the scan's method filter, while a missing one loses Go methods under Native AOT
/// alone. A <c>file</c> class cannot be named from this file; none is declared by converted sources, and GolibTests'
/// ExtensionHostListTests compares every converted assembly's list with its metadata.
/// </para>
/// </remarks>
[Generator]
public class ExtensionHostListGenerator : ISourceGenerator
{
    /// <summary>
    /// The hint name of the one file this generator writes.
    /// </summary>
    public const string HintName = "go2cs.extension-hosts.g.cs";

    public void Initialize(GeneratorInitializationContext context) { }

    public void Execute(GeneratorExecutionContext context)
    {
        Compilation compilation = context.Compilation;

        // golib's own extension methods are C# helpers its scan skips, and a compilation that cannot name the attribute
        // has nothing to write it with.
        if (compilation.AssemblyName == "golib" || compilation.GetTypeByMetadataName(GeneratedSource.ExtensionHostAttributeMetadataName) is null)
            return;

        StringBuilder source = new();

        source.Append("// <auto-generated/>\r\n");
        source.Append(GeneratedSource.ExtensionHostListDeclaration).Append("\r\n");

        foreach (string host in Hosts(compilation.Assembly.GlobalNamespace).OrderBy(name => name, StringComparer.Ordinal))
            source.Append(GeneratedSource.ExtensionHostDeclaration(host)).Append("\r\n");

        context.AddGeneratedSource(HintName, source.ToString());
    }

    // The fully qualified names of the top-level, non-generic static classes declared in this namespace and those
    // below it.
    private static IEnumerable<string> Hosts(INamespaceSymbol space)
    {
        foreach (INamedTypeSymbol type in space.GetTypeMembers())
        {
            if (type is { TypeKind: TypeKind.Class, IsStatic: true, IsGenericType: false, IsFileLocal: false })
                yield return type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        }

        foreach (INamespaceSymbol nested in space.GetNamespaceMembers())
        {
            foreach (string host in Hosts(nested))
                yield return host;
        }
    }
}
