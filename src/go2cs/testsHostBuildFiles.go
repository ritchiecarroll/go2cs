// testsHostBuildFileMarker marks the Directory.Build.props and .targets a single-package -tests run writes beside a
// test host converted OUTSIDE a go2cs root (writeTestsHostBuildFiles).
const testsHostBuildFileMarker = "<!-- Generated by go2cs -tests. -->"

// writeTestsHostBuildFiles gives a test host converted outside a go2cs root the one go2csPath rule every way of
// building it honours (COORD's S5, from the .NET 11 usability pass and R's IDE pass, 2026-11-26).
//
// Both projects of the output default go2csPath in their body: Release to $(USERPROFILE)/go2cs/, Debug to
// $(SolutionDir), and the tests csproj alone then to a relative pin. Outside a go2cs root nothing sets it first, so:
//   - a hand `dotnet run` or a VS Code open (no SolutionDir) left the PRODUCTION csproj with an empty go2csPath:
//     CS0246 and CS0234 'go.builtin', MSB9008 for gen/go2cs-gen;
//   - Visual Studio sets SolutionDir to the project's own folder, so go2csPath became the output folder and even the
//     tests csproj's pin was never reached (NU1104).
//
// A Directory.Build.props is imported BEFORE either project body, so a go2csPath it sets is non-empty by the time
// those defaults run and neither consults SolutionDir. It also defaults GoTargetOS/GoTargetArch to the platform the
// conversion read (recurseTargetPlatformLines), so the host does not build the windows flavour on another platform.
// The .targets imports golib's roll-forward targets (an executable runs on a newer major .NET when 10 is absent)
// and hands the platform to NuGet's restore walk, as a -recurse output root does.
//
// Nothing is written when the output is inside the go2cs root, or inside any other go2cs root (the standard library's
// own hosts: src/core's Directory.Build.props pins go2csPath), or under a -recurse output root (the -tests -recurse driver's phase B: that
// root's props pins it). The files import any Directory.Build.props/.targets above the output, which they would
// otherwise hide, and a value set there, an environment variable or a -p: global still wins. A foreign file at the
// output is left as it is, with a warning.
//
// A module package's host also records the module's directory (COORD's T17 ruling, 2026-11-26): GoModuleRoot, relative
// to the props as the go2csPath pin is, handed to the runtimeconfig as go2cs.ModuleRoot (and go2cs.ModuleGoMod for a
// module that ships no go.mod), which the host reads when GO2CS_MODULE_ROOT is unset (PackageAncestry.ResolveModuleRoot).
// The variable, set by the pipeline on every run, still wins, and the emitted file holds no absolute path.
func writeTestsHostBuildFiles(inputPath, outputPath string, options Options) {
	if !testsHostNeedsBuildFiles(outputPath, options.go2csPath) {
		return
	}

	pin := testsHostGo2CSPathPin(outputPath, options.go2csPath)

	propsLines := []string{
		"<Project>",
		"",
		"  " + testsHostBuildFileMarker,
		"",
		"  <!-- A Directory.Build.props higher up still applies: this file would otherwise hide it. -->",
		"  <PropertyGroup>",
		"    <_GoTestsHostParentProps>$([MSBuild]::GetPathOfFileAbove('Directory.Build.props', '$(MSBuildThisFileDirectory)../'))</_GoTestsHostParentProps>",
		"  </PropertyGroup>",
		"  <Import Project=\"$(_GoTestsHostParentProps)\" Condition=\"'$(_GoTestsHostParentProps)' != ''\" />",
		"",
		"  <!-- The go2cs runtime root both projects here compose every core/golib/analyzer reference from. Set before",
		"       either project body, so neither falls back to $(SolutionDir), which an IDE sets to this folder or not",
		"       at all. An environment variable, a -p:go2csPath global or a higher props still wins. -->",
		"  <PropertyGroup Condition=\"'$(go2csPath)' == ''\">",
		fmt.Sprintf("    <go2csPath>%s</go2csPath>", escapeXMLAttributeValue(pin)),
		"  </PropertyGroup>",
	}

	propsLines = append(propsLines, recurseTargetPlatformLines(options.targetPlatform)...)
	propsLines = append(propsLines, testsHostModuleRootLines(inputPath, outputPath, options)...)
	propsLines = append(propsLines, "", "</Project>", "")

	targetsLines := []string{
		"<Project>",
		"",
		"  " + testsHostBuildFileMarker,
		"",
		"  <!-- A Directory.Build.targets higher up still applies: this file would otherwise hide it. -->",
		"  <PropertyGroup>",
		"    <_GoTestsHostParentTargets>$([MSBuild]::GetPathOfFileAbove('Directory.Build.targets', '$(MSBuildThisFileDirectory)../'))</_GoTestsHostParentTargets>",
		"  </PropertyGroup>",
		"  <Import Project=\"$(_GoTestsHostParentTargets)\" Condition=\"'$(_GoTestsHostParentTargets)' != ''\" />",
		"",
		"  <!-- The host runs on a newer major .NET when no .NET 10 runtime is installed (golib's go.lib.rollforward.targets);",
		"       the guard keeps a second import inert. -->",
		"  <Import Project=\"$(go2csPath)core/golib/buildTransitive/go.lib.rollforward.targets\"",
		"          Condition=\"'$(GoLibRollForwardTargetsImported)' != 'true' and '$(go2csPath)' != '' and Exists('$(go2csPath)core/golib/buildTransitive/go.lib.rollforward.targets')\" />",
	}

	if len(recurseTargetPlatformLines(options.targetPlatform)) > 0 {
		targetsLines = append(targetsLines,
			"",
			"  <!-- NuGet's restore walk evaluates referenced projects without ProjectReference metadata, so the platform the",
			"       props hand down is handed to the restore too. -->",
			"  <PropertyGroup Condition=\"'$(GoTargetOS)' != '' and '$(GoTargetArch)' != ''\">",
			"    <_GenerateRestoreGraphProjectEntryInputProperties>$(_GenerateRestoreGraphProjectEntryInputProperties);GoTargetOS=$(GoTargetOS);GoTargetArch=$(GoTargetArch)</_GenerateRestoreGraphProjectEntryInputProperties>",
			"  </PropertyGroup>",
		)
	}

	targetsLines = append(targetsLines, "", "</Project>", "")

	writeTestsHostBuildFile(filepath.Join(outputPath, "Directory.Build.props"), propsLines)
	writeTestsHostBuildFile(filepath.Join(outputPath, "Directory.Build.targets"), targetsLines)
}

// testsHostNeedsBuildFiles reports whether a -tests output directory lacks a go2csPath pin of its own: it is not
// inside the configured go2cs root, nor under ANY go2cs root (the predicate -tests self-locates by, findGo2CSRootAbove:
// a clone's src/core while a deployed root is configured, P3's read), and no ancestor carries a -recurse output
// root's generated Directory.Build.props.
func testsHostNeedsBuildFiles(outputPath, go2csPath string) bool {
	if outputPath == "" || go2csPath == "" || isPathUnder(outputPath, go2csPath) || findGo2CSRootAbove(outputPath) != "" {
		return false
	}

	for dir := filepath.Dir(outputPath); ; dir = filepath.Dir(dir) {
		if contents, err := os.ReadFile(filepath.Join(dir, "Directory.Build.props")); err == nil && strings.Contains(string(contents), generatedBuildFileMarker) {
			return false
		}

		if parent := filepath.Dir(dir); parent == dir {
			return true
		}
	}
}

// testsHostModuleRootLines records a module package's module root (and a synthesized go.mod, when the module ships
// none) for a by-hand run: the values testHostModuleEnv hands the pipeline's run, as paths relative to the props.
func testsHostModuleRootLines(inputPath, outputPath string, options Options) []string {
	var lines []string

	for _, entry := range testHostModuleEnv(inputPath, options) {
		name, value, _ := strings.Cut(entry, "=")
		property, key := "GoModuleRoot", "go2cs.ModuleRoot"

		if name == "GO2CS_MODULE_GOMOD" {
			property, key = "GoModuleGoMod", "go2cs.ModuleGoMod"
		} else if len(lines) == 0 {
			lines = append(lines,
				"",
				"  <!-- The module this package belongs to, for a by-hand run: the host stages a copy of it, as go test runs the",
				"       package inside the module tree. The runtimeconfig carries it to the host, which reads it only when",
				"       GO2CS_MODULE_ROOT is unset; that variable (none included) or a -p: global still wins. -->",
			)
		}

		lines = append(lines,
			fmt.Sprintf("  <PropertyGroup Condition=\"'$(%s)' == ''\">", property),
			fmt.Sprintf("    <%s>$([System.IO.Path]::GetFullPath('%s'))</%s>", property, escapeXMLAttributeValue(testsHostRelativePath(outputPath, value)), property),
			"  </PropertyGroup>",
			fmt.Sprintf("  <ItemGroup Condition=\"'$(%s)' != ''\">", property),
			fmt.Sprintf("    <RuntimeHostConfigurationOption Include=\"%s\" Value=\"$(%s)\" />", key, property),
			"  </ItemGroup>",
		)
	}

	return lines
}

// testsHostRelativePath spells target relative to the build file at outputPath when the two share a volume, else as
// the absolute path itself.
func testsHostRelativePath(outputPath, target string) string {
	if rel, err := filepath.Rel(outputPath, target); err == nil {
		return "$(MSBuildThisFileDirectory)" + filepath.ToSlash(rel)
	}

	return filepath.ToSlash(target)
}

// testsHostGo2CSPathPin is the go2csPath default for a host at outputPath: relative to the build file when the two
// share a volume, as the tests csproj's own pin is (writeTestProject), else the root itself.
func testsHostGo2CSPathPin(outputPath, go2csPath string) string {
	if rel, err := filepath.Rel(outputPath, go2csPath); err == nil {
		return "$(MSBuildThisFileDirectory)" + strings.TrimRight(filepath.ToSlash(rel), "/") + "/"
	}

	return strings.TrimRight(filepath.ToSlash(go2csPath), "/") + "/"
}

// writeTestsHostBuildFile writes one generated build file, leaving a foreign one in place with a warning.
func writeTestsHostBuildFile(path string, lines []string) {
	if existing, err := os.ReadFile(path); err == nil && !strings.Contains(string(existing), testsHostBuildFileMarker) {
		fmt.Printf("WARNING: %s already exists and was not written by go2cs — left as is.\n", path)
		fmt.Printf("         A hand build of the test host, or an IDE, needs go2csPath set: add -p:go2csPath=<go2cs root>/.\n")
		return
	}

	contents := []byte(strings.Join(lines, "\r\n"))

	if !needToWriteFile(path, contents) {
		return
	}

	if err := os.WriteFile(path, contents, 0644); err != nil {
		fmt.Printf("WARNING: failed to write %q: %v\n", path, err)
	}
}
