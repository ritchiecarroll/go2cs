// cgo Phase 2 increment 5 (docs/phase4/DESIGN-cgo-phase2-pinvoke.md §11.20): the converter's cgo route. Under -cgo a
// package converts when every C use it makes is in Phase 2's set, and is otherwise refused, before anything is
// written, with each use that is not and the phase that owns it.
//
// The route reads cmd/cgo's output, not the package's import "C" sources: the trees cmd/cgo rewrote from them, which
// convert under their sources' names, and cmd/cgo's types file, whose C type and constant declarations become the
// bindings file <package>.cgo.cs beside the bindings themselves. Its plumbing (the _Cfunc_ bodies, the linkname
// variables, _cgoCheckPointer and its kin) has no C# meaning and is dropped, so every USE of what that file declares
// must be consumed by a shape the route recognises, and any other use refuses (§11.20, M2): a census, not a matcher,
// is what keeps an unrecognised shape from converting into a call to something the bindings dropped.

// cgoOfflineTrees is set only by tests (cgoDriver_test.go): the package directory holds checked-in cmd/cgo output as
// plain files, which load at CGO_ENABLED=0 with runtime/cgo's Incomplete overlaid, and whose roles are read from
// content alone. A host with no C compiler cannot make cmd/cgo's output, so this is how the route is tested there.
var cgoOfflineTrees bool

// cgoOfflineBuildFlags are the offline load's build flags: ONE -tags flag, the user's tags and cgo. go keeps only the
// last -tags it is given, so a second flag for cgo would drop the user's, and every file under them.
func cgoOfflineBuildFlags(options Options) []string {
	offline := options
	offline.buildTags = append(append([]string{}, options.buildTags...), "cgo")

	return offline.loaderBuildFlags()
}

// cgoCaptureOverride is set only by tests: it answers the library capture, each symbol's load-time name and the C
// toolchain's version line, in place of a C toolchain.
var cgoCaptureOverride func(symbols []string) ([]cgoSymbolLibrary, string, error)

// cgoIncompleteOverlay declares runtime/cgo's Incomplete exactly as cgo.go does, for an offline load: at CGO_ENABLED=0
// the file that declares it drops out, and every cmd/cgo types file names it.
const cgoIncompleteOverlay = `package cgo

import "internal/runtime/sys"

type Incomplete struct {
	_ sys.NotInHeap
}
`

// cgoGeneratedHeader opens each file cmd/cgo writes for a package (cmd/cgo out.go).
const cgoGeneratedHeader = "// Code generated by cmd/cgo; DO NOT EDIT."

// The route's package state, set by planCgoRoute and reset with the rest of the package state.
var (
	// cgoRouteActive is set while a package converts through the cgo route: what the visitor does only to cmd/cgo's
	// trees (dropping the parentheses cmd/cgo writes around a C name, unwrapping its check closures) is gated on it,
	// which is what keeps every other package's emission unchanged.
	cgoRouteActive bool

	// cgoRouteFunctions maps each _Cfunc_ or _C2func_ name the package calls to its pseudo-package member.
	cgoRouteFunctions map[string]string

	// cgoCheckClosures maps each recognised call of cmd/cgo's check closure to its unwrap.
	cgoCheckClosures map[*ast.CallExpr]*cgoCheckClosure

	// cgoBindingsWritten is set when this conversion wrote the package's bindings file.
	cgoBindingsWritten bool
)

// cgoCheckClosure is one call through cmd/cgo's pointer-check closure, unwrapped: the call the closure makes, and what
// each of the closure's own variables stands for there.
type cgoCheckClosure struct {
	call      *ast.CallExpr
	arguments map[types.Object]cgoClosureArgument
}

// cgoClosureArgument is what one of a check closure's variables stands for: an expression, which for
// `var _cgoN T = X` is converted to the type the closure declared.
type cgoClosureArgument struct {
	value    ast.Expr
	declared ast.Expr
}

// cgoRoute is a package's conversion through the cgo route.
type cgoRoute struct {
	trees     []syntaxSourceFile // the trees that convert, each under its output name, the bindings host last
	typesFile *ast.File          // cmd/cgo's types file, reduced to its imports and its C type and constant declarations
	folder    string             // the bindings file's folder: its one target's, `<goos>-<arch>` (§11.20, S3)
	header    string             // the bindings file's header (§4.1, §11.20)
	members   string             // the bindings: the pseudo-package's wrappers, mirrors and registration
}

// cgoUseRefusal is one C use the route refuses, at the source position that wrote it.
type cgoUseRefusal struct {
	position token.Position
	text     string
}

// cgoTreeRoles sorts a package's trees: cmd/cgo's rewrite of each import "C" source, cmd/cgo's types file and its
// dynamic-import file, and plain Go source. A tree that opens with cmd/cgo's header and is none of these, and a second
// tree for a source that already has one, are refused rather than guessed at (§11.20, S2).
func cgoTreeRoles(pkg *packages.Package) (sources []syntaxSourceFile, typesFile *ast.File, imports map[string]bool, refusals []cgoUseRefusal) {
	goFiles := map[string]bool{}

	for _, path := range pkg.GoFiles {
		goFiles[filepath.Clean(path)] = true
	}

	mapped := map[string]bool{}

	for _, file := range pkg.Syntax {
		generated := pkg.Fset.PositionFor(file.Package, false).Filename
		source := pkg.Fset.PositionFor(file.Package, true).Filename

		if source == generated {
			source = ""
		}

		fromCmdCgo := cgoFileHasComment(file, func(text string) bool { return text == cgoGeneratedHeader })
		refuse := func(text string) {
			refusals = append(refusals, cgoUseRefusal{position: pkg.Fset.PositionFor(file.Package, false), text: text})
		}

		// On the real route cmd/cgo's trees are compiled files, never the package's own sources.
		if fromCmdCgo && !cgoOfflineTrees && goFiles[filepath.Clean(generated)] {
			refuse(fmt.Sprintf("%s: a Go source of the package carries cmd/cgo's header", filepath.Base(generated)))
			continue
		}

		switch {
		case cgoDeclaresTopLevel(file, "_Cgo_ptr"):
			if typesFile != nil {
				refuse(fmt.Sprintf("%s: cmd/cgo output not recognized: a second types file", filepath.Base(generated)))
				continue
			}

			typesFile = file
		case len(file.Decls) == 0 && cgoFileHasComment(file, func(text string) bool { return strings.HasPrefix(text, "//go:cgo_import_dynamic ") }):
			// cmd/cgo's _cgo_import.go: the symbols its own binary imports, each by the name it imports it under
			// (the local name of each //go:cgo_import_dynamic line; `_` names a library alone). Nothing of it is
			// converted; the route reads it to bind only a name C really calls (cgoImportedByCmdCgo).
			if imports == nil {
				imports = map[string]bool{}
			}

			for _, group := range file.Comments {
				for _, comment := range group.List {
					if fields := strings.Fields(comment.Text); len(fields) >= 2 && fields[0] == "//go:cgo_import_dynamic" && fields[1] != "_" {
						imports[fields[1]] = true
					}
				}
			}
		case fromCmdCgo && source != "":
			if mapped[filepath.Clean(source)] {
				refuse(fmt.Sprintf("two cmd/cgo trees map to %s", filepath.Base(source)))
				continue
			}

			mapped[filepath.Clean(source)] = true
			sources = append(sources, syntaxSourceFile{file: file, path: generated, output: strings.TrimSuffix(filepath.Base(source), ".go")})
		case fromCmdCgo:
			refuse(fmt.Sprintf("%s: cmd/cgo output not recognized", filepath.Base(generated)))
		default:
			sources = append(sources, syntaxSourceFile{file: file, path: generated})
		}
	}

	return sources, typesFile, imports, refusals
}

// cgoPlumbingImport is the name cmd/cgo imports unsafe under for its own use: the result type of a check closure that
// returns a void pointer (`func() _cgo_unsafe.Pointer { … }()`).
const cgoPlumbingImport = "_cgo_unsafe"

// cgoDropPlumbingImport removes cmd/cgo's own import of unsafe from a tree it rewrote. Every check closure converts as
// the call it makes, so nothing that converts names the import, and it would otherwise reach the C# as a using.
func cgoDropPlumbingImport(file *ast.File) {
	plumbing := func(spec *ast.ImportSpec) bool {
		return spec.Name != nil && spec.Name.Name == cgoPlumbingImport
	}

	file.Imports = slices.DeleteFunc(file.Imports, plumbing)

	var decls []ast.Decl

	for _, decl := range file.Decls {
		if genDecl, ok := decl.(*ast.GenDecl); ok && genDecl.Tok == token.IMPORT {
			genDecl.Specs = slices.DeleteFunc(genDecl.Specs, func(spec ast.Spec) bool {
				importSpec, ok := spec.(*ast.ImportSpec)
				return ok && plumbing(importSpec)
			})

			if len(genDecl.Specs) == 0 {
				continue
			}
		}

		decls = append(decls, decl)
	}

	file.Decls = decls
}

// cgoDropDirectiveComments removes cmd/cgo's own comments from a tree it rewrote: its generated-file header, which
// describes the Go file and not the C#, and its //line and /*line*/ directives, which place each rewritten name back at
// its source position and are not the source's comments. Position lookups already applied them (N3), so the comments
// carry nothing a converted file should show, and -comments would otherwise write every one.
func cgoDropDirectiveComments(file *ast.File) {
	emptied := map[*ast.CommentGroup]bool{}
	var groups []*ast.CommentGroup

	for _, group := range file.Comments {
		var kept []*ast.Comment

		for _, comment := range group.List {
			if comment.Text != cgoGeneratedHeader && !strings.HasPrefix(comment.Text, "//line ") && !strings.HasPrefix(comment.Text, "/*line ") {
				kept = append(kept, comment)
			}
		}

		if len(kept) == 0 {
			emptied[group] = true
			continue
		}

		group.List = kept
		groups = append(groups, group)
	}

	file.Comments = groups

	if len(emptied) == 0 {
		return
	}

	// A doc or line comment that held only directives is no comment at all.
	clear := func(group **ast.CommentGroup) {
		if *group != nil && emptied[*group] {
			*group = nil
		}
	}

	clear(&file.Doc)

	ast.Inspect(file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.FuncDecl:
			clear(&n.Doc)
		case *ast.GenDecl:
			clear(&n.Doc)
		case *ast.Field:
			clear(&n.Doc)
			clear(&n.Comment)
		case *ast.ImportSpec:
			clear(&n.Doc)
			clear(&n.Comment)
		case *ast.ValueSpec:
			clear(&n.Doc)
			clear(&n.Comment)
		case *ast.TypeSpec:
			clear(&n.Doc)
			clear(&n.Comment)
		}

		return true
	})
}

// cgoFileHasComment reports whether any comment line of a file is one the predicate admits.
func cgoFileHasComment(file *ast.File, admits func(text string) bool) bool {
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if admits(comment.Text) {
				return true
			}
		}
	}

	return false
}

// cgoDeclaresTopLevel reports whether a file declares a top-level function of the name.
func cgoDeclaresTopLevel(file *ast.File, name string) bool {
	for _, decl := range file.Decls {
		if funcDecl, ok := decl.(*ast.FuncDecl); ok && funcDecl.Recv == nil && funcDecl.Name.Name == name {
			return true
		}
	}

	return false
}

// cgoTypesDeclarations reduces cmd/cgo's types file to what converts: its imports, less runtime/cgo, and its C type and
// constant declarations, which 3d's route emits into the pseudo-package. The rest is cmd/cgo's plumbing.
func cgoTypesDeclarations(file *ast.File, declarations map[types.Object]cgoDeclaration, info *types.Info) *ast.File {
	reduced := &ast.File{Doc: nil, Package: file.Package, Name: file.Name, FileStart: file.FileStart, FileEnd: file.FileEnd}

	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)

		if !ok {
			continue
		}

		switch genDecl.Tok {
		case token.IMPORT:
			var specs []ast.Spec

			for _, spec := range genDecl.Specs {
				importSpec := spec.(*ast.ImportSpec)

				if importSpec.Path.Value != `"runtime/cgo"` {
					specs = append(specs, importSpec)
					reduced.Imports = append(reduced.Imports, importSpec)
				}
			}

			if len(specs) > 0 {
				copied := *genDecl
				copied.Specs = specs
				reduced.Decls = append(reduced.Decls, &copied)
			}
		case token.TYPE, token.CONST:
			if cgoDeclaresOnlyCNames(genDecl, declarations, info) {
				reduced.Decls = append(reduced.Decls, genDecl)
			}
		}
	}

	return reduced
}

// cgoDeclaresOnlyCNames reports whether every name a type or const declaration declares is a C type or constant.
func cgoDeclaresOnlyCNames(genDecl *ast.GenDecl, declarations map[types.Object]cgoDeclaration, info *types.Info) bool {
	declared := 0

	for _, spec := range genDecl.Specs {
		var names []*ast.Ident

		switch spec := spec.(type) {
		case *ast.TypeSpec:
			names = []*ast.Ident{spec.Name}
		case *ast.ValueSpec:
			names = spec.Names
		}

		for _, name := range names {
			declaration, found := declarations[info.Defs[name]]

			if !found || !cgoPseudoPackageKind(declaration.kind) {
				return false
			}

			declared++
		}
	}

	return declared > 0
}

// cgoCheckClosureFunc answers the function literal a call through cmd/cgo's check closure calls: a call of a literal,
// with no arguments, whose body calls _cgoCheckPointer.
func cgoCheckClosureFunc(call *ast.CallExpr, info *types.Info, plumbing map[types.Object]bool) *ast.FuncLit {
	funcLit, ok := ast.Unparen(call.Fun).(*ast.FuncLit)

	if !ok || len(call.Args) > 0 || !cgoCallsCheckPointer(funcLit, info, plumbing) {
		return nil
	}

	return funcLit
}

// cgoCallsCheckPointer reports whether a node calls cmd/cgo's _cgoCheckPointer.
func cgoCallsCheckPointer(node ast.Node, info *types.Info, plumbing map[types.Object]bool) bool {
	found := false

	ast.Inspect(node, func(n ast.Node) bool {
		if ident, ok := n.(*ast.Ident); ok && ident.Name == "_cgoCheckPointer" && plumbing[info.Uses[ident]] {
			found = true
		}

		return !found
	})

	return found
}

// cgoClosureVariable answers the index a closure variable's name carries after prefix (`_cgo3` is 3), or -1.
func cgoClosureVariable(ident *ast.Ident, prefix string) int {
	if ident == nil {
		return -1
	}

	digits, found := strings.CutPrefix(ident.Name, prefix)

	if !found || digits == "" {
		return -1
	}

	index := 0

	for _, digit := range digits {
		if digit < '0' || digit > '9' {
			return -1
		}

		index = index*10 + int(digit-'0')
	}

	return index
}

// cgoRecognizeCheckClosure unwraps a non-deferred check closure in the forms cmd/cgo writes (cmd/cgo gcc.go,
// rewriteCall and checkAddr): first each argument's definition, in order (`_cgoBaseN := &x; _cgoN := _cgoBaseN`, or the
// same under conversions, for the address form; `_cgoN := p` for the variable form; `var _cgoN T = x` for an argument
// that needs no check), then one check of each checked argument, then the call itself, of exactly _cgo0 … _cgoN-1 in
// order, returned or as a statement. Anything else is not recognised, and the census refuses it.
func cgoRecognizeCheckClosure(funcLit *ast.FuncLit, info *types.Info, plumbing map[types.Object]bool) *cgoCheckClosure {
	return cgoRecognizeCheckClosureStatements(funcLit.Body.List, info, plumbing)
}

// cgoRecognizeCheckClosureStatements is cgoRecognizeCheckClosure over the statements themselves. The deferred form
// spreads them over two bodies (cgoDeferredCheckClosure), and they read here as the one list they are.
func cgoRecognizeCheckClosureStatements(statements []ast.Stmt, info *types.Info, plumbing map[types.Object]bool) *cgoCheckClosure {
	const (
		formPlain = iota
		formVariable
		formAddress
	)

	closure := &cgoCheckClosure{arguments: map[types.Object]cgoClosureArgument{}}
	forms := map[int]int{}
	argumentObjects := map[int]types.Object{}
	baseValues := map[int]ast.Expr{}
	i := 0

	// The definitions.
	for ; i < len(statements); i++ {
		switch statement := statements[i].(type) {
		case *ast.AssignStmt:
			if statement.Tok != token.DEFINE || len(statement.Lhs) != 1 || len(statement.Rhs) != 1 {
				return nil
			}

			lhs, _ := statement.Lhs[0].(*ast.Ident)

			if index := cgoClosureVariable(lhs, "_cgoBase"); index >= 0 {
				if _, seen := baseValues[index]; seen {
					return nil
				}

				baseValues[index] = statement.Rhs[0]
				closure.arguments[info.Defs[lhs]] = cgoClosureArgument{value: statement.Rhs[0]}
				continue
			}

			index := cgoClosureVariable(lhs, "_cgo")

			if index != len(argumentObjects) {
				return nil
			}

			form := formVariable

			if _, based := baseValues[index]; based {
				form = formAddress

				if !cgoMentionsOnce(statement.Rhs[0], "_cgoBase", index) {
					return nil
				}
			}

			forms[index] = form
			argumentObjects[index] = info.Defs[lhs]
			closure.arguments[info.Defs[lhs]] = cgoClosureArgument{value: statement.Rhs[0]}
			continue
		case *ast.DeclStmt:
			genDecl, ok := statement.Decl.(*ast.GenDecl)

			if !ok || genDecl.Tok != token.VAR || len(genDecl.Specs) != 1 {
				return nil
			}

			spec := genDecl.Specs[0].(*ast.ValueSpec)

			if len(spec.Names) != 1 || len(spec.Values) != 1 || spec.Type == nil {
				return nil
			}

			index := cgoClosureVariable(spec.Names[0], "_cgo")

			if index != len(argumentObjects) {
				return nil
			}

			forms[index] = formPlain
			argumentObjects[index] = info.Defs[spec.Names[0]]
			closure.arguments[info.Defs[spec.Names[0]]] = cgoClosureArgument{value: spec.Values[0], declared: spec.Type}
			continue
		}

		break
	}

	// The checks: one for each checked argument, of the variable it is checked through.
	checked := map[int]bool{}

	for ; i < len(statements); i++ {
		exprStmt, ok := statements[i].(*ast.ExprStmt)

		if !ok {
			break
		}

		call, ok := exprStmt.X.(*ast.CallExpr)

		if !ok || len(call.Args) != 2 {
			break
		}

		callee, ok := call.Fun.(*ast.Ident)

		if !ok || callee.Name != "_cgoCheckPointer" || !plumbing[info.Uses[callee]] {
			break
		}

		target, _ := call.Args[0].(*ast.Ident)
		index := cgoClosureVariable(target, "_cgoBase")

		if index >= 0 {
			if forms[index] != formAddress || !cgoIsZeroEqualsZero(call.Args[1]) {
				return nil
			}
		} else if index = cgoClosureVariable(target, "_cgo"); index >= 0 {
			if form, defined := forms[index]; !defined || form != formVariable || !cgoIsNil(call.Args[1]) {
				return nil
			}
		} else {
			return nil
		}

		if checked[index] {
			return nil
		}

		checked[index] = true
	}

	for index, form := range forms {
		if (form == formPlain) == checked[index] {
			return nil
		}
	}

	// The call itself, last.
	if i != len(statements)-1 {
		return nil
	}

	var call *ast.CallExpr

	switch statement := statements[i].(type) {
	case *ast.ReturnStmt:
		if len(statement.Results) == 1 {
			call, _ = statement.Results[0].(*ast.CallExpr)
		}
	case *ast.ExprStmt:
		call, _ = statement.X.(*ast.CallExpr)
	}

	if call == nil || len(call.Args) != len(argumentObjects) {
		return nil
	}

	callee, ok := ast.Unparen(call.Fun).(*ast.Ident)

	if !ok || !(strings.HasPrefix(callee.Name, "_Cfunc_") || strings.HasPrefix(callee.Name, "_C2func_")) || !plumbing[info.Uses[callee]] {
		return nil
	}

	for index, arg := range call.Args {
		ident, ok := arg.(*ast.Ident)

		if !ok || info.Uses[ident] != argumentObjects[index] {
			return nil
		}
	}

	closure.call = call
	return closure
}

// cgoReceiverAddresses answers each `unsafe.Pointer(p)` in a tree, inside a method with a pointer receiver, whose operand
// has that receiver's own pointer type: the receiver itself, or any other pointer of its type. The converter renders a
// pointer receiver as the value it points at, by reference, and inside such a method it mints that conversion from a
// reference alone (convCallExpr's FromRef arm, which is keyed on the operand's TYPE): a bare number, of storage nothing
// pins, that carries no box and that no registry knows. Everywhere else that is a recorded residual. In a cgo package
// it is the one address of Go memory a void pointer's door could not tell from C memory, with no uintptr in the
// source, so the route refuses it by name (Phase 3, increment 3.1; found while the pin moments were listed for the
// review of that door). A function that takes the pointer as a parameter mints it with its box, which is the way
// round the refusal names.
func cgoReceiverAddresses(file *ast.File, info *types.Info) []token.Pos {
	var positions []token.Pos

	for _, decl := range file.Decls {
		funcDecl, ok := decl.(*ast.FuncDecl)

		if !ok || funcDecl.Body == nil || funcDecl.Recv == nil {
			continue
		}

		// The receiver's type is read from the method's SIGNATURE, never through the receiver's name: a receiver with
		// no name, or the blank one, defines no object, and the conversion inside such a method is minted the same way
		// (the review of increment 3.1, finding 5).
		method, _ := info.Defs[funcDecl.Name].(*types.Func)

		if method == nil {
			continue
		}

		signature, _ := method.Type().(*types.Signature)

		if signature == nil || signature.Recv() == nil {
			continue
		}

		receiverType := signature.Recv().Type()

		if _, isPointer := receiverType.Underlying().(*types.Pointer); !isPointer {
			continue
		}

		ast.Inspect(funcDecl.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)

			if !ok || len(call.Args) != 1 {
				return true
			}

			conversion, isType := info.Types[call.Fun]

			if !isType || !conversion.IsType() {
				return true
			}

			if basic, ok := conversion.Type.Underlying().(*types.Basic); !ok || basic.Kind() != types.UnsafePointer {
				return true
			}

			if operand := info.TypeOf(call.Args[0]); operand != nil && types.Identical(operand, receiverType) {
				positions = append(positions, call.Pos())
			}

			return true
		})
	}

	return positions
}

// cgoDirectlyChecks reports whether one of a body's own statements is a call of cmd/cgo's _cgoCheckPointer: the body is
// a check closure's, not a function that holds one further in.
func cgoDirectlyChecks(body *ast.BlockStmt, info *types.Info, plumbing map[types.Object]bool) bool {
	for _, statement := range body.List {
		if exprStmt, ok := statement.(*ast.ExprStmt); ok {
			if call, ok := exprStmt.X.(*ast.CallExpr); ok {
				if callee, ok := call.Fun.(*ast.Ident); ok && callee.Name == "_cgoCheckPointer" && plumbing[info.Uses[callee]] {
					return true
				}
			}
		}
	}

	return false
}

// cgoDeferredCheckClosure reads the form cmd/cgo gives `defer C.f(args)` when an argument needs its pointer check
// (cmd/cgo gcc.go, rewriteCall): `defer func() func() { DEFINITIONS; return func() { CHECKS; CALL } }()()`. The outer
// literal runs at the defer and evaluates the arguments; the literal it returns is what is deferred, and it checks and
// calls. It answers the two bodies as the one statement list a check closure has, or nil for any other deferred call:
// a deferred Go function that calls C further in is an ordinary defer, and its own check closures are read where they
// are met.
func cgoDeferredCheckClosure(deferred *ast.CallExpr, info *types.Info, plumbing map[types.Object]bool) []ast.Stmt {
	made, ok := deferred.Fun.(*ast.CallExpr)

	if !ok || len(deferred.Args) > 0 || len(made.Args) > 0 {
		return nil
	}

	outer, ok := ast.Unparen(made.Fun).(*ast.FuncLit)

	if !ok || len(outer.Body.List) == 0 {
		return nil
	}

	last := len(outer.Body.List) - 1
	returned, ok := outer.Body.List[last].(*ast.ReturnStmt)

	if !ok || len(returned.Results) != 1 {
		return nil
	}

	inner, ok := returned.Results[0].(*ast.FuncLit)

	if !ok || !cgoDirectlyChecks(inner.Body, info, plumbing) {
		return nil
	}

	return append(append([]ast.Stmt{}, outer.Body.List[:last]...), inner.Body.List...)
}

// cgoLowerDeferredClosure makes a recognised deferred check closure the deferred call it stands for: cmd/cgo's own call
// of the C function, each argument the expression its closure variable was defined as. Go evaluates a deferred call's
// arguments at the defer, in order, which is when and how the outer literal evaluated them; the call runs at return,
// which is when the inner literal ran. The pointer check ran there too, and the wrapper makes it where it runs.
//
// An argument cmd/cgo declared at its parameter's type (`var _cgoN T = x`) is x itself: x is assignable to T, and T is
// the parameter's type, so it is the same implicit conversion a call makes.
func cgoLowerDeferredClosure(closure *cgoCheckClosure, info *types.Info) *ast.CallExpr {
	var resolve func(expr ast.Expr) ast.Expr

	resolve = func(expr ast.Expr) ast.Expr {
		return astutil.Apply(expr, func(cursor *astutil.Cursor) bool {
			if ident, ok := cursor.Node().(*ast.Ident); ok {
				if argument, found := closure.arguments[info.Uses[ident]]; found && info.Uses[ident] != nil {
					cursor.Replace(resolve(argument.value))
					return false
				}
			}

			return true
		}, nil).(ast.Expr)
	}

	for index, arg := range closure.call.Args {
		closure.call.Args[index] = resolve(arg)
	}

	return closure.call
}

// cgoMentionsOnce reports whether an expression names prefix<index> exactly once.
func cgoMentionsOnce(expr ast.Expr, prefix string, index int) bool {
	count := 0

	ast.Inspect(expr, func(n ast.Node) bool {
		if ident, ok := n.(*ast.Ident); ok && cgoClosureVariable(ident, prefix) == index {
			count++
		}

		return true
	})

	return count == 1
}

// cgoIsZeroEqualsZero reports whether an expression is cmd/cgo's `0 == 0`, its check's "the pointee's members only".
func cgoIsZeroEqualsZero(expr ast.Expr) bool {
	binary, ok := expr.(*ast.BinaryExpr)

	if !ok || binary.Op != token.EQL {
		return false
	}

	x, xok := binary.X.(*ast.BasicLit)
	y, yok := binary.Y.(*ast.BasicLit)

	return xok && yok && x.Value == "0" && y.Value == "0"
}

// cgoIsNil reports whether an expression is the identifier nil.
func cgoIsNil(expr ast.Expr) bool {
	ident, ok := expr.(*ast.Ident)
	return ok && ident.Name == "nil"
}

// cgoCalledFunction answers the cmd/cgo function a statement's call through a check closure calls, for a refusal's name.
func cgoCalledFunction(node ast.Node, declarations map[types.Object]cgoDeclaration, info *types.Info) string {
	name := ""

	ast.Inspect(node, func(n ast.Node) bool {
		if ident, ok := n.(*ast.Ident); ok && name == "" {
			if declaration, found := declarations[info.Uses[ident]]; found && (declaration.kind == cgoFunc || declaration.kind == cgoErrnoFunc) {
				name = "C." + declaration.cName
			}
		}

		return name == ""
	})

	if name == "" {
		return "a C function"
	}

	return name
}

// planCgoRoute plans a package's conversion through the cgo route: the trees that convert and the bindings. It returns
// nil when the package holds no cmd/cgo output (cmd/cgo did not run), so the caller's own refusal stands, and refuses,
// exiting before anything is written, when any C use is outside Phase 2's set.
func planCgoRoute(pkg *packages.Package, options Options, load cgoLoad) *cgoRoute {
	sources, typesFile, imports, refusals := cgoTreeRoles(pkg)

	if typesFile == nil && len(refusals) == 0 {
		return nil
	}

	info := pkg.TypesInfo
	declarations := map[types.Object]cgoDeclaration{}

	for _, declaration := range cgoDeclarations(pkg.Types) {
		if declaration.object != nil {
			declarations[declaration.object] = declaration
		}
	}

	// What cmd/cgo's types file declares: every use of one of these must be consumed by a recognised shape.
	plumbing := map[types.Object]bool{}

	if typesFile != nil {
		ast.Inspect(typesFile, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.FuncDecl:
				plumbing[info.Defs[n.Name]] = true
				return false
			case *ast.TypeSpec:
				plumbing[info.Defs[n.Name]] = true
			case *ast.ValueSpec:
				for _, name := range n.Names {
					plumbing[info.Defs[name]] = true
				}
			}

			return true
		})
	}

	delete(plumbing, nil)

	consumed := map[*ast.Ident]bool{}
	closures := map[*ast.CallExpr]*cgoCheckClosure{}
	calledIdents := map[*ast.Ident]bool{}
	var used []cgoDeclaration
	usedAt := map[types.Object]token.Position{}

	refuse := func(pos token.Pos, text string) {
		refusals = append(refusals, cgoUseRefusal{position: pkg.Fset.Position(pos), text: text})
	}

	consume := func(node ast.Node) {
		ast.Inspect(node, func(n ast.Node) bool {
			if ident, ok := n.(*ast.Ident); ok && plumbing[info.Uses[ident]] {
				consumed[ident] = true
			}

			return true
		})
	}

	for _, source := range sources {
		for _, position := range cgoReceiverAddresses(source.file, info) {
			refuse(position, "unsafe.Pointer of a pointer of the method's own receiver type, inside that method: go2cs mints that address from a reference, as a bare number it cannot tell from C memory. Hand the pointer to a function that takes it as a parameter and convert it there; Phase 3")
		}

		ast.Inspect(source.file, func(n ast.Node) bool {
			switch n := n.(type) {
			case *ast.DeferStmt:
				// `defer C.f(args)` through the check closure is a deferred call of C.f (Phase 3, increment 3.1). The
				// statement's call becomes that call here, before anything else reads the tree.
				if statements := cgoDeferredCheckClosure(n.Call, info, plumbing); statements != nil {
					closure := cgoRecognizeCheckClosureStatements(statements, info, plumbing)

					if closure == nil {
						if cgoMentionsPrefix(n, "_cgoIndex") || cgoMentionsPrefix(n, "_cgoSlice") {
							refuse(n.Pos(), fmt.Sprintf("%s: a pointer to an element of a Go slice or array, checked by cmd/cgo; Phase 3", cgoCalledFunction(n, declarations, info)))
						} else {
							refuse(n.Pos(), fmt.Sprintf("%s: a deferred call through cmd/cgo's pointer-check closure in a shape go2cs does not recognise", cgoCalledFunction(n, declarations, info)))
						}

						consume(n)
						return false
					}

					n.Call = cgoLowerDeferredClosure(closure, info)
				}
			case *ast.GoStmt:
				// `go C.f(args)` through the check closure: cmd/cgo makes the goroutine's function the check closure
				// itself, so its arguments are evaluated inside the new goroutine. A goroutine on a Go function that
				// calls C further in is an ordinary one.
				if funcLit, ok := ast.Unparen(n.Call.Fun).(*ast.FuncLit); ok && cgoDirectlyChecks(funcLit.Body, info, plumbing) {
					refuse(n.Pos(), fmt.Sprintf("%s: a goroutine started on a call through cmd/cgo's pointer-check closure, whose arguments cmd/cgo evaluates inside the new goroutine; Phase 2 later", cgoCalledFunction(n, declarations, info)))
					consume(n)
					return false
				}
			case *ast.CallExpr:
				if callee, ok := ast.Unparen(n.Fun).(*ast.Ident); ok {
					calledIdents[callee] = true
				}

				if funcLit := cgoCheckClosureFunc(n, info, plumbing); funcLit != nil {
					if closure := cgoRecognizeCheckClosure(funcLit, info, plumbing); closure != nil {
						closures[n] = closure

						for _, statement := range funcLit.Body.List {
							if exprStmt, ok := statement.(*ast.ExprStmt); ok {
								if call, ok := exprStmt.X.(*ast.CallExpr); ok {
									if callee, ok := call.Fun.(*ast.Ident); ok && callee.Name == "_cgoCheckPointer" {
										consumed[callee] = true
									}
								}
							}
						}
					} else if cgoMentionsPrefix(funcLit, "_cgoIndex") || cgoMentionsPrefix(funcLit, "_cgoSlice") {
						refuse(n.Pos(), fmt.Sprintf("%s: a pointer to an element of a Go slice or array, checked by cmd/cgo; Phase 3", cgoCalledFunction(funcLit, declarations, info)))
						consume(funcLit)
						return false
					}
				}
			}

			return true
		})

		ast.Inspect(source.file, func(n ast.Node) bool {
			ident, ok := n.(*ast.Ident)

			if !ok || consumed[ident] {
				return true
			}

			object := info.Uses[ident]

			if !plumbing[object] {
				return true
			}

			declaration, found := declarations[object]

			switch {
			case found && cgoPseudoPackageKind(declaration.kind):
				// A C type or constant: 3d's route.
			case found && (declaration.kind == cgoFunc || declaration.kind == cgoErrnoFunc):
				if !calledIdents[ident] {
					refuse(ident.Pos(), fmt.Sprintf("C.%s: a C function used as a value rather than called; Phase 2 later", declaration.cName))
				} else if _, seen := usedAt[object]; !seen {
					usedAt[object] = pkg.Fset.Position(ident.Pos())
					used = append(used, declaration)
				}
			case found && declaration.kind == cgoVar:
				refuse(ident.Pos(), fmt.Sprintf("C.%s: a C variable (§11.6); Phase 2 later", declaration.cName))
			case found && declaration.kind == cgoFuncValue:
				refuse(ident.Pos(), fmt.Sprintf("C.%s: a C function's address used as a value (§11.6); Phase 2 later", declaration.cName))
			case found && declaration.kind == cgoMacro:
				refuse(ident.Pos(), fmt.Sprintf("C.%s: a C macro that is not a constant, which cmd/cgo evaluates in C; Phase 4", declaration.cName))
			case ident.Name == "_Cgo_ptr":
				// The wrapper of a C function's address (_Cfpvar_fp_), refused by name above.
			case ident.Name == "_cgoCheckPointer":
				refuse(ident.Pos(), "a call through cmd/cgo's pointer-check closure in a shape go2cs does not recognise; refused rather than converted into a lambda that calls cmd/cgo's dropped check")
			default:
				refuse(ident.Pos(), fmt.Sprintf("%s: cmd/cgo plumbing go2cs does not convert", ident.Name))
			}

			return true
		})
	}

	// The bindings, for the C functions called: a wrapper refuses a signature outside Phase 2's set by name.
	goos, goarch, _ := strings.Cut(options.targetPlatform, "/")
	target := cgoBindingTarget{goos: goos}
	errnoForm := false

	if goos == "windows" {
		target.crt = "ucrtbase.dll"
	}

	sizes := types.SizesFor("gc", goarch)
	members := map[string]string{}

	sort.SliceStable(used, func(i, j int) bool {
		if used[i].cName != used[j].cName {
			return used[i].cName < used[j].cName
		}

		return used[i].kind < used[j].kind
	})

	var symbols []string
	functions := map[string]string{}

	// A first pass decides refusals, before any C toolchain runs; the bindings are written once the capture names
	// each symbol's library.
	check := newCgoWrapperSet(target, sizes)

	for _, declaration := range used {
		if _, err := check.wrapper(declaration); err != nil {
			position := usedAt[declaration.object]
			refusals = append(refusals, cgoUseRefusal{position: position, text: strings.TrimPrefix(err.Error(), "cgo wrapper: ")})
			continue
		}

		member := getCoreSanitizedIdentifier(declaration.cName)

		if declaration.kind == cgoErrnoFunc {
			member += cgoErrnoFormSuffix
			errnoForm = true
		}

		functions[declaration.object.Name()] = member

		if symbol := cgoSymbolOf(declaration); symbol != "" && !slices.Contains(symbols, symbol) {
			symbols = append(symbols, symbol)
		}
	}

	sort.Strings(symbols)

	if len(refusals) > 0 {
		refuseCgoRoute(pkg, refusals)
	}

	// The link flags cmd/cgo recorded, each a plain token (§11.15): the capture links with them.
	args, err := cgoLinkerDirectives(typesFile)
	var flags cgoLinkFlags

	if err == nil {
		flags, err = parseCgoLinkFlags(goos, args, pkg.Dir)
	}

	if err != nil {
		refuseCgoRoute(pkg, []cgoUseRefusal{{position: pkg.Fset.PositionFor(typesFile.Package, false), text: err.Error()}})
	}

	// The library each symbol loads from (§6.1, §11.5), and the C toolchain that answered.
	var captured []cgoSymbolLibrary
	var toolchain string

	symbolUses := map[string]token.Position{}

	for _, declaration := range used {
		if symbol := cgoSymbolOf(declaration); symbol != "" {
			if _, seen := symbolUses[symbol]; !seen {
				symbolUses[symbol] = usedAt[declaration.object]
			}
		}
	}

	if cgoCaptureOverride != nil {
		captured, toolchain, err = cgoCaptureOverride(symbols)
	} else {
		var undefined []cgoUseRefusal
		captured, toolchain, undefined, err = cgoCapture(load, goos, goarch, flags, symbols, symbolUses)

		if len(undefined) > 0 {
			refuseCgoRoute(pkg, undefined)
		}
	}

	if err != nil {
		refuseCgoRoute(pkg, []cgoUseRefusal{{position: pkg.Fset.PositionFor(typesFile.Package, false), text: err.Error()}})
	}

	// The capture asks a library for each PLAIN name, with no header in sight, so a name a header renames is found
	// under the wrong function. Each name is held to what cmd/cgo's own binary imports.
	if len(symbols) > 0 && imports == nil {
		refuseCgoRoute(pkg, []cgoUseRefusal{{position: pkg.Fset.PositionFor(typesFile.Package, false), text: "cgo: cmd/cgo wrote no dynamic imports for this package (its C does not link as go builds it), so nothing shows which symbol each C call reaches, and Phase 2 binds only a name cmd/cgo itself imports"}})
	}

	if unverified := cgoImportedByCmdCgo(symbols, imports, symbolUses); len(unverified) > 0 {
		refuseCgoRoute(pkg, unverified)
	}

	set := newCgoWrapperSet(target, sizes)
	set.libraries = map[string]string{}

	for _, entry := range captured {
		set.libraries[entry.symbol] = entry.name
	}

	for _, declaration := range used {
		text, err := set.wrapper(declaration)

		if err != nil {
			refuseCgoRoute(pkg, []cgoUseRefusal{{position: usedAt[declaration.object], text: strings.TrimPrefix(err.Error(), "cgo wrapper: ")}})
		}

		members[declaration.cName+cgoKindMemberLabel(declaration.kind)] = text
	}

	if errnoForm && target.crt != "" {
		members[cgoMirrorSuffix+"errno"] = cgoErrnoLocationBinding(target.crt)
	}

	for name, text := range set.support() {
		members[name] = text
	}

	members[cgoMirrorSuffix+"0 libraries"] = cgoLibrariesRegistration(pkg.Name, options.targetPlatform, cgoLibraryTable(flags, captured))

	reduced := cgoTypesDeclarations(typesFile, declarations, info)

	route := &cgoRoute{
		typesFile: reduced,
		folder:    goos + "-" + goarch,
		header:    cgoBindingsHeader(pkg, sources, reduced, options.targetPlatform, toolchain),
		members:   cgoPseudoPackageText(pkg.Name, members),
	}

	for _, source := range sources {
		if source.output != "" {
			cgoDropDirectiveComments(source.file)
			cgoDropPlumbingImport(source.file)
		}
	}

	route.trees = append(append(route.trees, sources...), syntaxSourceFile{file: reduced, path: pkg.Fset.PositionFor(typesFile.Package, false).Filename, bindings: true})

	// The package's other analyses walk pkg.Syntax: they see the trees that convert, and never cmd/cgo's plumbing.
	pkg.Syntax = nil

	for _, tree := range route.trees {
		pkg.Syntax = append(pkg.Syntax, tree.file)
	}

	cgoRouteActive = true
	cgoRouteFunctions = functions
	cgoCheckClosures = closures

	return route
}

// cgoSymbolOf is the C symbol a called declaration binds, which the capture finds a library for and the verified-names
// rule holds to cmd/cgo's own imports: the C function's own name. cmd/cgo's helpers are Go functions and bind none,
// except that the two that allocate bind the package's malloc, as C.malloc's wrapper does (Phase 3, increment 3.1).
func cgoSymbolOf(declaration cgoDeclaration) string {
	if declaration.kind == cgoFunc && cgoBuiltinNames[declaration.cName] {
		if cgoAllocatingHelpers[declaration.cName] {
			return cgoAllocator
		}

		return ""
	}

	return declaration.cName
}

// cgoKindMemberLabel orders a C name's two bindings, its plain and its errno form, within the pseudo-package.
func cgoKindMemberLabel(kind cgoDeclKind) string {
	if kind == cgoErrnoFunc {
		return " errno"
	}

	return ""
}

// cgoMentionsPrefix reports whether a node names any identifier prefix<digits>.
func cgoMentionsPrefix(node ast.Node, prefix string) bool {
	found := false

	ast.Inspect(node, func(n ast.Node) bool {
		if ident, ok := n.(*ast.Ident); ok && cgoClosureVariable(ident, prefix) >= 0 {
			found = true
		}

		return !found
	})

	return found
}

// refuseCgoRoute reports each refused C use at its source position, and exits before anything is written.
func refuseCgoRoute(pkg *packages.Package, refusals []cgoUseRefusal) {
	sort.SliceStable(refusals, func(i, j int) bool {
		a, b := refusals[i].position, refusals[j].position

		if a.Filename != b.Filename {
			return a.Filename < b.Filename
		}

		return a.Offset < b.Offset
	})

	for _, refusal := range refusals {
		reportDiagnostic(refusal.position.String(), diagnosticCgoRefused, refusal.text)
	}

	log.Fatalf("Refusing to convert: package %s uses C in %d way(s) cgo Phase 2 does not bind, each named above with the phase that owns it; nothing was written\n", pkg.PkgPath, len(refusals))
}

// cgoBindingsHeader writes the bindings file's header (§4.1, as amended by §11.20, M4): the target, the C toolchain's
// first --version line, never its path, and a sha256 over the package's import "C" sources and the C type and
// constant declarations cmd/cgo gave them, each normalised, so that two bindings files are told apart by provenance and
// the same package converted anywhere hashes the same. No path, link flag or host library version reaches the hash.
func cgoBindingsHeader(pkg *packages.Package, sources []syntaxSourceFile, reduced *ast.File, targetPlatform, toolchain string) string {
	hash := sha256.New()
	var names []string
	paths := map[string]string{}

	for _, source := range sources {
		if source.output == "" {
			continue
		}

		path := pkg.Fset.PositionFor(source.file.Package, true).Filename
		names = append(names, filepath.Base(path))
		paths[filepath.Base(path)] = path
	}

	sort.Strings(names)

	for _, name := range names {
		content, err := os.ReadFile(paths[name])

		if err != nil {
			log.Fatalf("Refusing to convert: cgo: the import \"C\" source %s cannot be read for the bindings' hash: %s\n", name, err)
		}

		fmt.Fprintf(hash, "source %s\n%s\n", name, strings.ReplaceAll(string(content), "\r\n", "\n"))
	}

	for _, decl := range reduced.Decls {
		if genDecl, ok := decl.(*ast.GenDecl); ok && genDecl.Tok != token.IMPORT {
			var text bytes.Buffer

			if err := printer.Fprint(&text, pkg.Fset, genDecl); err != nil {
				log.Fatalf("Refusing to convert: cgo: a C declaration cannot be printed for the bindings' hash: %s\n", err)
			}

			fmt.Fprintf(hash, "declaration\n%s\n", text.String())
		}
	}

	var header strings.Builder

	fmt.Fprintf(&header, "// %s.cgo.cs - the C bindings of Go package %s, made by go2cs from cmd/cgo's output for its import \"C\"\n", pkg.Name, pkg.PkgPath)
	header.WriteString("// sources (docs/phase4/DESIGN-cgo-phase2-pinvoke.md §4.1, §11.20). DO NOT EDIT: convert the package again with -cgo.\n")
	fmt.Fprintf(&header, "// target: %s\n", targetPlatform)
	fmt.Fprintf(&header, "// C toolchain: %s\n", cgoToolchainLine(toolchain))
	fmt.Fprintf(&header, "// sha256: %s (the import \"C\" sources and the C declarations cmd/cgo gave them)\n\n", hex.EncodeToString(hash.Sum(nil)))

	return header.String()
}

// bindingsText completes the bindings file from its converted declarations: the header first, the assembly's
// search-path attribute ahead of the namespace (an assembly attribute must precede it, CS1730), and the bindings last.
func (route *cgoRoute) bindingsText(converted string) string {
	attribute := cgoLibrariesSearchPathsAttribute()
	namespaceAt := strings.Index(converted, "\nnamespace ")

	if strings.HasPrefix(converted, "namespace ") {
		namespaceAt = 0
	} else if namespaceAt >= 0 {
		namespaceAt++
	}

	if namespaceAt < 0 {
		return route.header + attribute + "\n" + converted + "\n" + route.members
	}

	return route.header + converted[:namespaceAt] + attribute + "\n" + converted[namespaceAt:] + "\n" + route.members
}

// bindingsPath is where the bindings file lands: in its one target's folder (§11.20, S3).
func (route *cgoRoute) bindingsPath(packageOutputPath, packageName string) string {
	return filepath.Join(packageOutputPath, route.folder, packageName+".cgo.cs")
}

// convCgoCheckClosure converts a call through cmd/cgo's pointer-check closure as the call the closure makes, each of the
// closure's variables rendering what it stands for. The wrapper copies a struct's pointee in and checks it as cmd/cgo's
// address-form check does (GoCgoArgs.StructPointer), and C is handed only that copy (§11.20, M1). Each argument is
// still evaluated once, in order.
func (v *Visitor) convCgoCheckClosure(closure *cgoCheckClosure, context LambdaContext) string {
	if v.cgoClosureArguments == nil {
		v.cgoClosureArguments = map[types.Object]cgoClosureArgument{}
	}

	for object, argument := range closure.arguments {
		v.cgoClosureArguments[object] = argument
	}

	defer func() {
		for object := range closure.arguments {
			delete(v.cgoClosureArguments, object)
		}
	}()

	return v.convCallExpr(closure.call, context)
}

// convCgoClosureArgument renders what a check closure's variable stands for, in the context the variable was met in (a
// pointer parameter's argument renders its box): its expression, converted to the type the closure declared it at when
// it did (`var _cgoN T = x`, which gives an untyped constant its C type).
func (v *Visitor) convCgoClosureArgument(argument cgoClosureArgument, context IdentContext) string {
	// The variable stood for a pointer as a value, so a pointer parameter renders its box (Ꮡp), never its dereference.
	if valueType := v.info.TypeOf(argument.value); valueType != nil {
		if _, isPointer := valueType.Underlying().(*types.Pointer); isPointer {
			context.isPointer = true
		}
	}

	value := v.convExpr(argument.value, []ExprContext{context})

	if argument.declared == nil {
		return value
	}

	return fmt.Sprintf("(%s)(%s)", v.getExpressionTypeName(argument.declared, false), value)
}

// cgoTargetDefaults makes a cgo package's project default to the one target its bindings were converted for: layout
// L3's own defaults are the corpus's (windows, amd64), and a build of another target would compile no bindings. It
// also makes the project hold to that target (cgoTargetBlocks).
func cgoTargetDefaults(projectFileContents, targetPlatform string) string {
	goos, goarch, _ := strings.Cut(targetPlatform, "/")

	for property, value := range map[string]string{platformTargetOSProperty: goos, platformTargetArchProperty: goarch} {
		projectFileContents = regexp.MustCompile(`<`+property+`>[^<]*</`+property+`>`).
			ReplaceAllLiteralString(projectFileContents, "<"+property+">"+value+"</"+property+"> <!-- the one target of this package's cgo bindings -->")
	}

	closeAt := strings.LastIndex(projectFileContents, "</Project>")

	if closeAt < 0 || strings.Contains(projectFileContents, cgoTargetCheckName) {
		return projectFileContents
	}

	return projectFileContents[:closeAt] + cgoTargetBlocks(goos, goarch) + projectFileContents[closeAt:]
}

// cgoTargetCheckName is the MSBuild target that refuses a cgo project's build for another target.
const cgoTargetCheckName = "GoCheckCgoTarget"

// cgoTargetBlocks are the two things that hold a cgo package's project to the one target of its bindings.
//
// A build for another target is refused by name, before any reference is built or the compiler runs: it would
// compile no bindings file, and fail on the first C type in an exported signature (CS0051), far from the cause.
//
// And the project hands a target to the projects it references. Its default reaches only itself; the standard
// library's own default is the corpus's, so a build that names no target would compile these bindings beside the
// windows standard library, and say nothing. What it hands down is the target the standard library is LAID OUT for
// (cgoReferenceTarget), which is not always the bindings' own.
func cgoTargetBlocks(goos, goarch string) string {
	target := goos + "/" + goarch
	build := "$(" + platformTargetOSProperty + ")/$(" + platformTargetArchProperty + ")"
	referenceOS, referenceArch := cgoReferenceTarget(goos, goarch)

	return "  <!-- This package's cgo bindings were converted for " + target + ", and are for no other target. A build for\r\n" +
		"       another would compile no bindings file and fail far from the cause, so it is refused here by name. -->\r\n" +
		"  <Target Name=\"" + cgoTargetCheckName + "\" BeforeTargets=\"BeforeBuild;CoreCompile\">\r\n" +
		"    <Error Condition=\"'" + build + "'!='" + target + "'\"\r\n" +
		"           Text=\"go2cs: this package's cgo bindings were converted for " + target + ", and this build is for " + build +
		". A cgo package builds only for the target it was converted for: build it for " + target +
		", or convert it again with -cgo on a " + build + " host.\" />\r\n" +
		"  </Target>\r\n\r\n" +
		"  <!-- The projects this package references are built for this package's operating system, at the architecture\r\n" +
		"       the standard library is laid out for there. The standard library's own default is windows/amd64, and a\r\n" +
		"       build that names no target would put that one beside these bindings. -->\r\n" +
		"  <ItemDefinitionGroup>\r\n" +
		"    <ProjectReference>\r\n" +
		"      <AdditionalProperties>" + platformTargetOSProperty + "=" + referenceOS + ";" + platformTargetArchProperty + "=" + referenceArch + "</AdditionalProperties>\r\n" +
		"    </ProjectReference>\r\n" +
		"  </ItemDefinitionGroup>\r\n\r\n"
}

// cgoReferenceTarget is the target a cgo package's project references are built for. The converted standard library is
// laid out for a declared set of targets (platformUniverse), and its own build refuses any other by name. A cgo
// package's bindings are for the host's own target, which need not be in that set: darwin/arm64 is not, and the
// library's darwin/amd64 flavour serves both of darwin's architectures. So the references take the package's own
// target where the library is laid out for it, and otherwise the flavour the library has for that operating system.
// Handing down the bindings' own pair refused every build of a cgo project on darwin/arm64 (first read on the hosted
// leg 43335132134).
func cgoReferenceTarget(goos, goarch string) (string, string) {
	flavourArch := ""

	for _, target := range platformUniverse {
		targetOS, targetArch, _ := strings.Cut(target, "/")

		if targetOS != goos {
			continue
		}

		if targetArch == goarch {
			return goos, goarch
		}

		if flavourArch == "" {
			flavourArch = targetArch
		}
	}

	if flavourArch == "" {
		// An operating system the library has no flavour of: its own check names the pair it is handed.
		return goos, goarch
	}

	return goos, flavourArch
}

// cgoLoad is the environment and directory go list loaded the package in: the real route reads go env and runs the C
// compiler under the same ones, so the compiler that captures each library is the one cmd/cgo used.
type cgoLoad struct {
	env []string
	dir string
}

// cgoGoEnv reads go env values in the load's own environment, one per key, in order.
func cgoGoEnv(load cgoLoad, keys ...string) ([]string, error) {
	cmd := exec.Command("go", append([]string{"env"}, keys...)...)
	cmd.Env = load.env
	cmd.Dir = load.dir
	out, err := cmd.Output()

	if err != nil {
		return nil, fmt.Errorf("cgo: go env %s in the package's load: %w", strings.Join(keys, " "), err)
	}

	values := strings.Split(strings.TrimRight(strings.ReplaceAll(string(out), "\r\n", "\n"), "\n"), "\n")

	if len(values) != len(keys) {
		return nil, fmt.Errorf("cgo: go env %s read %d values", strings.Join(keys, " "), len(values))
	}

	return values, nil
}

// cgoHostTarget refuses a -cgo conversion for any target but the host's own (§11.20, S3): cmd/cgo lays out C types with
// the host's C compiler, so bindings for another target need that target's toolchain, which is Phase 2 later. The host
// is what go env reads in the load's own environment (GOHOSTOS/GOHOSTARCH), never go2cs's own runtime.GOOS, and the
// refusal names both sides.
func cgoHostTarget(load cgoLoad, target string) error {
	host, err := cgoGoEnv(load, "GOHOSTOS", "GOHOSTARCH")

	if err != nil {
		return err
	}

	if hostTarget := host[0] + "/" + host[1]; hostTarget != target {
		return fmt.Errorf("cgo: -cgo converts for the host's own target only: this conversion asks for %s, and go env in its load reads the host as %s (GOHOSTOS/GOHOSTARCH); converting cgo for another target is Phase 2 later", target, hostTarget)
	}

	return nil
}

// cgoCapture answers each symbol's library through the C compiler the load used (go env CC, split as cmd/go splits it),
// and the first line that compiler prints for --version, which the bindings' header records: never the CC value,
// whose path would name the converting machine (§11.20, M4). A symbol no library defines, a function the preamble
// itself defines among them, is refused by name at its use, as Phase 4's: the probe links each symbol alone to name them.
func cgoCapture(load cgoLoad, goos, goarch string, flags cgoLinkFlags, symbols []string, usedAt map[string]token.Position) ([]cgoSymbolLibrary, string, []cgoUseRefusal, error) {
	values, err := cgoGoEnv(load, "CC")

	if err != nil {
		return nil, "", nil, err
	}

	command, err := splitCgoCommand(values[0])

	if err != nil {
		return nil, "", nil, err
	}

	// The compiler is resolved once, so its --version (run here) and the probe's link (run in a temporary directory)
	// are one program: a relative CC is the package directory's, as it is cmd/go's, and a bare name is PATH's.
	if strings.ContainsAny(command[0], `/\`) {
		if !filepath.IsAbs(command[0]) {
			command[0] = filepath.Join(load.dir, command[0])
		}
	} else if resolved, lookErr := exec.LookPath(command[0]); lookErr == nil {
		command[0] = resolved
	}

	toolchain := cgoToolchain{cc: command, env: load.env, arch: cgoArchFlags(goos, goarch)}
	versionCommand := exec.Command(command[0], append(append([]string{}, command[1:]...), "--version")...)
	versionCommand.Env = append(os.Environ(), load.env...)
	version, err := versionCommand.Output()

	if err != nil {
		return nil, "", nil, fmt.Errorf("cgo: the C compiler cmd/cgo used does not report its version (--version): %w", err)
	}

	toolchainLine := cgoToolchainLine(string(version))
	workDir, err := os.MkdirTemp("", "go2cs-cgo-capture-")

	if err != nil {
		return nil, "", nil, err
	}

	defer os.RemoveAll(workDir)

	captured, err := captureCgoLibraries(toolchain, goos, flags, symbols, workDir)

	if err == nil {
		return captured, toolchainLine, nil, nil
	}

	// Each symbol no shared library exports is refused at its use. A shared probe may link with the symbol left undefined
	// (ELF allows it) and resolve it nowhere, and a probe that does not link names no symbol at all, so there each symbol
	// is linked alone to name the ones no library defines.
	unbound := map[string]bool{}
	var named *cgoUnboundSymbols

	if errors.As(err, &named) {
		for _, symbol := range named.symbols {
			unbound[symbol] = true
		}
	} else {
		// A probe that references nothing must link. When it does not, the failure is the package's link line or the
		// compiler itself (a library that is not there, a directory for another architecture), and no symbol is to
		// blame: the linker's own words are the refusal.
		if _, _, baselineErr := linkCgoProbe(toolchain, goos, flags, nil, workDir, nil); baselineErr != nil {
			// The baseline's own error, never the first probe's: that one referenced every symbol, and a linker
			// that traces symbols names each of them beside the library that is not there.
			return nil, "", nil, baselineErr
		}

		for _, symbol := range symbols {
			if _, _, linkErr := linkCgoProbe(toolchain, goos, flags, []string{symbol}, workDir, nil); linkErr != nil {
				unbound[symbol] = true
			}
		}
	}

	var refusals []cgoUseRefusal

	for _, symbol := range symbols {
		if unbound[symbol] {
			refusals = append(refusals, cgoUseRefusal{position: usedAt[symbol], text: fmt.Sprintf("C.%s: no shared library the package links exports it (it resolved statically, or nowhere), and Phase 2 binds only a shared library's export; a function the preamble defines is compiled C, Phase 4's", symbol)})
		}
	}

	if len(refusals) > 0 {
		return nil, "", refusals, nil
	}

	return nil, "", nil, err
}

// cgoToolchainLineLimit caps the toolchain line the bindings' header records.
const cgoToolchainLineLimit = 120

// cgoToolchainLine is the line of a C compiler's --version output the bindings' header records: its first line, in
// printable ASCII only, capped. The line is written into a C# comment, and the text is whatever CC printed (a wrapper
// script's too): a bare CR, U+0085, U+2028 and U+2029 each end a C# line, so anything outside 0x20-0x7E is dropped,
// and nothing of it can become code.
func cgoToolchainLine(version string) string {
	var line strings.Builder

	for _, r := range strings.SplitN(version, "\n", 2)[0] {
		if r >= 0x20 && r <= 0x7e {
			line.WriteRune(r)
		}
	}

	text := strings.TrimSpace(line.String())

	if len(text) > cgoToolchainLineLimit {
		text = strings.TrimSpace(text[:cgoToolchainLineLimit])
	}

	return text
}

// cgoArchFlags are the flags that make a C compiler build for goos/goarch, as cmd/go hands them to CC for every cgo
// compile and link (cmd/go/internal/work, gccArchArgs, go1.26.10), for the targets go2cs converts. The probe carries
// them, so a compiler whose default architecture is not the conversion's (an amd64 go under Rosetta, or on Windows on
// Arm) answers for the right one.
func cgoArchFlags(goos, goarch string) []string {
	switch goarch {
	case "amd64":
		if goos == "darwin" {
			return []string{"-arch", "x86_64", "-m64"}
		}

		return []string{"-m64"}
	case "arm64":
		if goos == "darwin" {
			return []string{"-arch", "arm64"}
		}
	}

	return nil
}

// cgoImportedByCmdCgo refuses each symbol cmd/cgo's own binary does not import under its plain C name (imports, the
// local names of _cgo_import.go). A header may rename a function behind its C name: darwin/amd64's <sys/stat.h> makes
// fstat the symbol fstat$INODE64, a different function over a different struct stat, and glibc may make strtol
// __isoc23_strtol. The plain name still exists in the library, so the capture finds it, and a binding to it would call a
// function C never calls. A name the binary imports is the one C calls. One it does not import is renamed, or the C
// compiler inlined the call (cmd/cgo compiles at -O2, and abs is a builtin), and nothing here tells the two apart, so
// both are refused by name: a loud over-refusal rather than a silent wrong binding (COORD's ruling on the review's M3).
func cgoImportedByCmdCgo(symbols []string, imports map[string]bool, usedAt map[string]token.Position) []cgoUseRefusal {
	var refusals []cgoUseRefusal

	for _, symbol := range symbols {
		if imports[symbol] {
			continue
		}

		var decorated []string

		for name := range imports {
			if strings.Contains(name, symbol) {
				decorated = append(decorated, name)
			}
		}

		sort.Strings(decorated)
		instead := ""

		if len(decorated) > 3 {
			decorated = decorated[:3]
		}

		if len(decorated) > 0 {
			instead = " (it imports " + strings.Join(decorated, ", ") + ")"
		}

		refusals = append(refusals, cgoUseRefusal{position: usedAt[symbol], text: fmt.Sprintf("C.%s: cmd/cgo's own binary does not import a symbol named %s%s, so nothing shows that name is the function C calls here: a header renames it, or the C compiler inlined the call as a builtin. Binding the plain name could call a different function, so it is refused; Phase 2 later", symbol, symbol, instead)})
	}

	return refusals
}
