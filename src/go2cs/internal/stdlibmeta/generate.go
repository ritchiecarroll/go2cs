// Package stdlibmeta builds the converter's embedded record of the exported cross-package
// metadata published by each converted standard-library package's package_info.cs.
//
// It is shared by the genstdlibmeta generator and by the converter's in-process sync test,
// so the committed asset can never drift from src/core without a test failure.
package stdlibmeta

import (
	"bufio"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// AssetFileName is the generated asset the converter embeds, relative to src/go2cs.
const AssetFileName = "stdlib-metadata.txt"

// PackageInfoFileName duplicates the converter's symbols.go constant of the same name. The
// converter is `package main`, so its constants are not importable from here; the value is
// fixed by the emitted file's name and is asserted against the converter's constant by
// TestStdLibMetadataAssetFileName.
const PackageInfoFileName = "package_info.cs"

// ReferenceGOOS is the platform flavor this record describes.
//
// Layout L3 (docs/phase4/DESIGN-multiplatform-corpus.md §8) moves a package's platform-VARYING
// artifacts into per-GOOS subfolders, and `package_info.cs` is one of them — 27 packages corpus-wide
// carry a per-platform copy rather than a flat one. This asset, though, feeds `-recurse=nuget`,
// where the dependency is a PUBLISHED assembly and the consumer therefore sees exactly one compile
// surface: the flavor shipped as the package's `lib/{tfm}` compile-time asset (design §9(a)). So the
// record is taken from the flat copy where one exists, and from this GOOS's copy where the metadata
// varies — the same designated flavor `$(GoTargetOS)` defaults to.
//
// It duplicates the converter's platformDefaultTargetOS for the same reason PackageInfoFileName
// duplicates its constant (this package cannot import `package main`), and is asserted against it by
// TestStdLibMetadataAssetFileName.
const ReferenceGOOS = "windows"

// SectionPrefix introduces a package section; the remainder of the line is the package's
// dotted name (`math.rand.v2`), matching PackageInfo.PackageName and the `go.<name>` NuGet
// package id. A single '#' introduces a file-level comment line.
const SectionPrefix = "##"

const aliasSectionStart = "// <ExportedTypeAliases>"
const aliasSectionEnd = "// </ExportedTypeAliases>"
const implementPrefix = "[assembly: GoImplement<"

// refPrimaryPrefix is the cross-package lowering contract's record (refVerdictPublication.go in
// the converter, which keys its own reader on the same spelling): the third record family a
// consumer reads back from a dependency, carried here so a NuGet-referenced package publishes its
// `ref`-receiver primaries exactly as an on-disk package_info.cs does.
const refPrimaryPrefix = "[assembly: GoRefPrimary("

var header = []string{
	"# Code generated by genstdlibmeta from ../core/**/" + PackageInfoFileName + "; DO NOT EDIT.",
	"#",
	"# The converter normally learns a referenced package's exported type aliases and",
	"# interface-implementation records by reading that package's " + PackageInfoFileName + " out of",
	"# the converted-source tree on disk. Under -recurse=nuget there is no such tree -- the",
	"# standard library arrives as pre-compiled go.<pkg> NuGet packages -- so the same facts",
	"# are carried here instead, captured from src/core (the tree push-nuget.ps1",
	"# packs), which makes the embedded record and the published assemblies one commit's output.",
	"#",
	"# Format: '##<dotted package name>' opens a section; its lines are the matching",
	"# " + PackageInfoFileName + " lines verbatim, so the converter's existing parsers read them unchanged.",
	"#",
	"# Regenerate with `go generate .` from src/go2cs; never hand-edit.",
}

// Generate walks convertedRoot for package_info.cs files and returns the asset content, the
// number of package sections written, and any error. Output is deterministic: sections are
// sorted by package name and each carries its matched lines verbatim in file order.
func Generate(convertedRoot string) ([]byte, int, error) {
	sections, err := Collect(convertedRoot)

	if err != nil {
		return nil, 0, err
	}

	if len(sections) == 0 {
		return nil, 0, fmt.Errorf("no %s files found under %q -- is the converted standard library present?", PackageInfoFileName, convertedRoot)
	}

	names := make([]string, 0, len(sections))

	for name := range sections {
		names = append(names, name)
	}

	sort.Strings(names)

	var builder strings.Builder

	for _, line := range header {
		builder.WriteString(line)
		builder.WriteString("\r\n")
	}

	for _, name := range names {
		builder.WriteString("\r\n")
		builder.WriteString(SectionPrefix)
		builder.WriteString(name)
		builder.WriteString("\r\n")

		for _, line := range sections[name] {
			builder.WriteString(line)
			builder.WriteString("\r\n")
		}
	}

	return []byte(builder.String()), len(names), nil
}

// Collect returns, per dotted package name, the package_info.cs lines that carry exported
// cross-package metadata: the <ExportedTypeAliases> section (markers included, so an empty
// section still parses as "no aliases" rather than "unknown") and every GoImplement record.
// Layout L3 (docs/phase4/DESIGN-multiplatform-corpus.md §8) can put a package's package_info.cs in a
// per-GOOS subfolder instead of flat, so the walk is TWO passes: pass one records where every
// package_info.cs and every .csproj live, pass two decides which copy each package is described by.
//
// The per-GOOS folder is told from a nested package by the project file — a converted package
// directory always holds one, a source folder never does. That is the converter's own discriminator
// (isPlatformSourceFolder), and it is what keeps `internal/syscall/windows`, a real package whose
// name IS a GOOS, from being folded into `internal/syscall`.
func Collect(convertedRoot string) (map[string][]string, error) {
	infoDirs := map[string]string{} // package-info dir (rel, forward slashes) -> absolute file path
	packageDirs := map[string]bool{}

	err := filepath.WalkDir(convertedRoot, func(filePath string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if entry.IsDir() {
			switch entry.Name() {
			case "bin", "obj", "Generated", ".vs", ".git":
				return fs.SkipDir
			}

			return nil
		}

		relDir, relErr := filepath.Rel(convertedRoot, filepath.Dir(filePath))

		if relErr != nil {
			return relErr
		}

		relDir = filepath.ToSlash(relDir)

		switch {
		case entry.Name() == PackageInfoFileName:
			infoDirs[relDir] = filePath
		case strings.EqualFold(filepath.Ext(entry.Name()), ".csproj"):
			packageDirs[relDir] = true
		}

		return nil
	})

	if err != nil {
		return nil, err
	}

	sections := map[string][]string{}

	for _, relDir := range sortedKeys(infoDirs) {
		packageDir := relDir

		if !packageDirs[relDir] && packageDirs[path.Dir(relDir)] {
			// A per-GOOS copy. Keep only the reference flavor: this asset feeds -recurse=nuget,
			// where the dependency is a published assembly presenting exactly one compile surface
			// (design §9(a)), and ReferenceGOOS names which one.
			if path.Base(relDir) != ReferenceGOOS {
				continue
			}

			packageDir = path.Dir(relDir)
		}

		name := strings.ReplaceAll(packageDir, "/", ".")

		// A flat copy is authoritative; a per-GOOS one only describes a package that has none.
		if _, exists := sections[name]; exists && packageDir != relDir {
			continue
		}

		lines, readErr := extract(infoDirs[relDir])

		if readErr != nil {
			return nil, readErr
		}

		sections[name] = lines
	}

	return sections, nil
}

// sortedKeys returns a map's keys in sorted order, so the two-pass collection above is
// order-independent regardless of the filesystem walk.
func sortedKeys(values map[string]string) []string {
	keys := make([]string, 0, len(values))

	for key := range values {
		keys = append(keys, key)
	}

	sort.Strings(keys)

	return keys
}

// extract pulls the metadata-bearing lines out of one package_info.cs, preserving their
// original spelling so the converter's regex parsers can consume them unchanged.
func extract(packageInfoFile string) ([]string, error) {
	file, err := os.Open(packageInfoFile)

	if err != nil {
		return nil, err
	}

	defer file.Close()

	var lines []string
	inAliasSection := false

	scanner := bufio.NewScanner(file)

	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)

		switch {
		case trimmed == aliasSectionStart:
			inAliasSection = true
			lines = append(lines, trimmed)
		case trimmed == aliasSectionEnd:
			inAliasSection = false
			lines = append(lines, trimmed)
		case inAliasSection && strings.HasPrefix(trimmed, "[assembly: GoTypeAlias("):
			lines = append(lines, trimmed)
		case strings.HasPrefix(trimmed, implementPrefix):
			lines = append(lines, trimmed)
		case strings.HasPrefix(trimmed, refPrimaryPrefix):
			lines = append(lines, trimmed)
		}
	}

	return lines, scanner.Err()
}

// ExtractForTest exposes extract to the converter's own test suite, which asserts that record
// families sharing package_info.cs with the two this generator reads (today: GoSourcePositionMaps)
// are not scooped into the metadata.
func ExtractForTest(packageInfoFile string) ([]string, error) {
	return extract(packageInfoFile)
}
