// FormatUint returns the string representation of i in the given base,
// for 2 <= base <= 36. The result uses the lower-case letters 'a' to 'z'
// for digit values >= 10.
public static @string FormatUint(uint64 i, nint @base) {
    if (@base == 10) {
        if (i < nSmalls) {
            return small((nint)i);
        }
        array<byte> a = new(24);
        nint j = formatBase10(a[..], i);
        return (@string)(a.slice(j));
    }
    var (_, s) = formatBits(default, i, @base, false, false);
    return s;
}

// FormatInt returns the string representation of i in the given base,
// for 2 <= base <= 36. The result uses the lower-case letters 'a' to 'z'
// for digit values >= 10.
public static @string FormatInt(int64 i, nint @base) {
    if (@base == 10) {
        if (0 <= i && i < nSmalls) {
            return small((nint)i);
        }
        array<byte> a = new(24);
        var u = (uint64)i;
        if (i < 0) {
            u = ((uint64)0 - u);
        }
        nint j = formatBase10(a[..], u);
        if (i < 0) {
            j--;
            a[j] = (byte)'-';
        }
        return (@string)(a.slice(j));
    }
    var (_, s) = formatBits(default, (uint64)i, @base, i < 0, false);
    return s;
}

// Itoa is equivalent to [FormatInt](int64(i), 10).
public static @string Itoa(nint i) {
    return FormatInt((int64)i, 10);
}

// AppendInt appends the string form of the integer i,
// as generated by [FormatInt], to dst and returns the extended buffer.
public static slice<byte> AppendInt(slice<byte> dst, int64 i, nint @base) {
    var u = (uint64)i;
    if (i < 0) {
        dst = append(dst, (byte)'-');
        u = ((uint64)0 - u);
    }
    return AppendUint(dst, u, @base);
}

// AppendUint appends the string form of the unsigned integer i,
// as generated by [FormatUint], to dst and returns the extended buffer.
