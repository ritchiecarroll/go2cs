internal static readonly @string digits = "0123456789abcdefghijklmnopqrstuvwxyz"u8;

// formatBits computes the string representation of u in the given base.
// If neg is set, u is treated as negative int64 value. If append_ is
// set, the string is appended to dst and the resulting byte slice is
// returned as the first result value; otherwise the string is returned
// as the second result value.
// The caller is expected to have handled base 10 separately for speed.
internal static (slice<byte> d, @string s) formatBits(slice<byte> dst, uint64 u, nint @base, bool neg, bool append_) {
    slice<byte> d = default;
    @string s = default;

    if (@base < 2 || @base == 10 || @base > len(digits)) {
        throw panic("strconv: illegal AppendInt/FormatInt base");
    }
    // 2 <= base && base <= len(digits)

    array<byte> a = new(65); /* 64 + 1 */ // +1 for sign of 64bit value in base 2
    nint i = len(a);
    if (neg) {
        u = ((uint64)0 - u);
    }

    // convert bits
    // We use uint values where we can because those will
    // fit into a single register even on a 32bit machine.
    if (isPowerOfTwo(@base)) {
        // Use shifts and masks instead of / and %.
        nuint shift = (nuint)bits.TrailingZeros((nuint)@base);
        var b = (uint64)@base;
        nuint m = (nuint)@base - 1; // == 1<<shift - 1
        while (u >= b) {
            i--;
            a[i] = digits[((nuint)u & m)];
            u.RshAssign(shift);
        }
        // u < base
        i--;
        a[i] = digits[(nuint)u];
    } else {
        // general case
        var b = (uint64)@base;
        while (u >= b) {
            i--;
            // Avoid using r = a%b in addition to q = a/b
            // since 64bit division and modulo operations
            // are calculated by runtime functions on 32bit machines.
            var q = u / b;
            a[i] = digits[(nuint)(u - q * b)];
            u = q;
        }
        // u < base
        i--;
        a[i] = digits[(nuint)u];
    }

    // add sign, if any
    if (neg) {
        i--;
        a[i] = (byte)'-';
    }

    if (append_) {
        d = appendꓸꓸꓸ(dst, a.slice(i));
        return (d, s);
    }
    s = (@string)(a.slice(i));
    return (d, s);
}

internal static bool isPowerOfTwo(nint x) {
    return (x & (x - 1)) == 0;
}

internal static UntypedInt nSmalls => 100;

// smalls is the formatting of 00..99 concatenated.
// It is then padded out with 56 x's to 256 bytes,
// so that smalls[x&0xFF] has no bounds check.
internal static readonly @string smalls = "00010203040506070809101112131415161718192021222324252627282930313233343536373839404142434445464748495051525354555657585960616263646566676869707172737475767778798081828384858687888990919293949596979899";

internal const bool host64bit = /* ^uint(0)>>32 != 0 */ true;

// small returns the string for an i with 0 <= i < nSmalls.
internal static @string small(nint i) {
    if (i < 10) {
        return digits.slice(i, i + 1);
    }
    return smalls.slice(i * 2, i * 2 + 2);
}

// RuntimeFormatBase10 formats u into the tail of a
// and returns the offset to the first byte written to a.
// It is only for use by package runtime.
// Other packages should use AppendUint.
public static nint RuntimeFormatBase10(slice<byte> a, uint64 u) {
    return formatBase10(a, u);
}

// formatBase10 formats the decimal representation of u into the tail of a
// and returns the offset of the first byte written to a. That is, after
//
//	i := formatBase10(a, u)
//
// the decimal representation is in a[i:].
internal static nint formatBase10(slice<byte> a, uint64 u) {
    // Split into 9-digit chunks that fit in uint32s
    // and convert each chunk using uint32 math instead of uint64 math.
    // The obvious way to write the outer loop is "for u >= 1e9", but most numbers are small,
    // so the setup for the comparison u >= 1e9 is usually pure overhead.
    // Instead, we approximate it by u>>29 != 0, which is usually faster and good enough.
    nint i = len(a);
    while ((host64bit && u >> 29 != 0) || (!host64bit && ((uint32)u >> 29 | (uint32)(u >> 32)) != 0)) {
        uint32 loΔ1 = default;
        (u, loΔ1) = (u / 1000000000, (uint32)(u % 1000000000));

        // Convert 9 digits.
        foreach (var _ᴛ1 in range(4)) {
            uint32 ddΔ1 = default;
            (loΔ1, ddΔ1) = (loΔ1 / 100, (loΔ1 % 100) * 2);
            i -= 2;
            (a[i + 0], a[i + 1]) = (smalls[ddΔ1 + 0], smalls[ddΔ1 + 1]);
        }
        i--;
        a[i] = smalls[loΔ1 * 2 + 1];

        // If we'd been using u >= 1e9 then we would be guaranteed that u/1e9 > 0,
        // but since we used u>>29 != 0, u/1e9 might be 0, so we might be done.
        // (If u is now 0, then at the start we had 2²⁹ ≤ u < 10⁹, so it was still correct
        // to write 9 digits; we have not accidentally written any leading zeros.)
        if (u == 0) {
            return i;
        }
    }

    // Convert final chunk, at most 8 digits.
    var lo = (uint32)u;
    while (lo >= 100) {
        uint32 ddΔ2 = default;
        (lo, ddΔ2) = (lo / 100, (lo % 100) * 2);
        i -= 2;
        (a[i + 0], a[i + 1]) = (smalls[ddΔ2 + 0], smalls[ddΔ2 + 1]);
    }
    i--;
    var dd = lo * 2;
    a[i] = smalls[dd + 1];
    if (lo >= 10) {
        i--;
        a[i] = smalls[dd + 0];
    }
    return i;
}

