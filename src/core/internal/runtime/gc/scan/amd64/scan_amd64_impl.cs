// - ExpandAVX512: DERIVED FROM src/internal/runtime/gc/scan/expand_reference.go, Go 1.26.11, func ExpandReference.
//   The body calls it.
// - ExpandAVX512's cleared output: INSPIRED BY src/internal/runtime/gc/scan/scan_amd64.s, Go 1.26.11, assembly
//   routine ExpandAVX512. The kernel stores all 16 words of the output (two 64-byte stores), so the output is cleared
//   first rather than OR-ed into.
// - scanSpanPackedAVX512's walk: DERIVED FROM src/internal/runtime/gc/scan/scan_reference.go, Go 1.26.11, func
//   ScanSpanPackedReference. The walk over the span's words, in order.
// - scanSpanPackedAVX512's word mask: INSPIRED BY src/internal/runtime/gc/scan/scan_amd64.s, Go 1.26.11, assembly
//   routine scanSpanPackedAVX512. objMarks EXPANDED (bounded by the span's object count) AND-ed with ptrMask, each
//   selected word compressed into the buffer in order, ZERO WORDS INCLUDED, with no nil test (the caller
//   ScanSpanPackedAVX512 runs FilterNilAVX512 after it). For a mark bit at or past the object count the reference
//   would scan the span's tail words (size 48: words 1020-1023) and the kernel does not; this follows the kernel.
// - FilterNilAVX512: INSPIRED BY src/internal/runtime/gc/scan/filter_amd64.s, Go 1.26.11, assembly routine
//   FilterNilAVX512. An ORDER-PRESERVING compaction of the non-zero words (VPCOMPRESSQ over 8-word frames, then a
//   scalar tail), here one scalar loop. Not derived from filter.go's FilterNil, which swaps from the end and does not
//   keep order; ScanSpanPackedAVX512's test compares against the reference in ORDER.
// - the rest of the file: original go2cs code.
//
// NOT REPRODUCED: the assembly's full-width stores also write lanes past the returned count (up to 7 words). Their
// contents are unspecified and nothing reads them. This file writes only the words it returns.
//
// WHY MANAGED BODIES. The kernels are AVX-512 assembly (expand_amd64.s is generated by mkasm.go). The converted package
// declares them as bodiless partials, and without these bodies each one would be a generated stub that throws. Go runs
// them only where avx512ScanPackedReqsMet holds (scan_amd64.go): VL, BW, GFNI, BITALG, DQ and VBMI.
// internal/cpu/amd64/cpu_x86_impl.cs reads HasAVX512BITALG from CPUID as Go's doinit does, so CanAVX512() reads the
// hardware here too, and these bodies are what it then reaches. Plain loops, not Vector512: .NET has no BITALG
// (VPOPCNTB). ExpandAVX512 is "Test-only" in Go's own source, and scanSpanPackedAVX512 is reached only from Go's garbage
// collector, which the converted runtime does not run. So the readable shape costs nothing a program can see.
// gcExpandersAVX512 (the expanders' PCs) stays as emitted: no managed code calls through it.

namespace go.@internal.runtime.gc;

using goarch = go.@internal.goarch_package;
using gc = go.@internal.runtime.gc_package;
using @unsafe = unsafe_package;
using go.@internal;
using go.@internal.runtime;

partial class scan_package {

// ExpandAVX512 expands each bit in packed into f consecutive bits in unpacked, where f is the word size of objects in
// sizeClass. Every word of unpacked is written.
public static partial void ExpandAVX512(nint sizeClass, ж<gc.ObjMask> packed, ж<gc.PtrMask> unpacked) {
    ref var words = ref unpacked.DerefOrNull();

    foreach (var i in range(len(words))) {
        words[i] = 0;
    }
    ExpandReference(sizeClass, packed, unpacked);
}

// scanSpanPackedAVX512 writes, in order, every word of mem whose bit is set both in objMarks expanded to words and in
// ptrMask, zero words included, and returns how many it wrote.
internal static partial int32 /*count*/ scanSpanPackedAVX512(@unsafe.Pointer mem, ж<uintptr> bufp, ж<gc.ObjMask> objMarks, uintptr sizeClass, ж<gc.PtrMask> ptrMask) {
    int32 count = default;
    ref var ptrs = ref ptrMask.DerefOrNull();

    // The grey word mask: one bit per word of a marked object.
    ref var grey = ref heap(new gc.PtrMask(), out var Ꮡgrey);
    ExpandAVX512((nint)sizeClass, objMarks, Ꮡgrey);

    var buf = @unsafe.Slice(bufp, gc.PageWords);
    foreach (var word in range(gc.PageWords)) {
        var bit = ((uintptr)1).Lsh((int64)(word % (nint)goarch.PtrBits));
        if ((uintptr)(grey[word / (nint)goarch.PtrBits] & ptrs[word / (nint)goarch.PtrBits] & bit) == 0) {
            continue;
        }
        buf[count] = ~@unsafe.Pointer.To<uintptr>(@unsafe.Add(mem, word * (nint)goarch.PtrSize));
        count++;
    }
    return count;
}

// FilterNilAVX512 removes the zero words from bufp[:n], keeping the order of the rest, and returns the new length.
public static partial int32 FilterNilAVX512(ж<uintptr> bufp, int32 n) {
    var buf = @unsafe.Slice(bufp, (nint)n);
    int32 cnt = 0;
    foreach (var (_, p) in range(buf)) {
        if (p == 0) {
            continue;
        }
        buf[cnt] = p;
        cnt++;
    }
    return cnt;
}

} // end scan_package
