// step processes the next opcode and updates r.state. If the opcode
// emits a row in the line table, this updates *entry and returns
// true.
internal static bool step(this ref ΔLineReader r, ж<LineEntry> Ꮡentry) {
    ref var entry = ref Ꮡentry.DerefOrNull();

    nint opcode = (nint)r.buf.uint8();

    if (opcode >= r.opcodeBase) {
        // Special opcode [DWARF2 6.2.5.1, DWARF4 6.2.5.1]
        nint adjustedOpcode = opcode - r.opcodeBase;
        r.advancePC(quo(adjustedOpcode, r.lineRange));
        nint lineDelta = r.lineBase + rem(adjustedOpcode, r.lineRange);
        r.state.Line += lineDelta;
        goto emit;
    }

    switch (opcode) {
    case 0: {
        // Extended opcode [DWARF2 6.2.5.3]
        var length = (Offset)(uint32)r.buf.@uint();
        var startOff = r.buf.off;
        var opcodeΔ2 = r.buf.uint8();

        switch (opcodeΔ2) {
        case var ᴛ2 when ᴛ2 == lneEndSequence: {
            r.state.EndSequence = true;
            entry = r.state;
            r.resetState();
            break;
        }
        case var ᴛ2 when ᴛ2 == lneSetAddress: {
            switch (r.addrsize) {
            case 1: {
                r.state.Address = (uint64)r.buf.uint8();
                break;
            }
            case 2: {
                r.state.Address = (uint64)r.buf.uint16();
                break;
            }
            case 4: {
                r.state.Address = (uint64)r.buf.uint32();
                break;
            }
            case 8: {
                r.state.Address = r.buf.uint64();
                break;
            }
            default: {
                r.buf.error(unknownAddressSizeˢ);
                break;
            }}
            break;
        }
        case var ᴛ2 when ᴛ2 == lneDefineFile: {
            {
                var (done, err) = r.readFileEntry(); if (err != nil) {
                    r.buf.err = err;
                    return false;
                } else if (done) {
                    r.buf.err = new DecodeError("line"u8, startOff, "malformed DW_LNE_define_file operation"u8);
                    return false;
                }
