// p521Square squares a field element in the Montgomery domain.
//
// Preconditions:
//
//	0 ≤ eval arg1 < m
//
// Postconditions:
//
//	eval (from_montgomery out1) mod m = (eval (from_montgomery arg1) * eval (from_montgomery arg1)) mod m
//	0 ≤ eval out1 < m
internal static void p521Square(ref p521MontgomeryDomainFieldElement out1, ref p521MontgomeryDomainFieldElement arg1) {
    p521Mul(ref out1, ref arg1, ref arg1);
}

// Mul64 is the full 64x64 -> 128-bit product, high word returned and low word out, from four 32x32 -> 64
// products. Each is one IMUL, whose time does not depend on its operands, and the sums cannot overflow: the
// middle sum is below 3 * 2^32. It is not Math.BigMul for ReadyToRun's sake (see the file header).
[MethodImpl(MethodImplOptions.AggressiveInlining)]
private static ulong Mul64(ulong x, ulong y, out ulong lo) {
    ulong x0 = (uint)x, x1 = x >> 32, y0 = (uint)y, y1 = y >> 32;
    ulong p00 = x0 * y0, p01 = x0 * y1, p10 = x1 * y0, p11 = x1 * y1;
    ulong mid = (p00 >> 32) + (uint)p01 + (uint)p10;
    lo = (mid << 32) | (uint)p00;
    return p11 + (p01 >> 32) + (p10 >> 32) + (mid >> 32);
}

