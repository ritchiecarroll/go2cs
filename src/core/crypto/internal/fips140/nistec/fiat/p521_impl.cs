// Hand-owned p521Mul and p521Square for crypto/internal/fips140/nistec/fiat
// (manualConversionFuncs["crypto/internal/fips140/nistec/fiat"]; H, COORD ruling 2026-11-06).
//
// WHY THIS EXISTS. fiat-crypto's word-by-word Montgomery output for P-521 converts faithfully, but each
// of these two functions declares 1,006 locals, past the JIT's 512-local cut-off for inlining INTO a
// method. Nothing inlines, so every bits.Mul64, bits.Add64, p521Uint1 conversion and limb read stays a
// call: 1,250 per field multiply, the same under the JIT and under ReadyToRun, where calls into
// math.bits, golib and CoreLib cannot inline at all. Measured on H (win-x64, runtime 10.0.13): a field
// multiply took 2.37 us under the JIT and 13.7 us under ReadyToRun against Go's 190 ns, and the P-521
// generator-table build that crypto/tls's test package pays at every start took 523 ms against Go's 6 ms
// (docs/phase4/DATA-p521-table.md). Lever 2 of docs/phase4/DATA-bogo-startup.md section 8.4.
//
// WHAT IT COMPUTES. fiat's own contract, unchanged: the arguments are Montgomery-domain elements below
// p = 2^521 - 1, and out1 = (arg1 * arg2 * R^-1) mod p, fully reduced, with R = 2^576. A fully reduced
// residue has exactly one nine-limb representation, so the limbs are fiat's limbs. The method is
// word-by-word Montgomery multiplication (CIOS) over nine 64-bit limbs:
//   - p = -1 (mod 2^64), so m' = -p^-1 mod 2^64 = 1 and each round's quotient digit is m = t0;
//   - p = 2^521 - 1, so (t + m*p) / 2^64 = (t - t0) / 2^64 + m * 2^457, and 457 = 7*64 + 9: the reduction
//     is a one-limb shift plus m << 9 into limb 7 and m >> 55 into limb 8, with no multiply;
//   - before each round t < 2p < 2^522, so limb 9 is zero entering it and the round cannot overflow ten
//     limbs; after the last round t < 2p, and one masked subtraction of p reduces it fully.
// p521Square is p521Mul of an element by itself, as fiat's own Square is the same product.
//
// CONSTANT TIME, as fiat's output is. The body is straight-line: no loop, no branch, and every limb
// index is a constant. Carries and borrows are computed with math/bits' own Add64/Sub64 formulas
// (bitwise, no comparison and no flag read), the 64x64->128 product is four 32x32->64 multiplies, and the
// final reduction selects d = t - p or t through a mask, as fiat's p521CmovznzU64 does. CHECKED by reading the compiled body under the JIT and under crossgen2: its only conditional
// jumps are the limb wrappers' null and bounds checks, which test a field's presence and a constant index
// against the array's fixed length of nine, never a limb's value (DATA-p521-table.md, the listing).
//
// VERIFIED against an oracle with no dependency on this repository: GolibTests P521FieldDifferentialTests
// compares Mul and Square with System.Numerics.BigInteger on every edge fiat's input contract admits and
// on 20,000 seeded random pairs, and the P521CurveBytes behavioral test compares P-521 ECDH, ECDSA and
// crypto/elliptic output with Go byte for byte. The Go functions this displaces are pinned by source hash
// (repoguard TestHandOwnedReimplementationsMatchPinnedGoSource), so a release hop that changes fiat's
// p521Mul or p521Square fails there, naming this file, until it is re-derived.
//
// WHY THE PRODUCT IS NOT Math.BigMul. ReadyToRun's runtime DISCARDS a precompiled body that uses an
// instruction-set-dependent intrinsic when the CPU's support differs from crossgen2's baseline, and then
// JIT-compiles the method at its first call. Math.BigMul, Bmi2.X64.MultiplyNoFlags behind IsSupported and
// UInt128 multiplication are all such intrinsics, and each made the BoGo-shaped host JIT p521Mul at run time,
// 8 to 19 ms of JIT at start-up, while the four-product spelling here keeps the precompiled body: measured
// variant by variant with DOTNET_JitDisasmSummary (DATA-p521-table.md). math/bits' Mul64 calls Math.BigMul
// and is discarded and JIT-compiled the same way.
//
// The straight-line body below is GENERATED by docs/phase4/data/p521-table/gen_p521_impl.py, which
// states the rounds in a dozen lines; regenerate rather than hand-edit it.

