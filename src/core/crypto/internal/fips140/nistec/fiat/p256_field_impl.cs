    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t2 = s; c = hi + k;
    hi = Mul64(a3, b2, out lo);
    s = lo + t3; k = ((lo & t3) | ((lo | t3) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t3 = s; c = hi + k;
    s = t4 + c; k = ((t4 & c) | ((t4 | c) & ~s)) >> 63; t4 = s; t5 = k;
    m = t0;
    hi = Mul64(m, ulong.MaxValue, out lo);
    s = lo + t0; k = ((lo & t0) | ((lo | t0) & ~s)) >> 63; c = hi + k;
    hi = Mul64(m, 0xFFFFFFFFUL, out lo);
    s = lo + t1; k = ((lo & t1) | ((lo | t1) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t0 = s; c = hi + k;
    s = t2 + c; k = ((t2 & c) | ((t2 | c) & ~s)) >> 63; t1 = s; c = k;
    hi = Mul64(m, 0xFFFFFFFF00000001UL, out lo);
    s = lo + t3; k = ((lo & t3) | ((lo | t3) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t2 = s; c = hi + k;
    s = t4 + c; k = ((t4 & c) | ((t4 | c) & ~s)) >> 63; t3 = s; t4 = t5 + k; t5 = 0;

    // Round 3: t += a * b3, then t = (t + m*p) / 2^64 with m = t0.
    c = 0;
    hi = Mul64(a0, b3, out lo);
    s = lo + t0; k = ((lo & t0) | ((lo | t0) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t0 = s; c = hi + k;
    hi = Mul64(a1, b3, out lo);
    s = lo + t1; k = ((lo & t1) | ((lo | t1) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t1 = s; c = hi + k;
    hi = Mul64(a2, b3, out lo);
    s = lo + t2; k = ((lo & t2) | ((lo | t2) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t2 = s; c = hi + k;
    hi = Mul64(a3, b3, out lo);
    s = lo + t3; k = ((lo & t3) | ((lo | t3) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t3 = s; c = hi + k;
    s = t4 + c; k = ((t4 & c) | ((t4 | c) & ~s)) >> 63; t4 = s; t5 = k;
    m = t0;
    hi = Mul64(m, ulong.MaxValue, out lo);
    s = lo + t0; k = ((lo & t0) | ((lo | t0) & ~s)) >> 63; c = hi + k;
    hi = Mul64(m, 0xFFFFFFFFUL, out lo);
    s = lo + t1; k = ((lo & t1) | ((lo | t1) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t0 = s; c = hi + k;
    s = t2 + c; k = ((t2 & c) | ((t2 | c) & ~s)) >> 63; t1 = s; c = k;
    hi = Mul64(m, 0xFFFFFFFF00000001UL, out lo);
    s = lo + t3; k = ((lo & t3) | ((lo | t3) & ~s)) >> 63; lo = s; hi += k;
    s = lo + c; k = ((lo & c) | ((lo | c) & ~s)) >> 63; t2 = s; c = hi + k;
    s = t4 + c; k = ((t4 & c) | ((t4 | c) & ~s)) >> 63; t3 = s; t4 = t5 + k; t5 = 0;

    // t < 2p. Subtract p once with a borrow chain, then select the result by mask: d when the
    // subtraction did not borrow or t4 carries (t >= p), t otherwise. No branch reads a limb.
    ulong borrow = 0;
    ulong d0 = t0 - ulong.MaxValue - borrow; borrow = ((~t0 & ulong.MaxValue) | (~(t0 ^ ulong.MaxValue) & d0)) >> 63;
    ulong d1 = t1 - 0xFFFFFFFFUL - borrow; borrow = ((~t1 & 0xFFFFFFFFUL) | (~(t1 ^ 0xFFFFFFFFUL) & d1)) >> 63;
    ulong d2 = t2 - 0x0UL - borrow; borrow = ((~t2 & 0x0UL) | (~(t2 ^ 0x0UL) & d2)) >> 63;
    ulong d3 = t3 - 0xFFFFFFFF00000001UL - borrow; borrow = ((~t3 & 0xFFFFFFFF00000001UL) | (~(t3 ^ 0xFFFFFFFF00000001UL) & d3)) >> 63;
    ulong keepD = 0UL - ((borrow ^ 1) | t4);
    out1[0] = (d0 & keepD) | (t0 & ~keepD);
    out1[1] = (d1 & keepD) | (t1 & ~keepD);
    out1[2] = (d2 & keepD) | (t2 & ~keepD);
    out1[3] = (d3 & keepD) | (t3 & ~keepD);
    // END GENERATED
}

// p256Square squares a field element in the Montgomery domain.
//
// Preconditions:
//
//	0 ≤ eval arg1 < m
//
// Postconditions:
//
//	eval (from_montgomery out1) mod m = (eval (from_montgomery arg1) * eval (from_montgomery arg1)) mod m
//	0 ≤ eval out1 < m
internal static void p256Square(ref p256MontgomeryDomainFieldElement out1, ref p256MontgomeryDomainFieldElement arg1) {
    p256Mul(ref out1, ref arg1, ref arg1);
}

