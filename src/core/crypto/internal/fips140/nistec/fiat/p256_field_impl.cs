// Hand-owned p256Mul and p256Square for crypto/internal/fips140/nistec/fiat
// (manualConversionFuncs["crypto/internal/fips140/nistec/fiat"]; R, COORD ruling 2026-11-07).
// p256_impl.cs beside it is a different companion: the Montgomery-limb loader, which displaces nothing.
//
// WHY THIS EXISTS. fiat-crypto's P-256 output converts faithfully and, unlike P-384 and P-521, inlines
// fully under the JIT (182 locals; 28 MULX, calls only on cold paths). Under ReadyToRun each assembly is
// precompiled alone, so every call into math/bits and golib stays a call: 136 per field multiply (51
// bits.Add64, 28 bits.Mul64, 5 bits.Sub64, 24 limb reads, 24 cold materializeValue, 4 p256CmovznzU64).
// Measured on R-LAPTOP (win-x64, runtime 10.0.11): a field multiply took 0.32 to 0.43 us under the JIT and
// 1.6 us under ReadyToRun, and a TLS 1.3 handshake on an ECDSA P-256 certificate with P-256 key exchange
// 60 ms under ReadyToRun (docs/phase4/DATA-p256-field.md). P-256 is the curve TLS negotiates on the
// purego path this corpus is, so the bubble is paid on every such handshake.
//
// WHAT IT COMPUTES. fiat's own contract, unchanged: the arguments are Montgomery-domain elements below
// p = 2^256 - 2^224 + 2^192 + 2^96 - 1, and out1 = (arg1 * arg2 * R^-1) mod p, fully reduced, with
// R = 2^256. A fully reduced residue has exactly one four-limb representation, so the limbs are fiat's
// limbs. The method is word-by-word Montgomery multiplication (CIOS) over four 64-bit limbs:
//   - p's low limb is 2^64 - 1, so m' = -p^-1 mod 2^64 = 1 and each round's quotient digit is m = t0;
//   - p's limb 2 is zero, so its product is left out (a constant of the prime, not a data-dependent
//     choice), and the reduction multiplies m by the other three limbs;
//   - before each round t < 2p < 2^257, so limb 5 is zero entering it and receives at most a one-bit
//     carry; after the last round t < 2p, and one masked subtraction of p reduces it fully.
// p256Square is p256Mul of an element by itself, as fiat's own Square is the same product.
//
// CONSTANT TIME, as fiat's output is. The body is straight-line: no loop, no branch, and every limb
// index is a constant. Carries and borrows are computed with math/bits' own Add64/Sub64 formulas
// (bitwise, no comparison and no flag read), the 64x64->128 product is p521_impl.cs's four-product
// Mul64 (one constant-time primitive for every curve), and the final reduction selects d = t - p or t
// through a mask, as fiat's p256CmovznzU64 does. CHECKED by reading the compiled body under the JIT and
// under crossgen2: its only conditional jumps are the limb wrappers' null and bounds checks, which test a
// field's presence and a constant index against the array's fixed length of four, never a limb's value
// (DATA-p256-field.md, the listings).
//
// VERIFIED against an oracle with no dependency on this repository: GolibTests P256FieldDifferentialTests
// compares Mul and Square with System.Numerics.BigInteger on every edge fiat's input contract admits, on
// 20,000 seeded random pairs, and on raw limbs where only the final select reduces, and the P256CurveBytes
// behavioral test compares P-256 ECDH, ECDSA and crypto/elliptic output with Go byte for byte. The Go
// functions this displaces are pinned by source hash (repoguard
// TestHandOwnedReimplementationsMatchPinnedGoSource), so a release hop that changes fiat's p256Mul or
// p256Square fails there, naming this file, until it is re-derived.
//
// The straight-line body below is GENERATED by docs/phase4/data/p256-field/gen_p256_impl.py, which
// states the rounds in a dozen lines; regenerate rather than hand-edit it.

