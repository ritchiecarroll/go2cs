// Hand-owned p384Mul and p384Square for crypto/internal/fips140/nistec/fiat
// (manualConversionFuncs["crypto/internal/fips140/nistec/fiat"]; R, COORD ruling 2026-11-06).
//
// WHY THIS EXISTS. fiat-crypto's word-by-word Montgomery output for P-384 converts faithfully, but each
// of these two functions starts at about 460 locals, and every inlined callee adds temporaries, so the
// JIT stops inlining into them after about 74 callees. The rest stay calls: 590 per field multiply
// (292 p384Uint1 conversions, 137 bits.Add64, 73 bits.Mul64, 36 limb reads, 7 bits.Sub64, 6
// p384CmovznzU64), and under ReadyToRun no math/bits call can inline at all. Measured on R-LAPTOP
// (win-x64, runtime 10.0): a field multiply took 2.07 us under the JIT and 5.06 us under ReadyToRun
// against Go's 77 ns, and a P-384 ScalarBaseMult 3.44 ms and 9.0 ms against Go's 175 us
// (docs/phase4/DATA-p384-field.md). The same seam as p521_impl.cs, at a smaller scale.
//
// WHAT IT COMPUTES. fiat's own contract, unchanged: the arguments are Montgomery-domain elements below
// p = 2^384 - 2^128 - 2^96 + 2^32 - 1, and out1 = (arg1 * arg2 * R^-1) mod p, fully reduced, with
// R = 2^384. A fully reduced residue has exactly one six-limb representation, so the limbs are fiat's
// limbs. The method is word-by-word Montgomery multiplication (CIOS) over six 64-bit limbs:
//   - p's low limb is 2^32 - 1, so m' = -p^-1 mod 2^64 = 0x100000001, the constant fiat's body uses,
//     and each round's quotient digit is m = t0 * 0x100000001;
//   - p is not a Mersenne prime, so the reduction multiplies m by every limb of p (36 products beside
//     the 36 of a * b);
//   - before each round t < 2p < 2^385, so limb 7 is zero entering it and receives at most a one-bit
//     carry; after the last round t < 2p, and one masked subtraction of p reduces it fully.
// p384Square is p384Mul of an element by itself, as fiat's own Square is the same product.
//
// CONSTANT TIME, as fiat's output is. The body is straight-line: no loop, no branch, and every limb
// index is a constant. Carries and borrows are computed with math/bits' own Add64/Sub64 formulas
// (bitwise, no comparison and no flag read), the 64x64->128 product is p521_impl.cs's four-product
// Mul64 (one constant-time primitive for both curves), and the final reduction selects d = t - p or t
// through a mask, as fiat's p384CmovznzU64 does. CHECKED by reading the compiled body under the JIT and
// under crossgen2: its only conditional jumps are the limb wrappers' null and bounds checks, which test a
// field's presence and a constant index against the array's fixed length of six, never a limb's value
// (DATA-p384-field.md, the listings).
//
// VERIFIED against an oracle with no dependency on this repository: GolibTests P384FieldDifferentialTests
// compares Mul and Square with System.Numerics.BigInteger on every edge fiat's input contract admits, on
// 20,000 seeded random pairs, and on raw limbs where only the final select reduces, and the P384CurveBytes
// behavioral test compares P-384 ECDH, ECDSA and crypto/elliptic output with Go byte for byte. The Go
// functions this displaces are pinned by source hash (repoguard
// TestHandOwnedReimplementationsMatchPinnedGoSource), so a release hop that changes fiat's p384Mul or
// p384Square fails there, naming this file, until it is re-derived.
//
// The straight-line body below is GENERATED by docs/phase4/data/p384-field/gen_p384_impl.py, which
// states the rounds in a dozen lines; regenerate rather than hand-edit it.

