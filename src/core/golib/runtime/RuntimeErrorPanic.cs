    /// <summary>
    /// Invoked on the throwing goroutine each time a Go frame's panic filter examines an exception
    /// (<see cref="TryAsPanic"/>), during the filter pass and so BEFORE the frames between the throw
    /// and the handler unwind. The runtime registers the release of its stop-the-world locks here
    /// (runtime managed_impl.cs, stopTheWorld): a region that throws while holding worldsema or
    /// metricsSema would otherwise leave it held for every later caller, where Go fatals ("panic
    /// during preemptoff"). The handler must be cheap and idempotent; filters run once per
    /// enclosing Go frame. Unregistered, nothing runs (golib sits under runtime and cannot name it).
    /// </summary>
    public static Action? PanicObserved { get; set; }

    /// <summary>
    /// Converts a .NET exception that corresponds to a Go runtime panic into a <see cref="PanicException"/>,
    /// so it can be recovered with <c>recover()</c> and reported like a Go panic. Returns <c>false</c>
    /// (leaving the exception to propagate unchanged) for exceptions that are not Go runtime panics.
    /// </summary>
    /// <param name="ex">Exception to inspect.</param>
    /// <param name="panic">Resulting panic when the exception maps to a Go runtime panic.</param>
    /// <returns><c>true</c> if <paramref name="ex"/> is (or maps to) a Go panic; otherwise <c>false</c>.</returns>
    /// <remarks>
    /// This is the ONE place a .NET exception becomes a Go panic, so it is also where the panic's
    /// origin is snapshotted (<see cref="PanicException.PanicTrace"/>) — a mapped runtime error is
    /// synthesized HERE and was never thrown at the fault site, so only <paramref name="ex"/> carries
    /// those frames, and once this returns they are the caller's last chance to be recorded. Doing it
    /// at the adoption point rather than in each adopter is what lets a panic that passes through NO
    /// <c>GoFunc</c> at all — a function that never defers, so nothing wraps it — still report where
    /// it faulted. The snapshot is once-only, so a panic re-adopted by each enclosing frame keeps the
    /// innermost (deepest) origin, and nothing is computed on a non-panicking path.
    /// </remarks>
    public static bool TryAsPanic(Exception ex, [NotNullWhen(true)] out PanicException? panic)
    {
        PanicObserved?.Invoke();

        switch (ex)
        {
            case PanicException panicException:
                panic = panicException;
                panic.CaptureThrowSite(ex);
                return true;
            case DivideByZeroException:
                // Go: integer division or modulo by zero panics with a runtime error. .NET raises
                // DivideByZeroException for the same operation; map it so recover() behaves like Go.
                panic = IntegerDivideByZero();
                panic.CaptureThrowSite(ex);
                return true;
            case NullReferenceException:
                // Go: dereferencing a nil pointer panics with "runtime error: invalid memory address
                // or nil pointer dereference" — a RECOVERABLE panic that real Go code relies on
                // (sync's TestNilPool calls Get/Put on a nil *Pool and requires recover() to catch
                // it). The converted equivalent — reading `Ꮡp.Value` through a nil ж<T>, or any nil
                // reference deref in emitted code — raises NullReferenceException, which recover()
                // could not see, so the panic escaped as an unrecoverable infrastructure error.
                // Mapping it here gives recover() Go's behavior and prints Go's message verbatim.
                panic = NilPointerDereference();
                panic.CaptureThrowSite(ex);
                return true;
            default:
                panic = null;
                return false;
        }
    }

    private const string InvalidPrefixDowncastMessage =
        $"{RuntimeErrorMessage}invalid prefix downcast to *{{0}} (the *{{1}} behind this pointer is not the first field of a {{0}})";
    /// <summary>
    /// The REFUSAL of Go's prefix-downcast idiom, <c>(*entry[T])(unsafe.Pointer(n))</c>, over a first-field view
    /// whose offset-0 chain reaches no box of the destination type: in Go the larger object would be read past
    /// the header, and here there is no such object to answer, so the conversion says so by name.
    /// </summary>
    /// <param name="destination">The destination type, as Go's <c>%T</c> prints it.</param>
    /// <param name="source">The source pointer's element type, as Go's <c>%T</c> prints it.</param>
    public static PanicException InvalidPrefixDowncast(string destination, string source)
    {
        return new PanicException((@string)string.Format(InvalidPrefixDowncastMessage, destination, source));
    }

    /// <summary>
    /// Supplies Go 1.26's <c>maps.unhashableTypeError</c> (internal/runtime/maps, map.go) for an
    /// unhashable key type: the value <c>mapKeyError</c> panics with.
    /// </summary>
    /// <remarks>
    /// Registered by the internal/runtime/maps package through the runtime package's value bridge, as
    /// <see cref="PlainErrorValue"/> is, because golib sits below both and cannot name the type. Go
    /// 1.26 raises it where a map operation must refuse an unhashable dynamic key WITHOUT reaching the
    /// hash: a lookup or delete on an EMPTY or NIL map (issue 23734) and reflect's equivalents. Its
    /// <c>Error()</c> is <c>"hash of unhashable type: " + T</c> -- no <c>runtime error: </c> prefix and a
    /// colon -- and it satisfies <c>runtime.Error</c> through its <c>RuntimeError()</c> method. Go 1.24
    /// raised the prefixed <c>errorString</c> there instead; the hash path itself (a populated map, any
    /// assignment) still does. Unregistered, the bare text stands.
    /// </remarks>
    public static Func<Type, object>? UnhashableKeyErrorValue { get; set; }

    /// <summary>
    /// Go 1.26's panic for an unhashable map key found by <c>mapKeyError</c>: an empty or nil map's
    /// lookup or delete, or reflect's nil-map and empty-map arms.
    /// </summary>
    /// <param name="unhashable">The slice, map or func type Go names, found inside the key's dynamic type.</param>
    public static PanicException UnhashableKey(Type unhashable)
    {
        return new PanicException(UnhashableKeyErrorValue?.Invoke(unhashable) ?? $"hash of unhashable type: {GoReflect.GoTypeName(unhashable)}");
    }

    /// <summary>
    /// Supplies the Go runtime's <c>runtime.errorString</c> for a message: the value runtime's own
    /// <c>panic(errorString("..."))</c> sites raise (alg.go's "hash of unhashable type", slice.go's
    /// growslice and makeslice checks).
    /// </summary>
    /// <remarks>
    /// Registered by the runtime package, as <see cref="PlainErrorValue"/> is. The message is the text
    /// WITHOUT the prefix: <c>errorString.Error()</c> prepends <c>runtime error: </c>, and the value
    /// satisfies <c>runtime.Error</c> through <c>RuntimeError()</c>. Unregistered, the prefixed text
    /// stands as a plain string.
    /// </remarks>
    public static Func<string, object>? ErrorStringValue { get; set; }

    /// <summary>
    /// A Go runtime panic whose value is <c>runtime.errorString(message)</c>.
    /// </summary>
    /// <param name="message">The text after the <c>runtime error: </c> prefix.</param>
    public static PanicException ErrorString(string message)
    {
        return new PanicException(ErrorStringValue?.Invoke(message) ?? RuntimeErrorMessage + message);
    }
