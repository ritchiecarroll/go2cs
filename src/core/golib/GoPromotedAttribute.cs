using System;

namespace go;

/// <summary>
/// Marks go2cs-gen's forwarder of a method promoted from an embedded field, the receiver-by-value (or
/// <c>this ref</c>) form the outer type's method set reads.
/// </summary>
/// <remarks>
/// <para>
/// A promoted forwarder and a method the type declares are both extension methods on the type, the same in
/// every other way, and a type that declares a method of the same name as one an embedded field has gets no
/// forwarder: its own method shadows the embed's, as in Go. This attribute is what tells them apart at run
/// time, where Go's behavior differs: a value method called through a nil <c>*T</c> is Go's panicwrap
/// ("value method pkg.T.M called using nil *T pointer") for a method <c>T</c> declares, and the nil-pointer
/// fault for one it promotes, raised where the autogenerated wrapper dereferences the embed.
/// </para>
/// </remarks>
[AttributeUsage(AttributeTargets.Method)]
public sealed class GoPromotedAttribute : Attribute;
