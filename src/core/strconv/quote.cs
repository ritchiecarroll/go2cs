// bsearch is semantically the same as [slices.BinarySearch] (without NaN checks)
// We copied this function because we can not import "slices" here.
internal static (nint, bool) bsearch<S, E>(S s, E v)
    where S : /* ~[]E */ ISlice<E>, ISupportMake<S>, ISliceWrap<S, E>, new()
    where E : /* ~uint16 | ~uint32 */ IAdditionOperators<E, E, E>, ISubtractionOperators<E, E, E>, IMultiplyOperators<E, E, E>, IDivisionOperators<E, E, E>, IIncrementOperators<E>, IDecrementOperators<E>, IUnaryNegationOperators<E, E>, IModulusOperators<E, E, E>, IBitwiseOperators<E, E, E>, IShiftOperators<E, int, E>, IEqualityOperators<E, E, bool>, IComparisonOperators<E, E, bool>, new()
{
    nint n = len(s);
    nint i = 0;
    nint j = n;
    while (i < j) {
        nint h = i + ((j - i) >> 1);
        if (s[h] < v) {
            i = h + 1;
        } else {
            j = h;
        }
    }
    return (i, i < n && AreEqual(s[i], v));
}

// TODO: IsPrint is a local implementation of unicode.IsPrint, verified by the tests
// to give the same answer. It allows this package not to depend on unicode,
// and therefore not pull in all the Unicode tables. If the linker were better
// at tossing unused tables, we could get rid of this implementation.
// That would be nice.

// IsPrint reports whether the rune is defined as printable by Go, with
// the same definition as [unicode.IsPrint]: letters, numbers, punctuation,
// symbols and ASCII space.
public static bool IsPrint(rune r) {
    // Fast check for Latin-1
    if (r <= 0xFF) {
        if (0x20 <= r && r <= 0x7E) {
            // All the ASCII is printable from space through DEL-1.
            return true;
        }
        if (0xA1 <= r && r <= 0xFF) {
            // Similarly for ¡ through ÿ...
            return r != 0xAD; // ...except for the bizarre soft hyphen.
        }
        return false;
    }

    // Same algorithm, either on uint16 or uint32 value.
    // First, find first i such that isPrint[i] >= x.
    // This is the index of either the start or end of a pair that might span x.
    // The start is even (isPrint[i&^1]) and the end is odd (isPrint[i|1]).
    // If we find x in a range, make sure x is not in isNotPrint list.

    if (0 <= r && r < (rune)(1 << 16)) {
        var (rrΔ1, isPrintΔ1, isNotPrintΔ1) = ((uint16)r, isPrint16, isNotPrint16);
        var (iΔ1, _) = bsearch(isPrintΔ1, rrΔ1);
        if (iΔ1 >= len(isPrintΔ1) || rrΔ1 < isPrintΔ1[(iΔ1 & ~(nint)1)] || isPrintΔ1[(iΔ1 | 1)] < rrΔ1) {
            return false;
        }
        var (_, foundΔ1) = bsearch(isNotPrintΔ1, rrΔ1);
        return !foundΔ1;
    }

    var (rr, isPrint, isNotPrint) = ((uint32)r, isPrint32, isNotPrint32);
    var (i, _) = bsearch(isPrint, rr);
    if (i >= len(isPrint) || rr < isPrint[(i & ~(nint)1)] || isPrint[(i | 1)] < rr) {
        return false;
    }
    if (r >= 0x20000) {
        return true;
    }
    r -= 0x10000;
    var (_, found) = bsearch(isNotPrint, (uint16)r);
    return !found;
}

// IsGraphic reports whether the rune is defined as a Graphic by Unicode. Such
// characters include letters, marks, numbers, punctuation, symbols, and
// spaces, from categories L, M, N, P, S, and Zs.
public static bool IsGraphic(rune r) {
    if (IsPrint(r)) {
        return true;
    }
    return isInGraphicList(r);
}

// isInGraphicList reports whether the rune is in the isGraphic list. This separation
// from IsGraphic allows quoteWith to avoid two calls to IsPrint.
// Should be called only if IsPrint fails.
internal static bool isInGraphicList(rune r) {
    // We know r must fit in 16 bits - see makeisprint.go.
    if (r > 0xFFFF) {
        return false;
    }
    var (_, found) = bsearch(isGraphic, (uint16)r);
    return found;
}

