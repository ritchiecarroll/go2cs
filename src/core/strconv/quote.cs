// UnquoteChar decodes the first character or byte in the escaped string
// or character literal represented by the string s.
// It returns four values:
//
//  1. value, the decoded Unicode code point or byte value;
//  2. multibyte, a boolean indicating whether the decoded character requires a multibyte UTF-8 representation;
//  3. tail, the remainder of the string after the character; and
//  4. an error that will be nil if the character is syntactically valid.
//
// The second argument, quote, specifies the type of literal being parsed
// and therefore which escaped quote character is permitted.
// If set to a single quote, it permits the sequence \' and disallows unescaped '.
// If set to a double quote, it permits \" and disallows unescaped ".
// If set to zero, it does not permit either escape and allows both quote characters to appear unescaped.
public static (rune value, bool multibyte, @string tail, error err) UnquoteChar(@string s, byte quote) {
    rune value = default;
    bool multibyte = default;
    @string tail = default;
    error err = default;

    // easy cases
    if (len(s) == 0) {
        err = ErrSyntax;
        return (value, multibyte, tail, err);
    }
    {
        var cΔ1 = s[0];
        switch (ᐧ) {
        case {} when cΔ1 == quote && (quote == (byte)'\'' || quote == (byte)'"'): {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        case {} when cΔ1 >= utf8.RuneSelf: {
            var (r, size) = utf8.DecodeRuneInString(s);
            return (r, true, s.slice(size), default);
        }
        case {} when cΔ1 is not (byte)'\\': {
            return ((rune)s[0], false, s[1..], default);
        }}
    }

    // hard case: c is backslash
    if (len(s) <= 1) {
        err = ErrSyntax;
        return (value, multibyte, tail, err);
    }
    var c = s[1];
    s = s[2..];

    switch (c) {
    case (byte)'a': {
        value = '\a';
        break;
    }
    case (byte)'b': {
        value = '\b';
        break;
    }
    case (byte)'f': {
        value = '\f';
        break;
    }
    case (byte)'n': {
        value = '\n';
        break;
    }
    case (byte)'r': {
        value = '\r';
        break;
    }
    case (byte)'t': {
        value = '\t';
        break;
    }
    case (byte)'v': {
        value = '\v';
        break;
    }
    case (byte)'x' or (byte)'u' or (byte)'U': {
        nint n = 0;
        switch (c) {
        case (byte)'x': {
            n = 2;
            break;
        }
        case (byte)'u': {
            n = 4;
            break;
        }
        case (byte)'U': {
            n = 8;
            break;
        }}
        rune v = default;
        if (len(s) < n) {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        for (nint j = 0; j < n; j++) {
            var (x, ok) = unhex(s[j]);
            if (!ok) {
                err = ErrSyntax;
                return (value, multibyte, tail, err);
            }
            v = v << 4 | x;
        }
        s = s.slice(n);
        if (c == 'x') {
            // single-byte string, possibly not UTF-8
            value = v;
            break;
        }
        if (!utf8.ValidRune(v)) {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        value = v;
        multibyte = true;
        break;
    }
    case (byte)'0' or (byte)'1' or (byte)'2' or (byte)'3' or (byte)'4' or (byte)'5' or (byte)'6' or (byte)'7': {
        var v = (rune)c - '0';
        if (len(s) < 2) {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        for (nint j = 0; j < 2; j++) { // one digit already; two more
            var x = (rune)s[j] - '0';
            if (x < 0 || x > 7) {
                err = ErrSyntax;
                return (value, multibyte, tail, err);
            }
            v = (v << 3) | x;
        }
        s = s[2..];
        if (v > 255) {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        value = v;
        break;
    }
    case (byte)'\\': {
        value = '\\';
        break;
    }
    case (byte)'\'' or (byte)'"': {
        if (c != quote) {
            err = ErrSyntax;
            return (value, multibyte, tail, err);
        }
        value = (rune)c;
        break;
    }
    default: {
        err = ErrSyntax;
        return (value, multibyte, tail, err);
    }}
    tail = s;
    return (value, multibyte, tail, err);
}

// QuotedPrefix returns the quoted string (as understood by [Unquote]) at the prefix of s.
// If s does not start with a valid quoted string, QuotedPrefix returns an error.
public static (@string, error) QuotedPrefix(@string s) {
    var (@out, _, err) = unquote(s, false);
    return (@out, err);
}

// Unquote interprets s as a single-quoted, double-quoted,
// or backquoted Go string literal, returning the string value
// that s quotes.  (If s is single-quoted, it would be a Go
// character literal; Unquote returns the corresponding
// one-character string. For an empty character literal
// Unquote returns the empty string.)
public static (@string, error) Unquote(@string s) {
    var (@out, rem, err) = unquote(s, true);
    if (len(rem) > 0) {
        return ("", ErrSyntax);
    }
    return (@out, err);
}

// unquote parses a quoted string at the start of the input,
// returning the parsed prefix, the remaining suffix, and any parse errors.
// If unescape is true, the parsed prefix is unescaped,
// otherwise the input prefix is provided verbatim.
