            u.RshAssign(shift);
        }
        // u < base
        i--;
        a[i] = digits[(nuint)u];
    } else {
        // general case
        var b = (uint64)@base;
        while (u >= b) {
            i--;
            // Avoid using r = a%b in addition to q = a/b
            // since 64bit division and modulo operations
            // are calculated by runtime functions on 32bit machines.
            var q = u / b;
            a[i] = digits[(nuint)(u - q * b)];
            u = q;
        }
        // u < base
        i--;
        a[i] = digits[(nuint)u];
