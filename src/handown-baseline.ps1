<#
.SYNOPSIS
    Writes the retired-hand-own guard's baseline (GoCorpusMigration.md H6, "Durable form"): the union of
    the hand-own marker census at each named commit. Reads git only; writes the one fixture file.

.DESCRIPTION
    The marker census is H6's own predicate, line-anchored and whole-file, over tracked .cs under src/core:

      git grep -l -E '^\s*\[module:\s*(go\.)?GoManualConversion\]' <sha> -- 'src/core/*.cs'

    The population is the MARKED set only. *_impl.cs companions are outside it, as ruled 2026-10-12
    (AUDIT-h6-handown-go124 OQ-1, ruled OUT): a deleted companion leaves its partial declarations without
    bodies and the build fails, while a deleted marked file is replaced by the automatic conversion,
    which compiles.

    Name the previous hop's OUTGOING commit (the merge-base H6 describes; for the go1.24.13 hop, the
    audit's population commit 2e6cf71e4) and the commit the baseline is generated at. A census of the
    generation commit alone reads zero absent entries and says nothing about the hop that just closed.

    The guard (src/go2cs/internal/repoguard/retiredHandOwns_test.go) re-derives the union from the SHAs
    in the file's header and fails when the body differs, so the file is regenerated by this script and
    never edited by hand.

.PARAMETER Sha
    The commits to census, in order. Each must resolve to a commit in this clone.

.PARAMETER Out
    The fixture to write. Defaults to the guard's own testdata file.

.EXAMPLE
    pwsh -File src/handown-baseline.ps1 -Sha 2e6cf71e4,226afb810a
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)] [string[]] $Sha,
    [string] $Out
)

$ErrorActionPreference = 'Stop'
# `pwsh -File` passes "a,b" as ONE string, so split here and the same call works from -File and -Command.
$Sha = @($Sha | ForEach-Object { $_ -split ',' } | Where-Object { $_ })
$root = Split-Path -Parent $PSScriptRoot
if (-not $Out) {
    $Out = Join-Path $root 'src/go2cs/internal/repoguard/testdata/handowns-baseline.txt'
}

$predicate = '^\s*\[module:\s*(go\.)?GoManualConversion\]'
$union = New-Object 'System.Collections.Generic.SortedSet[string]' ([System.StringComparer]::Ordinal)
$header = New-Object System.Collections.Generic.List[string]
[void]$header.Add('# The retired-hand-own guard''s baseline (GoCorpusMigration.md H6, "Durable form").')
[void]$header.Add('# GENERATED by src/handown-baseline.ps1 from the commits below; never edit it by hand.')
[void]$header.Add("# predicate: git grep -l -E '$predicate' <sha> -- 'src/core/*.cs', plus every *_impl.cs in git ls-tree -r <sha> -- src/core")

Push-Location $root
try {
    foreach ($s in $Sha) {
        $full = (git rev-parse --verify --quiet "$s^{commit}")
        if ($LASTEXITCODE -ne 0 -or -not $full) { throw "'$s' does not resolve to a commit in this clone" }
        $marked = @(git grep -l -E $predicate $full -- 'src/core/*.cs')
        $rc = $LASTEXITCODE
        if ($rc -ne 0 -or $marked.Count -eq 0) {
            throw "the marker census at $full returned nothing (git grep rc $rc): wrong clone or broken predicate"
        }
        # The companions too (retiredHandOwns_test.go, THE POPULATION): a lost *_impl.cs compiles, because
        # PartialStubGenerator stubs its bodyless partials, so it is a hand-own the build cannot see go missing.
        $companions = @(git ls-tree -r --name-only $full -- src/core | Where-Object { $_.EndsWith('_impl.cs') })
        if ($LASTEXITCODE -ne 0) { throw "the companion census at $full failed (git ls-tree rc $LASTEXITCODE)" }
        $census = New-Object 'System.Collections.Generic.HashSet[string]' ([System.StringComparer]::Ordinal)
        foreach ($m in $marked) { [void]$census.Add($m.Substring($full.Length + 1)) }
        foreach ($c in $companions) { [void]$census.Add($c) }
        foreach ($p in $census) { [void]$union.Add($p) }
        [void]$header.Add("# sha $full $($census.Count)")
    }
} finally { Pop-Location }

$text = (@($header) + @($union)) -join "`n"
[System.IO.File]::WriteAllText($Out, $text + "`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("{0}: {1} paths, the union of {2} census(es)" -f $Out, $union.Count, $Sha.Count)
