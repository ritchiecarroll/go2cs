// The ONE definition of "which Go packages does this behavioral project own, and in what order does
// the converter have to be invoked on them". LINKED by path into every instrument that transpiles a
// behavioral project, for the same reason ConverterBuildInputs.cs and PlatformExclusive.cs are: those
// instruments take no assembly dependency on one another, so a shared assembly is not available.
//
// It is hoisted here because the invariant it encodes is the one FALSE-GREEN ROUTE #3 was made of.
// Twenty-odd behavioral projects carry NESTED sub-library packages (IoLike\FsLike, VersionedImport\vlib,
// CrossPackageArrayZeroValue\bufpkg, ...). A sub-library's generated package_info.cs is an INPUT to its
// parent's transpile -- the parent reads the sibling's [assembly: GoImplement] records when deciding
// whether to mint a local value adapter -- so the walk must be DEEPEST-FIRST or the parent consumes
// stale-but-plausible records and its golden loses the ability to fail on a regression in that area.
// A top-level-only walk left those sub-libraries un-regenerated by any gate for months, and the damage
// was invisible precisely because each enumerator carried its own copy of the rule. Two copies existed
// when this file was written (BehavioralRunner and BehavioralTestBase); a golden-minting utility that
// re-derived it would have been a third.

using System;
using System.IO;
using System.Linq;

internal static class BehavioralPackages
{
    // A path fragment matching a build-output directory at any depth, built from the host's own
    // separator. The literal @"\bin\" these replaced does not ERROR off Windows -- it simply never
    // matches, so bin/ and obj/ enumerate as behavioral packages and get transpiled.
    private static readonly string s_binFragment = $"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}";
    private static readonly string s_objFragment = $"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}";

    /// <summary>
    /// The PRODUCTION Go sources in one package directory.
    /// </summary>
    /// <remarks>
    /// A production transpile converts the package's production sources only -- go/packages excludes
    /// <c>_test.go</c> -- so an in-package test file has no <c>.cs</c> and no golden, by design. It is
    /// still a real input: the converter scans the sibling test half for declarator names and for
    /// globals whose address it takes (SiblingTestAddressedGlobal guards the latter), which is why such
    /// a file exists in this corpus at all. Every per-<c>.go</c> loop in every enumerator therefore
    /// walks production sources, and a filter that forgot the exclusion would pin an up-to-date check
    /// permanently out of date.
    /// </remarks>
    public static string[] ProductionGoFiles(string packageDir) =>
        Directory.GetFiles(packageDir, "*.go")
            .Where(fileName => !fileName.EndsWith("_test.go", StringComparison.OrdinalIgnoreCase))
            .ToArray();

    /// <summary>
    /// Every Go package directory a behavioral project owns, DEEPEST-FIRST -- the order the converter
    /// must be invoked in.
    /// </summary>
    public static string[] GoPackageDirs(string projectDir) =>
        new[] { projectDir }
            .Concat(Directory.GetDirectories(projectDir, "*", SearchOption.AllDirectories)
                .Where(dirName => !dirName.Contains(s_binFragment, StringComparison.OrdinalIgnoreCase) &&
                                  !dirName.Contains(s_objFragment, StringComparison.OrdinalIgnoreCase))
                .Where(dirName => ProductionGoFiles(dirName).Length > 0))
            .OrderByDescending(dirName => dirName.Count(c => c == Path.DirectorySeparatorChar))
            .ThenBy(dirName => dirName, StringComparer.OrdinalIgnoreCase)
            .ToArray();

    /// <summary>
    /// go2cs.options: one behavioral project's EXTRA converter arguments, one per line. Every instrument that converts
    /// a behavioral project reads it through <see cref="ConverterOptions"/> (check-no-regression.ps1 mirrors it), and the
    /// repoguard TestBehavioralHarnessReadsConverterOptions fails by name if any converter call site stops doing so: a
    /// call site that silently dropped the file would convert the project without -warn, which is false-green route #2's
    /// shape (two instruments disagreeing on how a project converts).
    /// </summary>
    public const string ConverterOptionsFile = "go2cs.options";

    /// <summary>
    /// expected-output.txt: the stdout a project converted under -warn prints up to its refused site, where it must panic
    /// (exit 2, stderr's first line a "panic: go2cs:" refusal). It replaces the Go oracle for that project, whose Go run
    /// would go on past the refused call.
    /// </summary>
    public const string ExpectedOutputFile = "expected-output.txt";

    private static readonly System.Text.RegularExpressions.Regex s_allowedConverterOption = new(@"^-warn=GO2CS\d{4}(,GO2CS\d{4})*$");

    /// <summary>
    /// The project's converter options as one argument prefix ("" when it has no go2cs.options), or the error naming a
    /// line the file may not carry. The file may carry -warn=&lt;codes&gt; and nothing else, so a project cannot use it to turn
    /// on any other converter behavior.
    /// </summary>
    public static (string Options, string? Error) ConverterOptions(string projectDir)
    {
        string path = Path.Combine(projectDir, ConverterOptionsFile);

        if (!File.Exists(path))
            return ("", null);

        System.Text.StringBuilder options = new();

        foreach (string raw in File.ReadAllLines(path))
        {
            string line = raw.Trim();

            if (line.Length == 0)
                continue;

            if (!s_allowedConverterOption.IsMatch(line))
                return ("", $"{ConverterOptionsFile}: \"{line}\" is not an allowed converter option (only -warn=<code>[,<code>...])");

            options.Append(line).Append(' ');
        }

        return (options.ToString(), null);
    }

    /// <summary>Whether the project is an expected-output project (see <see cref="ExpectedOutputFile"/>).</summary>
    public static bool HasExpectedOutput(string projectDir) => File.Exists(Path.Combine(projectDir, ExpectedOutputFile));
}
