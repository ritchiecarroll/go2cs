using System;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Emit;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace go2cs.Tests;

/// <summary>
/// MethodLimitAnalyzer, GO2CS0012: a type that declares more methods than CoreCLR loads on it fails the build.
/// </summary>
/// <remarks>
/// <para>
/// RED before the analyzer existed: a package class of 116,102 methods built clean and threw TypeLoadException at its
/// first use.
/// </para>
/// <para>
/// The limit is the runtime's, so each edge is held to the runtime these tests run on: the fixture is emitted and
/// loaded, and the analyzer must accept exactly what loads. A static class or a struct loads with 65,521 methods and
/// fails with 65,522; a base type's new virtual methods come off that, and an override gives one back, up to 65,524
/// methods in all (MethodLimitAnalyzer has the measurements). A runtime that moves the limit turns these red, which is
/// the signal to measure again.
/// </para>
/// </remarks>
[TestClass]
public class MethodLimitAnalyzerTests
{
    // The most methods a static class, a struct, or a class deriving from Object can declare: MaxSlots less Object's four.
    private const int Most = MethodLimitAnalyzer.MaxSlots - 4;

    // The type go.big_package with the given number of static methods M0.., the second half in a part marked as
    // generated, after any other members and beside any other types of the namespace.
    // Each method is `public static void M<i>() { }` unless methodTail gives what follows the name (an interface's
    // `();`), with methodHead before it.
    private static CSharpCompilation Fixture(int methods, string extraMembers = "", string kind = "static partial class", string baseList = "", string otherTypes = "",
        string methodHead = "    public static void M", string methodTail = "() { }\n")
    {
        string Part(string kind, string baseList, int from, int to, string extra)
        {
            StringBuilder source = new();

            source.Append("namespace go;\n").Append(kind).Append(" big_package").Append(baseList).Append("\n{\n").Append(extra);

            for (int i = from; i < to; i++)
                source.Append(methodHead).Append(i).Append(methodTail);

            return source.Append("}\n").ToString();
        }

        CSharpParseOptions options = new(LanguageVersion.Latest);
        string coreDir = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        CSharpCompilation compilation = CSharpCompilation.Create("limit",
            [
                CSharpSyntaxTree.ParseText(Part(kind, baseList, 0, methods / 2, extraMembers) + otherTypes, options, path: "big.cs"),
                CSharpSyntaxTree.ParseText("// <auto-generated/>\n" + Part(kind, "", methods / 2, methods, ""), options, path: "big.g.cs")
            ],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location), MetadataReference.CreateFromFile(Path.Combine(coreDir, "System.Runtime.dll"))],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        Assert.AreEqual(0, compilation.GetDeclarationDiagnostics().Count(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error), "the fixture declares clean");

        return compilation;
    }

    private static ImmutableArray<Diagnostic> Analyze(CSharpCompilation compilation) =>
        compilation.WithAnalyzers([new MethodLimitAnalyzer()]).GetAnalyzerDiagnosticsAsync().GetAwaiter().GetResult();

    private static ImmutableArray<Diagnostic> Analyze(int methods, string extraMembers = "", string kind = "static partial class") =>
        Analyze(Fixture(methods, extraMembers, kind));

    // Whether the runtime loads go.big_package: the fixture is emitted, loaded from a stream, and its methods read.
    private static bool Loads(CSharpCompilation compilation)
    {
        using MemoryStream image = new();
        EmitResult emitted = compilation.Emit(image);
        Assert.IsTrue(emitted.Success, "the fixture emits: the compiler has no method limit: " + string.Join("; ", emitted.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Take(3)));
        image.Position = 0;

        AssemblyLoadContext context = new("method-limit", isCollectible: true);

        try
        {
            Type type = context.LoadFromStream(image).GetType("go.big_package", throwOnError: true)!;
            return type.GetMethods(BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static | BindingFlags.Instance | BindingFlags.DeclaredOnly).Length > 0;
        }
        catch (TypeLoadException)
        {
            return false;
        }
        finally
        {
            context.Unload();
        }
    }

    // The analyzer accepts the fixture exactly when the runtime loads it.
    private static void AssertEdge(CSharpCompilation compilation, bool loads, string what)
    {
        Assert.AreEqual(loads, Loads(compilation), what + ": the runtime");
        Assert.AreEqual(loads ? 0 : 1, Analyze(compilation).Length, what + ": the analyzer");
    }

    [TestMethod]
    public void TheRuntimeLoadsAStaticClassAtTheLimitAndTheAnalyzerAcceptsIt()
    {
        Assert.AreEqual(65_521, Most);
        AssertEdge(Fixture(Most), loads: true, "65,521 methods");
    }

    [TestMethod]
    public void TheRuntimeRefusesAStaticClassOneOverAndSoDoesTheAnalyzerGeneratedPartsCounted()
    {
        CSharpCompilation compilation = Fixture(Most + 1);

        Assert.IsFalse(Loads(compilation), "65,522 methods: TypeLoadException");

        ImmutableArray<Diagnostic> diagnostics = Analyze(compilation);

        Assert.AreEqual(1, diagnostics.Length, string.Join("; ", diagnostics));
        Assert.AreEqual("GO2CS0012", diagnostics[0].Id);
        Assert.AreEqual(DiagnosticSeverity.Error, diagnostics[0].Severity);
        StringAssert.Contains(diagnostics[0].GetMessage(), "'go.big_package' declares 65522 methods");
        StringAssert.Contains(diagnostics[0].GetMessage(), "at most 65521");
    }

    // The converted repro's two readings (N methods on a base embedded by M structs: 2NM + 2N + 5 in the package
    // class): 65,505 loaded and 65,523 threw TypeLoadException.
    [TestMethod]
    public void TheReprosTwoReadingsFallOnEitherSideOfTheEdge()
    {
        AssertEdge(Fixture(65_505), loads: true, "N=250, M=130");
        AssertEdge(Fixture(65_523), loads: false, "N=697, M=46");
    }

    // Object's four virtual slots are a struct's too.
    [TestMethod]
    public void AStructHasTheSameLimitItsImplicitConstructorNotCounted()
    {
        AssertEdge(Fixture(Most, kind: "partial struct"), loads: true, "a struct at the limit");
        AssertEdge(Fixture(Most + 1, kind: "partial struct"), loads: false, "a struct one over");
    }

    // Each new virtual method of a base type is a slot the class inherits, and an override takes none of its own.
    [TestMethod]
    public void ABaseTypesVirtualMethodsComeOffTheLimitAndAnOverrideTakesNoSlot()
    {
        const string Bases = "public class Deeper { public virtual void V1() { } public virtual void V2() { } }\npublic abstract class Abstract : Deeper { public abstract void V3(); }\n";
        const string Override = "    public override void V3() { }\n";

        // Seven inherited slots: Object's four and V1 to V3. The class declares its M methods, a constructor and the
        // override, which reuses V3's slot, so it needs M + 1 new ones.
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxSlots - 7 - 1, Override, "partial class", " : Abstract", Bases), loads: true, "65,517 static methods under three inherited virtual methods");
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxSlots - 7, Override, "partial class", " : Abstract", Bases), loads: false, "65,518 static methods under three inherited virtual methods");
    }

    // The second limit: 65,524 methods, however few slots they need. A class that overrides all four of Object's
    // virtual methods would have a slot to spare at 65,525 methods, and does not load with them.
    [TestMethod]
    public void AClassThatOverridesEveryInheritedMethodStopsAtTheLimitOnMethodsItself()
    {
        const string Overrides = "    public override string ToString() => \"\";\n    public override bool Equals(object other) => false;\n" +
                                 "    public override int GetHashCode() => 0;\n    ~big_package() { }\n";

        Assert.AreEqual(65_524, MethodLimitAnalyzer.MaxMethods);

        // The M methods, the four overrides and the constructor.
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxMethods - 5, Overrides, "partial class"), loads: true, "65,524 methods, four of them overrides");
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxMethods - 4, Overrides, "partial class"), loads: false, "65,525 methods, four of them overrides");
    }

    // An interface inherits no slot, so the limit on methods is the one that binds.
    [TestMethod]
    public void AnInterfaceStopsAtTheLimitOnMethodsItself()
    {
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxMethods, kind: "partial interface", methodHead: "    void M", methodTail: "();\n"), loads: true, "an interface of 65,524 methods");
        AssertEdge(Fixture(MethodLimitAnalyzer.MaxMethods + 1, kind: "partial interface", methodHead: "    void M", methodTail: "();\n"), loads: false, "an interface of 65,525 methods");
    }

    // A partial method nobody implements has no row in metadata, so it is not a method the runtime counts.
    [TestMethod]
    public void APartialMethodWithNoImplementationIsNotCounted()
    {
        Assert.AreEqual(0, Analyze(Most, "    static partial void P1();\n    static partial void P2();\n").Length);
    }

    // An implemented partial method is one method, not two.
    [TestMethod]
    public void AnImplementedPartialMethodIsCountedOnce()
    {
        const string Implemented = "    static partial void P1();\n    static partial void P1() { }\n";

        Assert.AreEqual(0, Analyze(Most - 1, Implemented).Length);
        Assert.AreEqual(1, Analyze(Most, Implemented).Length);
    }
}
