using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using go;

namespace GolibTests;

/// <summary>
/// Holds the converter's list of the names golib declares in namespace <c>go</c>
/// (<c>src/go2cs/golibNamespaceNames.go</c>) to golib's own assembly, and writes the list.
/// </summary>
/// <remarks>
/// <para>
/// A converted file of a package in namespace <c>go</c> reads the namespace's own types and child namespaces
/// before the names its usings bring. Inside a method holder the package's members arrive through
/// <c>using static</c>, so a package-level name that one of golib's types of namespace <c>go</c> also has is
/// golib's there, and the converter writes it through the package class. The converter decides that per use,
/// from this list; it cannot ask the compiler.
/// </para>
/// <para>
/// The list is generated: this test renders the file from the assembly it runs against and compares it with
/// the file in the tree, byte for byte after line endings. On a difference it writes the rendered file beside
/// the test's own output and names the path; copy it over <c>src/go2cs/golibNamespaceNames.go</c>. golib
/// declares the same types for every target, so one run renders the file for all of them.
/// </para>
/// </remarks>
[TestClass]
public class GolibNamespaceNamesTests
{
    private const string FileName = "golibNamespaceNames.go";

    private static string SrcRoot([CallerFilePath] string thisFile = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(thisFile)!, "..", ".."));

    // A top-level type of namespace `go` that C# source can name: the compiler's own types (closures, file-local
    // types, private implementation details) carry a character no identifier has.
    private static bool IsNameable(Type type) =>
        type is { IsNested: false, Namespace: "go" } && type.Name.IndexOfAny(['<', '>', '$']) < 0;

    private static string NameOf(Type type) =>
        type.Name.IndexOf('`') is var tick and >= 0 ? type.Name[..tick] : type.Name;

    internal static string Render(Assembly golib)
    {
        Type[] types = [.. golib.GetTypes().Where(IsNameable)];

        string[] plain = Names(types.Where(type => type is { IsPublic: true, IsGenericTypeDefinition: false }));
        string[] friend = Names(types.Where(type => type is { IsPublic: false, IsGenericTypeDefinition: false }));

        // A name golib declares only with type parameters hides no member, and still is no name for an alias.
        string[] generic = [.. Names(types.Where(type => type.IsGenericTypeDefinition)).Except(plain).Except(friend)];

        string[] children = [.. golib.GetTypes()
            .Select(type => type.Namespace)
            .Where(space => space is not null && space.StartsWith("go.", StringComparison.Ordinal))
            .Select(space => space!.Split('.')[1])
            .Distinct()
            .Order(StringComparer.Ordinal)];

        string[] friends = [.. golib.GetCustomAttributes<InternalsVisibleToAttribute>()
            .Select(grant => grant.AssemblyName.Split(',')[0].Trim())
            .Distinct()
            .Order(StringComparer.Ordinal)];

        StringBuilder file = new();

        file.Append(
            """
            // golibNamespaceNames.go - Gbtc
            // Copyright © 2026 The go2cs Authors. All rights reserved.
            //
            // SPDX-License-Identifier: AGPL-3.0-only
            // Use of this source code is governed by the GNU Affero General Public License
            // version 3 only, which can be found in the LICENSE file.
            // Additional permission for emitted output: see LICENSE-EXCEPTION (AGPL section 7).

            // Code generated by GolibTests' GolibNamespaceNamesTests from golib's assembly; DO NOT EDIT.

            // The names golib declares in namespace `go`. A converted file of a package in that namespace reads
            // them before the names its own usings bring, so inside a method holder, where the package's members
            // arrive through `using static`, a package-level name on one of these lists is golib's
            // (methodHolder.go). To change a list, change golib and run that test: it renders this file from the
            // assembly and names where it wrote it.

            package main

            // golibNamespaceTypes holds golib's public types of namespace `go` that take no type parameter.
            var golibNamespaceTypes = nameSet(

            """);

        AppendNames(file, plain);

        file.Append(
            """
            )

            // golibFriendNamespaceTypes holds golib's internal types of namespace `go` that take no type
            // parameter. An assembly golib names in InternalsVisibleTo reads them as it reads the public ones.
            var golibFriendNamespaceTypes = nameSet(

            """);

        AppendNames(file, friend);

        file.Append(
            """
            )

            // golibFriendAssemblies holds the assemblies golib names in InternalsVisibleTo.
            var golibFriendAssemblies = nameSet(

            """);

        AppendNames(file, friends);

        file.Append(
            """
            )

            // golibGenericNamespaceTypes holds the names golib declares in namespace `go` only with type
            // parameters. Such a type hides no member of a package, and its name is still no name for an alias.
            var golibGenericNamespaceTypes = nameSet(

            """);

        AppendNames(file, generic);

        file.Append(
            """
            )

            // golibChildNamespaces holds the namespaces golib declares directly below `go`.
            var golibChildNamespaces = nameSet(

            """);

        AppendNames(file, children);
        file.Append(")\n");

        return file.ToString().Replace("\r\n", "\n");

        static string[] Names(IEnumerable<Type> types) => [.. types.Select(NameOf).Distinct().Order(StringComparer.Ordinal)];

        static void AppendNames(StringBuilder file, string[] names)
        {
            foreach (string name in names)
                file.Append("\t\"").Append(name).Append("\",\n");
        }
    }

    [TestMethod]
    public void TheConvertersListIsGolibsNamespace()
    {
        string path = Path.Combine(SrcRoot(), "go2cs", FileName);

        if (!File.Exists(path))
            Assert.Inconclusive($"{path} is not beside this test's source: the list is guarded where the source tree is.");

        string rendered = Render(typeof(builtin).Assembly);
        string committed = File.ReadAllText(path).Replace("\r\n", "\n");

        if (rendered == committed)
            return;

        string written = Path.Combine(AppContext.BaseDirectory, FileName);
        File.WriteAllText(written, rendered, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

        string[] now = rendered.Split('\n');
        string[] was = committed.Split('\n');

        Assert.Fail($"src/go2cs/{FileName} is not golib's namespace: {now.Except(was).Count()} line(s) to add " +
                    $"({string.Join(" ", now.Except(was).Take(8).Select(line => line.Trim()))}), {was.Except(now).Count()} to remove " +
                    $"({string.Join(" ", was.Except(now).Take(8).Select(line => line.Trim()))}). The rendered file is {written}; copy it over the committed one.");
    }

    // The render reads what the converter's three questions need; each is pinned on one name golib is certain to
    // keep, so a render that loses a list fails here and not as a missing qualification in converted code.
    [TestMethod]
    public void TheRenderNamesWhatGolibDeclares()
    {
        string rendered = Render(typeof(builtin).Assembly);

        string section(string variable)
        {
            int start = rendered.IndexOf($"var {variable} = nameSet(", StringComparison.Ordinal);
            Assert.IsTrue(start >= 0, $"the render declares {variable}");

            return rendered[start..(rendered.IndexOf("\n)", start, StringComparison.Ordinal) + 1)];
        }

        StringAssert.Contains(section("golibNamespaceTypes"), "\t\"builtin\",\n", "a public class without type parameters");
        StringAssert.Contains(section("golibGenericNamespaceTypes"), "\t\"slice\",\n", "slice<T> is declared only with a type parameter");
        Assert.IsFalse(section("golibNamespaceTypes").Contains("\t\"slice\",\n", StringComparison.Ordinal), "and so is on no list of plain types");
        StringAssert.Contains(section("golibChildNamespaces"), "\t\"golib\",\n", "namespace go.golib");
        StringAssert.Contains(section("golibFriendAssemblies"), "\t\"go.runtime\",\n", "golib grants package runtime's assembly its internals");
        Assert.IsFalse(rendered.Contains('<'), "no compiler-generated type is named");
    }
}
