    private static void RequireAes()
    {
        if (!(X86.Aes.IsSupported && X86.Ssse3.IsSupported && X86.Sse41.IsSupported))
            Assert.Inconclusive("the host has no AES/SSSE3/SSE4.1: Go selects the fallback here too");
    }

    [TestMethod]
    public void AesHashMatchesGoAcrossEverySizeClass()
    {
        RequireAes();
        byte[] schedule = Schedule(), data = Data();

        foreach ((ulong seed, int n, ulong hash) in s_goMemhash)
            Assert.AreEqual(hash, GoAeshash(data.AsSpan(0, n), seed, schedule), $"memhash seed {seed} length {n}");
    }

    [TestMethod]
    public void AesHash32And64MatchGo()
    {
        RequireAes();
        byte[] schedule = Schedule(), data = Data();

        foreach ((ulong seed, int offset, ulong hash) in s_goMemhash32)
            Assert.AreEqual(hash, GoAeshash32(BitConverter.ToUInt32(data, offset), seed, schedule), $"memhash32 seed {seed} offset {offset}");

        foreach ((ulong seed, int offset, ulong hash) in s_goMemhash64)
            Assert.AreEqual(hash, GoAeshash64(BitConverter.ToUInt64(data, offset), seed, schedule), $"memhash64 seed {seed} offset {offset}");
    }

    [TestMethod]
    public void AesStrhashIsAeshashOverTheContent()
    {
        RequireAes();
        byte[] schedule = Schedule();

        foreach ((ulong seed, int length, ulong hash) in s_goStrhash)
        {
            byte[] content = Encoding.Latin1.GetBytes(s_strings.Single(s => s.Length == length));
            Assert.AreEqual(hash, GoAeshash(content, seed, schedule), $"strhash seed {seed} length {length}");
        }
    }

    [TestMethod]
    public void AlginitSelectsAesOnGosCondition()
    {
        // No GODEBUG cpu.* option is set in the test host, so the flags are the hardware's
        bool expected = X86.Aes.IsSupported && X86.Ssse3.IsSupported && X86.Sse41.IsSupported;
        Assert.AreEqual(expected, GoUsesAeshash, "useAeshash follows (GOARCH amd64) && HasAES && HasSSSE3 && HasSSE41");
    }

    [TestMethod]
    public void AZeroSizeHashReadsNothing()
    {
        // TestMemHashGlobalSeed's computeHash: MemHash(unsafe.Pointer(&v), 0, 0) for v struct{}; Go
        // never dereferences for a zero size, so the referent's shape does not matter
        ref (int, string) v = ref heap((0, ""), out ж<(int, string)> Ꮡv);
        @unsafe.Pointer p = @unsafe.Pointer.FromBox(Ꮡv);
        Assert.AreEqual(GoMemhash(ReadOnlySpan<byte>.Empty, 0), GoMemhashPointer(p, 0, 0), "fallback over zero bytes");
    }
